def shake_offset(f, s):
    amp = SHAKE.get(s['name'], 0.0)
    if amp <= 0:
        return Vector((0, 0, 0))
    t = tsec(f)
    return Vector((math.sin(t * 7.0), math.sin(t * 5.3 + 1), math.sin(t * 4.1 + 2))) * amp


