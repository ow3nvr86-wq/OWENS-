def bay_prism(bm, W0, W1, dep, z0, z1, mi):
    """Bay window volume: back width W1 at y=0, front width W0 at y=-dep."""
    pts = [(-W1 / 2, 0), (-W0 / 2, -dep), (W0 / 2, -dep), (W1 / 2, 0)]
    vb = [bm.verts.new((x, y, z0)) for x, y in pts]
    vt = [bm.verts.new((x, y, z1)) for x, y in pts]
    for i in range(3):
        f = bm.faces.new((vb[i], vb[i + 1], vt[i + 1], vt[i]))
        f.material_index = mi
    f = bm.faces.new(list(reversed(vb)))
    f.material_index = 1
    f = bm.faces.new(vt)
    f.material_index = 1


def house_bm(v):
    """Late-Victorian / Edwardian row house: facade faces -y (the street) at y = 0, body runs to +y."""
    rng = random.Random(v)
    n = 2 + (v % 2)
    W, D, FH, G = 7.4, 16.0, 3.3, 1.4
    H = G + n * FH
    bm = bmesh.new()
    add_box(bm, -W / 2, 0, -9, W / 2, D, H, mi=0)
    for f in bm.faces:
        if f.normal.z > 0.9:
            f.material_index = 3
    add_box(bm, -W / 2 - 0.05, -0.5, H, W / 2 + 0.05, 0.2, H + 0.35, mi=1)        # cornice
    add_box(bm, -W / 2, -0.2, H + 0.35, W / 2, 0.15, H + 0.9 + 0.3 * (v % 3), mi=0)   # parapet
    add_box(bm, -W / 2 - 0.02, -0.12, G - 0.15, W / 2 + 0.02, 0.0, G, mi=1)         # belt course
    # bay window over the upper floors (left part of the facade)
    bx = -W / 2 + 2.4 if v % 3 else 0.0
    bm2 = bmesh.new()
    for k in range(n):
        z0 = G + k * FH
        bay_prism(bm2, 1.9, 3.3, 0.85, z0, z0 + 0.75, 1)
        bay_prism(bm2, 1.9, 3.3, 0.85, z0 + 0.75, z0 + 2.75, 2)
        bay_prism(bm2, 1.9, 3.3, 0.85, z0 + 2.75, z0 + FH, 1)
    bmesh.ops.translate(bm2, verts=bm2.verts, vec=(bx, 0, 0))
    me = bpy.data.meshes.new('tmp')
    bm2.to_mesh(me)
    bm2.free()
    bm.from_mesh(me)
    bpy.data.meshes.remove(me)
    # flat windows on the other side of the facade, with trim
    wx = W / 2 - 1.3 if v % 3 else -W / 2 + 1.2
    for k in range(n):
        z0 = G + k * FH + 0.75
        add_box(bm, wx - 0.62, -0.1, z0 - 0.12, wx + 0.62, 0.0, z0 + 2.12, mi=1)
        add_box(bm, wx - 0.5, -0.14, z0, wx + 0.5, -0.05, z0 + 2.0, mi=2)
        if v % 3 == 0:
            add_box(bm, -wx - 0.62, -0.1, z0 - 0.12, -wx + 0.62, 0.0, z0 + 2.12, mi=1)
            add_box(bm, -wx - 0.5, -0.14, z0, -wx + 0.5, -0.05, z0 + 2.0, mi=2)
    # ground floor: entry door with a stoop, garage door
    dx = W / 2 - 1.3 if v % 3 else W / 2 - 1.0
    add_box(bm, dx - 0.55, -0.12, G, dx + 0.55, -0.02, G + 2.3, mi=4)
    for s in range(5):
        add_box(bm, dx - 0.75, -0.25 - s * 0.28, 0.0, dx + 0.75, -0.25 - (s - 1) * 0.28, G - s * 0.28, mi=5)
    add_box(bm, -W / 2 + 0.6, -0.08, 0.0, -W / 2 + 3.2, -0.01, 2.3, mi=4 if rng.random() < 0.6 else 1)
    add_box(bm, -W / 2 + 3.6, -0.08, 0.5, -W / 2 + 4.6, -0.01, 1.3, mi=2)
    return bm


