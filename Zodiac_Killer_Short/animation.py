    a, b = EV['letter_slide']
    _place(sfx, _paper(b - a + 0.2, 70), a, 0.45, pan=-0.2)
    cue(a, 'A letter slides across the desk (paper on wood)', 'sfx')
    a, b = EV['sheets_merge']
    for k in range(3):
        _place(sfx, _paper(0.7, 71 + k), a + 0.15 * k, 0.3, pan=-0.3 + 0.3 * k)
    cue(a, 'Three sheets of paper slide together', 'sfx')
    _place(sfx, _stamp(), EV['stamp'][0], 0.7)
    cue(EV['stamp'][0], 'Rubber stamp thump: NO NAME', 'sfx')
    # the cipher tiles: soft clicks as they land, a ripple of flips at the decode
    g0, g1 = EV['grid_form']
    for k in range(40):
        _place(sfx, _click(), g0 + 0.3 + rng.uniform(0, g1 - g0), 0.06, pan=rng.uniform(-0.6, 0.6))
    for k in range(60):
        _place(sfx, _click(), d0 + k / 60 * 1.6 + rng.uniform(0, 0.05), 0.08, pan=-0.6 + 1.2 * k / 60)
    cue(g0, 'Soft paper clicks as the cipher tiles land; a rippling run of flips at the decode', 'sfx')
    # lights going out
    la = EV['lights_out'][0]
    for tm, g in ((la, 0.25), (la + 2.3 + 0.75, 0.4), (la + 3.4, 0.2)):
        _place(sfx, _click(), tm, g)
    n = int(0.8 * SR)
    tt = np.arange(n) / SR
    buzz = np.sign(np.sin(2 * np.pi * 120 * tt)) * _norm(_noise(n, 90)) ** 2 * np.minimum((0.8 - tt) / 0.2, 1)
    _place(sfx, _norm(_bandpass(buzz, 100, 4000)), la + 2.3, 0.1)
    cue(la, 'The lights go out one by one: switch clicks, the desk lamp buzzes and dies', 'sfx')

    # --- mix ---------------------------------------------------------------------------------------
    vo = np.zeros(N)
    vpath = os.path.join(ROOT, 'audio', 'narration.wav')
    if os.path.exists(vpath):
        with wave.open(vpath) as w:
            a_ = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768
        vo[:min(N, len(a_))] = a_[:N]
    env = np.abs(vo)
    k = int(0.03 * SR)
    env = np.convolve(env, np.ones(k) / k, mode='same')
    env = np.clip(env / (env.max() + 1e-9) * 4, 0, 1)
    rel_k = int(0.3 * SR)
    env = np.maximum.reduce([np.roll(env, j) for j in range(0, rel_k, rel_k // 12)])
    duck_m = 1 - 0.6 * env
    duck_a = 1 - 0.55 * env
    bed = music + amb + sfx
    vo_gain = 2.2 * np.abs(bed).max() / (np.abs(vo).max() + 1e-9)
    with_voice = 0.38 * music * duck_m + 0.38 * amb * duck_a + 0.45 * sfx * duck_a + np.stack([vo, vo]) * vo_gain * 0.38
    no_voice = bed
    end_fade = np.clip((DURATION - t) / 0.2, 0, 1)
    os.makedirs(os.path.join(ROOT, 'audio'), exist_ok=True)
    outs = {}
    for name, mix in (('mix_with_voice', with_voice), ('mix_no_voice', no_voice), ('music_sfx_stem', bed)):
        mix = mix * end_fade
        mix = np.tanh(mix / (np.abs(mix).max() + 1e-9) * 1.3) * 0.89
        p = os.path.join(ROOT, 'audio', name + '.wav')
        with wave.open(p, 'wb') as w:
            w.setnchannels(2)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((np.clip(mix.T, -1, 1) * 32767).astype(np.int16).tobytes())
        outs[name] = p
    for name in ('mix_with_voice', 'mix_no_voice'):
        p = outs[name]
        tmp = p.replace('.wav', '_ln.wav')
        try:
            subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', p, '-af', 'loudnorm=I=-14:TP=-1.5:LRA=11',
                            '-ar', str(SR), tmp], check=True)
            os.replace(tmp, p)
        except (OSError, subprocess.CalledProcessError) as e:
            print('loudnorm skipped:', e)
    write_sound_effects_md(cues)
    print('audio written:', ', '.join(outs))


