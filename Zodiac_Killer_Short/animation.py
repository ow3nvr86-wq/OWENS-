def simple_mat(name, color, rough=0.7, noise_amt=0.15, noise_scale=8.0, metal=0.0, coat=0.0,
               emission=None, estr=0.0):
    m, nt, out = new_mat(name)
    n = noise(nt, noise_scale, 3.0, 0.55, vec=obj_coord(nt))
    base = mixc(nt, mth(nt, 'MULTIPLY', n, noise_amt), rgba(color), rgba([c * 0.55 for c in color]))
    p = principled(nt, out, **{'Base Color': base, 'Roughness': rough, 'Metallic': metal, 'Coat Weight': coat})
    if emission is not None:
        p.inputs['Emission Color'].default_value = rgba(emission)
        p.inputs['Emission Strength'].default_value = estr
    MAT[name] = m
    return m


def emission_mat(name, color, strength):
    m, nt, out = new_mat(name)
    e = nd(nt, 'ShaderNodeEmission', Color=rgba(color), Strength=strength)
    nt.links.new(e.outputs[0], out.inputs['Surface'])
    MAT[name] = m
    return m


def billboard_base(name):
    m, nt, out = new_mat(name)
    uv = nd(nt, 'ShaderNodeUVMap').outputs[0]
    sm = nd(nt, 'ShaderNodeVertexColor', p_layer_name='sm')
    scn = nd(nt, 'ShaderNodeSeparateColor', Color=sm.outputs['Color'])
    su = sep(nt, uv)
    du = mth(nt, 'SUBTRACT', su.outputs['X'], 0.5)
    dv = mth(nt, 'SUBTRACT', su.outputs['Y'], 0.5)
    r2 = mth(nt, 'MULTIPLY', mth(nt, 'ADD', mth(nt, 'MULTIPLY', du, du), mth(nt, 'MULTIPLY', dv, dv)), 4.0)
    return m, nt, out, su, scn, sm.outputs['Alpha'], r2


def particle_materials():
    # mist / spray / steam: soft unlit billboard puffs; colour attribute 'sm' = (seed, age, glow, opacity)
    for name, col0, col1 in (('mist', (0.50, 0.53, 0.56), (0.30, 0.33, 0.37)),
                             ('gaswisp', (0.55, 0.66, 0.78), (0.38, 0.46, 0.58))):
        m, nt, out, su, scn, opac, r2 = billboard_base(name)
        seed, age = scn.outputs[0], scn.outputs[1]
        fall = mth(nt, 'POWER', mth(nt, 'SUBTRACT', 1.0, r2, clamp=True), 1.6)
        v = comb(nt, mth(nt, 'MULTIPLY_ADD', su.outputs['X'], 1.6, mth(nt, 'MULTIPLY', seed, 37.0)),
                 mth(nt, 'MULTIPLY_ADD', su.outputs['Y'], 1.6, mth(nt, 'MULTIPLY', seed, 11.0)),
                 mth(nt, 'MULTIPLY', age, 1.6))
        n = noise(nt, 2.0, 5.0, 0.6, vec=v)
        dens = mth(nt, 'MULTIPLY', fall, mth(nt, 'MULTIPLY_ADD', n, 2.2, -0.75, clamp=True))
        dens = mth(nt, 'MULTIPLY', dens, opac, clamp=True)
        col = mixc(nt, mth(nt, 'MULTIPLY', n, 0.6), col0 + (1,), col1 + (1,))
        lum = value(nt, 'mist_lum', 0.3)
        shadeuv = mth(nt, 'MULTIPLY_ADD', su.outputs['Y'], 0.5, 0.75)
        k = mth(nt, 'MULTIPLY', lum, shadeuv)
        lit = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='MULTIPLY', Factor=1.0)
        nt.links.new(col, lit.inputs[6])
        nt.links.new(comb(nt, k, k, k), lit.inputs[7])
        em = nd(nt, 'ShaderNodeEmission', Color=lit.outputs[2], Strength=1.0)
        tr = nd(nt, 'ShaderNodeBsdfTransparent')
        mx = nd(nt, 'ShaderNodeMixShader', Fac=dens)
        nt.links.new(tr.outputs[0], mx.inputs[1])
        nt.links.new(em.outputs[0], mx.inputs[2])
        nt.links.new(mx.outputs[0], out.inputs['Surface'])
        MAT[name] = m
        register_value(m, 'mist_lum', 'mist_lum')
    # CO2 visualisation dots: tiny soft glowing specks (a diagram, not literal glowing gas)
    m, nt, out, su, scn, opac, r2 = billboard_base('dot')
    dens = mth(nt, 'POWER', mth(nt, 'SUBTRACT', 1.0, r2, clamp=True), 3.0)
    a = mth(nt, 'MULTIPLY', dens, opac, clamp=True)
    col = mixc(nt, scn.outputs[2], (1.0, 0.84, 0.62, 1), (1.0, 0.94, 0.82, 1))       # warm dust / glints
    em = nd(nt, 'ShaderNodeEmission', Color=col, Strength=mth(nt, 'MULTIPLY', a, value(nt, 'dot_lum', 6.0)))
    tr = nd(nt, 'ShaderNodeBsdfTransparent')
    mx = nd(nt, 'ShaderNodeMixShader', Fac=mth(nt, 'MULTIPLY', a, 1.4, clamp=True))
    nt.links.new(tr.outputs[0], mx.inputs[1])
    nt.links.new(em.outputs[0], mx.inputs[2])
    nt.links.new(mx.outputs[0], out.inputs['Surface'])
    MAT['dot'] = m
    register_value(m, 'dot_lum', 'dot_lum')



