    uv = np.zeros((n, 8, 2))
    for i in range(n):
        u0, u1, v0, v1 = atlas_uv(int(glyph[i]))
        uv[i, :4] = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
        u0, u1, v0, v1 = atlas_uv(int(letter[i]))
        uv[i, 4:] = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
    ul = ob.data.uv_layers.new(name='UVMap')
