def atlas_uv(i):
    c, r = i % 12, i // 12
    return c / 12, (c + 1) / 12, 1 - (r + 1) / 8, 1 - r / 8


def build_tiles():
    n = 340
    rng = np.random.default_rng(340)
    glyph = rng.integers(0, 63, n)
    letter = np.full(n, 89)
    for r, line in enumerate(PLAIN_ROWS):
        c0 = (17 - len(line)) // 2
        for k, ch in enumerate(line):
            if ch != ' ':
                letter[r * 17 + c0 + k] = 63 + ord(ch) - 65
    rest = [63 + ord(ch) - 65 for ch in PLAIN_REST]
    for i in range(4 * 17, n):
        j = i - 4 * 17
        letter[i] = rest[j] if j < len(rest) else 89
    h, e = 0.46, 0.006
    front = np.array([(-h, -e, -h), (h, -e, -h), (h, -e, h), (-h, -e, h)])
    back = np.array([(h, e, -h), (-h, e, -h), (-h, e, h), (h, e, h)])
