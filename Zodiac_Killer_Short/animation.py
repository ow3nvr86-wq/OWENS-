def rotm(a):
    """(n, 3) Euler XYZ -> (n, 3, 3)."""
    cx, sx = np.cos(a[:, 0]), np.sin(a[:, 0])
    cy, sy = np.cos(a[:, 1]), np.sin(a[:, 1])
    cz, sz = np.cos(a[:, 2]), np.sin(a[:, 2])
    one, zero = np.ones_like(cx), np.zeros_like(cx)
    Rx = np.stack([one, zero, zero, zero, cx, -sx, zero, sx, cx], -1).reshape(-1, 3, 3)
    Ry = np.stack([cy, zero, sy, zero, one, zero, -sy, zero, cy], -1).reshape(-1, 3, 3)
    Rz = np.stack([cz, -sz, zero, sz, cz, zero, zero, zero, one], -1).reshape(-1, 3, 3)
    return Rz @ Ry @ Rx


def update_tiles(t):
    T = TILES
    n = 340
    g0, g1 = EV['grid_form']
    y0, y1 = EV['years']
    d0, d1 = EV['decode340']
    u = np.clip((t - g0 - T['delay']) / 1.3, 0, 1)
    u = u * u * (3 - 2 * u)
    home = T['home'].copy()
    # the codebreakers' re-orderings: the columns slide into new orders and back
    cols = T['cols']
    xs = cols.astype(float)
    for k, tk in enumerate((y0 + 0.3, y0 + 1.3, y0 + 2.3)):
        w = ramp(t, tk, tk + 0.35) * (1 - ramp(t, tk + 0.75, tk + 1.0))
        if w > 0:
            xs = xs * (1 - w) + T['perms'][k][cols] * w
    home[:, 0] = VX + (xs - 8)
    pos = T['start'] * (1 - u[:, None]) + home * u[:, None]
    rot = T['rot0'] * (1 - u[:, None])
    # the decode: a diagonal wave flips every tile to its letter
    fl = np.clip((t - (d0 + T['diag'] * 1.5)) / 0.35, 0, 1)
    fl = fl * fl * (3 - 2 * fl)
    rot[:, 2] += math.pi * fl
    pos[:, 1] -= 0.35 * np.sin(math.pi * fl)
    # a slow breathing drift
    pos[:, 1] += 0.15 * np.sin(t * 0.8 + T['delay'] * 9)
    M = rotm(rot)
    V = pos[:, None, :] + np.einsum('nij,kj->nki', M, T['local'])
    me = T['ob'].data
    me.vertices.foreach_set('co', V.astype(np.float32).ravel())
    # brightness: the first sentence stays bright, the rest dims after decoding; a highlight sweeps with the flip
    top = T['rows'] < 4
    bright = np.where(top, 1.0, 1.0 - 0.72 * fl)
    hl = np.exp(-((fl - 0.5) / 0.25) ** 2) * 0.8 + np.where(top, fl * 0.12, 0.0)
    C = np.zeros((n, 8, 4))
    C[..., 0] = bright[:, None]
    C[..., 1] = hl[:, None]
    C[..., 3] = 1
    me.color_attributes['tc'].data.foreach_set('color', C.astype(np.float32).ravel())
    me.update()


