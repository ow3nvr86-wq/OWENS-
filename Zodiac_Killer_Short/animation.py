def basis_matrix(o, r, u):
    o, r, u = Vector(o), Vector(r).normalized(), Vector(u).normalized()
    n = r.cross(u).normalized()
    return Matrix(((r.x, u.x, n.x, o.x), (r.y, u.y, n.y, o.y), (r.z, u.z, n.z, o.z), (0, 0, 0, 1)))


def sheet(name, tex, w, h, o, r=(1, 0, 0), u=(0, 1, 0), spin=0.0, collection='Room', curl=0.0, alpha=False, seg=1):
    """A flat (optionally curled) sheet of paper of w x h metres, texture upright along u, facing r x u."""
    nx, ny = (8, 8) if curl else (seg, seg)
    xs, ys = np.linspace(-w / 2, w / 2, nx + 1), np.linspace(-h / 2, h / 2, ny + 1)
    X, Y = np.meshgrid(xs, ys)
    Z = curl * (((X / (w / 2)) ** 2) * 0.6 + ((Y / (h / 2)) ** 4) * 0.4) if curl else np.zeros_like(X)
    verts = np.stack([X, Y, Z], -1).reshape(-1, 3)
    ii = np.arange((nx + 1) * (ny + 1)).reshape(ny + 1, nx + 1)
    faces = np.stack([ii[:-1, :-1], ii[:-1, 1:], ii[1:, 1:], ii[1:, :-1]], -1).reshape(-1, 4)
    ob = mesh_obj(name, verts, faces, paper_mat(tex, alpha=alpha), collection=collection, smooth=True)
    uvl = ob.data.uv_layers.new(name='UVMap')
    uvs = np.stack([(X + w / 2) / w, (Y + h / 2) / h], -1).reshape(-1, 2)
    loops = np.zeros(len(ob.data.loops), np.int32)
    ob.data.loops.foreach_get('vertex_index', loops)
    uvl.data.foreach_set('uv', uvs[loops].astype(np.float32).ravel())
    rr, uu = Vector(r), Vector(u)
    n = rr.cross(uu)
    q = Matrix.Rotation(spin, 3, n)
    ob.matrix_world = basis_matrix(o, q @ rr, q @ uu)
    return ob


