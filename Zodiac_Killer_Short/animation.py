def hero_h(y):
    """The hero street (x = 0) climbs gently to the north."""
    return 3.0 + 0.05 * np.maximum(np.asarray(y, float) + 60.0, 0.0)


def height(x, y):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    h = 30.0 * (fbm(x / 650.0, y / 650.0, 4, seed=5) + 0.55) + 14.0 * fbm(x / 230.0, y / 230.0, 2, seed=9)
    h = np.maximum(h, 3.0)
    # the bay to the north and east, the ocean to the west; hills beyond the bay
    h -= 90.0 * (sstep(y, 2200, 2500) * (1 - sstep(y, 3600, 3900)) + sstep(x, 1550, 1800) * (1 - sstep(y, 3600, 3900)) * sstep(y, -900, -600)
                 + sstep(-x, 1550, 1850))
    h += 260.0 * sstep(y, 3700, 4600) * (0.6 + 0.5 * fbm(x / 900.0, y / 900.0, 3, seed=11))
    # flatten and smooth the hero street block (x within 70 m of 0, y from -150 to 300)
    d = np.maximum(np.abs(x) / 70.0, np.maximum((-150.0 - y) / 60.0, (y - 300.0) / 60.0))
    w = sstep(d, 0.6, 1.6)
    return h * w + hero_h(y) * (1 - w)


def gz(x, y):
    return float(height(x, y))


