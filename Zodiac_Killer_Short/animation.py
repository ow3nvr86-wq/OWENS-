def terrain_material():
    """Ground with the street grid drawn procedurally: wet asphalt, concrete sidewalks, yards."""
    m, nt, out = new_mat('terrain')
    oc = obj_coord(nt)
    s = sep(nt, oc)

    def dist(axis, pitch):
        a = mth(nt, 'FLOORED_MODULO', mth(nt, 'ADD', s.outputs[axis], pitch / 2), pitch)
        return mth(nt, 'ABSOLUTE', mth(nt, 'SUBTRACT', a, pitch / 2))
    dx, dy = dist('X', PX), dist('Y', PY)
    dmin = mth(nt, 'MINIMUM', dx, dy)
    road = mth(nt, 'LESS_THAN', dmin, ST)
    walk = mth(nt, 'LESS_THAN', dmin, ST + SW)
    n = noise(nt, 0.35, 3.0, 0.6, vec=oc)
    puddle = mth(nt, 'GREATER_THAN', noise(nt, 0.12, 2.0, 0.5, vec=oc), 0.56)
    yard = mixc(nt, n, (0.035, 0.040, 0.030, 1), (0.05, 0.05, 0.045, 1))
    walkc = mixc(nt, n, (0.16, 0.155, 0.15, 1), (0.10, 0.10, 0.10, 1))
    roadc = mixc(nt, n, (0.035, 0.035, 0.038, 1), (0.02, 0.02, 0.022, 1))
    c1 = mixc(nt, walk, yard, walkc)
    col = mixc(nt, road, c1, roadc)
    rough = mth(nt, 'SUBTRACT', 0.9, mth(nt, 'MULTIPLY', road, mth(nt, 'ADD', 0.45, mth(nt, 'MULTIPLY', puddle, 0.35))))
    principled(nt, out, **{'Base Color': col, 'Roughness': rough, 'Specular IOR Level': 0.5})
    MAT['terrain'] = m


