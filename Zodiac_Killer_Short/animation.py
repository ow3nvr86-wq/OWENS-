def torus(bm, R, r, nu=36, nv=10):
    verts = []
    for i in range(nu):
        a = i / nu * 2 * math.pi
        row = []
        for j in range(nv):
            b = j / nv * 2 * math.pi
            row.append(bm.verts.new(((R + r * math.cos(b)) * math.cos(a), (R + r * math.cos(b)) * math.sin(a), r * math.sin(b))))
        verts.append(row)
    for i in range(nu):
        for j in range(nv):
            bm.faces.new((verts[i][j], verts[(i + 1) % nu][j], verts[(i + 1) % nu][(j + 1) % nv], verts[i][(j + 1) % nv]))


