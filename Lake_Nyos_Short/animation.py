# Terrain: one rectilinear grid, fine (5 m) over the crater, the lake and the valley, coarse outside
# ============================================================================
def axis_coords(lo, hi, f0, f1, step, grow=1.09):
    fine = list(np.arange(f0, f1 + 1e-6, step))
    left, d, v = [], step, f0
    while v > lo:
        d *= grow
        v -= d
        left.append(max(v, lo))
    right, d, v = [], step, f1
    while v < hi:
        d *= grow
        v += d
        right.append(min(v, hi))
    return np.array(sorted(left) + fine + right)


def grid_mesh(name, xs, ys, zfun, mat, collection, drop=None, attrs=None):
    X, Y = np.meshgrid(xs, ys, indexing='xy')
    Z = zfun(X, Y)
    ny, nx = X.shape
    verts = np.stack([X, Y, Z], -1).reshape(-1, 3)
    ii = np.arange(nx * ny).reshape(ny, nx)
    q = np.stack([ii[:-1, :-1], ii[:-1, 1:], ii[1:, 1:], ii[1:, :-1]], -1).reshape(-1, 4)
    if drop is not None:
        c = verts[q].mean(1)
        q = q[~drop(c[:, 0], c[:, 1])]
    me = bpy.data.meshes.new(name)
    me.vertices.add(len(verts))
    me.vertices.foreach_set('co', verts.astype(np.float32).ravel())
    me.loops.add(q.size)
    me.loops.foreach_set('vertex_index', q.astype(np.int32).ravel())
    me.polygons.add(len(q))
    me.polygons.foreach_set('loop_start', (np.arange(len(q)) * 4).astype(np.int32))
    me.update()
    me.shade_smooth()
    if attrs:
        for an, arr in attrs.items():
            a = me.attributes.new(an, 'FLOAT', 'POINT')
            a.data.foreach_set('value', np.asarray(arr(X, Y), np.float32).ravel())
    ob = bpy.data.objects.new(name, me)
    if mat is not None:
        me.materials.append(mat)
    coll(collection).objects.link(ob)
    return ob


def build_terrain():
    xs = axis_coords(-9000, 9000, -1000.0, 1000.0, 5.0)
    ys = axis_coords(-9000, 11000, -1060.0, 2900.0, 5.0)
    ob = grid_mesh('Terrain', xs, ys, height, MAT['ground'], 'Terrain')
    print('terrain verts', len(ob.data.vertices))


