ERUPT_C = (-30.0, -60.0)          # where the overturn breaks the surface (illustrative)


def build_water():
    xs = np.arange(-720.0, 720.01, 6.0)
    ys = np.arange(-1010.0, 1010.01, 6.0)
    ob = grid_mesh('Water', xs, ys, lambda X, Y: np.zeros_like(X), MAT['water'], 'Water',
                   drop=lambda x, y: lake_polar(x, y)[0] > 1.07)
    ob.visible_shadow = False
    me = ob.data
    me.attributes.new('foam', 'FLOAT', 'POINT')
    co = np.zeros(len(me.vertices) * 3, np.float32)
    me.vertices.foreach_get('co', co)
    co = co.reshape(-1, 3)
    WATER.update(obj=ob, x=co[:, 0].astype(float), y=co[:, 1].astype(float))


def water_state(t, mode):
    """Height and foam of the lake surface at time t; mode: 'calm', 'erupt' or 'today'."""
    x, y = WATER['x'], WATER['y']
    z = np.zeros_like(x)
    for amp, k, ang, w in ((0.10, 0.09, 0.4, 0.9), (0.06, 0.16, 1.9, 1.3), (0.04, 0.31, 2.8, 1.9), (0.03, 0.55, 0.9, 2.6)):
        z += amp * np.sin(k * (x * math.cos(ang) + y * math.sin(ang)) - w * t)
    foam = np.zeros_like(x)
    if mode == 'erupt':
        cx, cy = ERUPT_C
        r = np.hypot(x - cx, y - cy)
        b0, b1 = EV['bubbles']
        f0, f1 = EV['fountain']
        kb = ramp(t, b0, b1)
        # the surface boils and bulges as the gas-charged water rises
        boil = kb * (1.0 + 0.5 * np.sin(r * 0.25 - t * 9.0)) * np.exp(-(r / 140.0) ** 2)
        z += 2.6 * boil + 0.8 * kb * np.sin(x * 0.4 + t * 7.0) * np.sin(y * 0.37 - t * 6.0) * np.exp(-(r / 160.0) ** 2)
        foam += np.clip(boil * 1.6, 0, 1)
        if t > f0:
            dt = t - f0
            # surge rings travelling outward from the burst (a ~25 m surge hit the southern shore)
            for k, c in enumerate((16.0, 11.0, 7.5)):
                rc = c * dt
                ring = np.exp(-((r - rc) / (14.0 + 6.0 * dt)) ** 2)
                z += (5.5 - 1.3 * k) * ring * np.sqrt(60.0 / (60.0 + rc)) * np.cos((r - rc) * 0.12)
                foam += np.clip(ring * (1.4 - 0.3 * k), 0, 1)
            z += 6.0 * math.exp(-dt * 0.6) * np.exp(-(r / 70.0) ** 2)
            foam += np.exp(-(r / (120.0 + 40.0 * dt)) ** 2)
    elif mode == 'today':
        r = np.hypot(x - RAFT[0], y - RAFT[1])
        foam += 0.9 * np.exp(-(r / 9.0) ** 2) + 0.3 * np.exp(-(r / 22.0) ** 2) * (0.6 + 0.4 * np.sin(r * 0.8 - t * 5.0))
        z += 0.25 * np.exp(-(r / 12.0) ** 2) * np.sin(t * 6.0 + r)
    return z, np.clip(foam, 0, 1)


def update_water(t, mode):
    me = WATER['obj'].data
    z, foam = water_state(t, mode)
    co = np.stack([WATER['x'], WATER['y'], z], -1).astype(np.float32)
    me.vertices.foreach_set('co', co.ravel())
    me.attributes['foam'].data.foreach_set('value', foam.astype(np.float32))
    me.update()


