"""LAKE NYOS - THE INVISIBLE KILLER.
A fully code-generated, cinematic 3D YouTube Short (1080x1920, 30 fps, 60 s) about the limnic
eruption of Lake Nyos, Cameroon, on 21 August 1986.

Everything is generated by this Blender (bpy) script: the volcanic highland terrain, the crater and
its 208 m deep lake (bathymetry, animated water surface, the underwater world), the villages in the
valley below (mud-brick houses with metal or thatch roofs, trees, banana plants), the scientific
visualisation of dissolved carbon dioxide, the overturn and the fountain of water and mist, the dense
CO2 cloud flowing down the valleys (a 2-D gravity-current simulation run by this script), the oil
lamps going out, the aftermath, today's degassing pipe, all particle effects, materials, lighting,
haze, cameras, the compositor grade, the synthesised music and sound effects, the edit (titles,
captions, transitions, film grain) and the final MP4 encode.

Run with Blender 4.2 LTS (headless):
  blender -b --factory-startup -P animation.py -- [options]

Stages (default: render):
  --stage render   build the 3D scene and render frames to renders/frames/
  --stage audio    synthesise music + SFX and write audio/mix_*.wav and sound_effects.md (numpy only)
  --stage edit     assemble frames, titles, captions, grain and audio in the Video Sequencer and
                   encode renders/lake_nyos_final.mp4
  --stage all      render + audio + edit

Options:
  --quality preview|final         preview = 270x480, 4 samples; final = 540x960, 8 samples (upscaled 2x in the edit)
  --frames A-B                    render only this frame range (resumable: existing frames are kept)
  --stills F1,F2,...              render single frames (look-dev checks)
  --out DIR                       frame folder (default renders/frames)
  --no-voice                      edit stage: leave the narration and captions out (for CapCut)
  --output NAME                   edit stage: output file name in renders/
  --save-blend PATH               also save the generated .blend

Timing comes from scene_timing.json (and build/vo_timing.json once tools/voiceover.py has run).
The gas simulation is cached in build/gas_sim.npz (delete it to re-run the simulation).
"""
