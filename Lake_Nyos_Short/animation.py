def roof_gable(bm, W, D, H, rise, oh, mi):
    """Gable roof over a W (x) by D (y) box of wall height H; ridge along y."""
    x0, x1, y0, y1 = -W / 2 - oh, W / 2 + oh, -D / 2 - oh, D / 2 + oh
    zr = H + rise
    zl = H - oh * rise / (W / 2)
    v = [bm.verts.new(p) for p in ((x0, y0, zl), (0, y0, zr), (x1, y0, zl), (x0, y1, zl), (0, y1, zr), (x1, y1, zl))]
    for f in ((v[0], v[3], v[4], v[1]), (v[1], v[4], v[5], v[2])):
        bm.faces.new(f).material_index = mi
    # gable ends (walls)
    for yy in (-D / 2, D / 2):
        f = bm.faces.new([bm.verts.new((-W / 2, yy, H)), bm.verts.new((W / 2, yy, H)), bm.verts.new((0, yy, zr - 0.08))])
        f.material_index = 0


def roof_cone(bm, r, z0, h, seg, mi):
    res = bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=True, segments=seg, radius1=r, radius2=0.02, depth=h,
                                matrix=Matrix.Translation((0, 0, z0 + h / 2)))
    _set_mi(bm, res['verts'], mi)


def window_box(bm, x, y, z, nx, ny, w=0.75, h=0.7):
    """A small shutter/window on a wall whose outward normal is (nx, ny)."""
    t = 0.06
    if abs(nx) > 0.5:
        add_box(bm, x - t, y - w / 2, z - h / 2, x + t, y + w / 2, z + h / 2, mi=4)
    else:
        add_box(bm, x - w / 2, y - t, z - h / 2, x + w / 2, y + t, z + h / 2, mi=4)


def house_bm(v):
    bm = bmesh.new()
    if v in (0, 1):
        W, D, H = (5.0, 7.0, 2.7) if v == 0 else (5.5, 10.0, 2.8)
        add_box(bm, -W / 2, -D / 2, -1.0, W / 2, D / 2, H, mi=0)
        roof_gable(bm, W, D, H, 1.1 if v == 0 else 1.3, 0.45, 1)
        add_box(bm, -0.5, -D / 2 - 0.05, -0.2, 0.5, -D / 2 + 0.05, 2.0, mi=3)              # door (front, -y)
        for yy in ([-1.5, 1.5] if v == 0 else [-3.0, 0.0, 3.0]):
            window_box(bm, W / 2, yy, 1.5, 1, 0)
            window_box(bm, -W / 2, yy, 1.5, -1, 0)
        window_box(bm, 1.5, -D / 2, 1.5, 0, -1)
    elif v == 2:
        bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=14, radius1=2.6, radius2=2.6, depth=3.3,
                                    matrix=Matrix.Translation((0, 0, 0.65)))
        roof_cone(bm, 3.4, 2.1, 2.9, 14, 2)
        add_box(bm, -0.45, -2.62, -0.2, 0.45, -2.5, 1.8, mi=3)
        window_box(bm, 2.58, 0.0, 1.4, 1, 0, 0.5, 0.5)
    else:
        add_box(bm, -1.8, -1.8, -1.0, 1.8, 1.8, 2.3, mi=0)
        roof_cone(bm, 2.9, 2.0, 2.2, 4, 2)
        add_box(bm, -0.4, -1.85, -0.2, 0.4, -1.75, 1.7, mi=3)
    return bm


def gn_scatter(name, pts, variant, rot, scale, inst_coll, collection, extra=None):
    me = bpy.data.meshes.new(name)
    me.vertices.add(len(pts))
    me.vertices.foreach_set('co', np.asarray(pts, np.float32).ravel())
    for an, arr, typ in (('variant', variant, 'INT'), ('rot', rot, 'FLOAT_VECTOR'), ('scl', scale, 'FLOAT_VECTOR')):
        a = me.attributes.new(an, typ, 'POINT')
        a.data.foreach_set('value' if typ == 'INT' else 'vector', np.asarray(arr).ravel().astype(
            np.int32 if typ == 'INT' else np.float32))
    for an, arr in (extra or {}).items():
        a = me.attributes.new(an, 'FLOAT', 'POINT')
        a.data.foreach_set('value', np.asarray(arr, np.float32))
    ob = bpy.data.objects.new(name, me)
    coll(collection).objects.link(ob)
    ng = bpy.data.node_groups.new(name + '_GN', 'GeometryNodeTree')
    ng.interface.new_socket('Geometry', in_out='INPUT', socket_type='NodeSocketGeometry')
    ng.interface.new_socket('Geometry', in_out='OUTPUT', socket_type='NodeSocketGeometry')
    N = ng.nodes
    gi, go = N.new('NodeGroupInput'), N.new('NodeGroupOutput')
    ci = N.new('GeometryNodeCollectionInfo')
    ci.inputs['Collection'].default_value = inst_coll
    ci.inputs['Separate Children'].default_value = True
    ci.inputs['Reset Children'].default_value = True
    iop = N.new('GeometryNodeInstanceOnPoints')
    iop.inputs['Pick Instance'].default_value = True

    def named(nm, dt):
        x = N.new('GeometryNodeInputNamedAttribute')
        x.data_type = dt
        x.inputs['Name'].default_value = nm
        return x.outputs['Attribute']
    ng.links.new(gi.outputs[0], iop.inputs['Points'])
    ng.links.new(ci.outputs[0], iop.inputs['Instance'])
    ng.links.new(named('variant', 'INT'), iop.inputs['Instance Index'])
    ng.links.new(named('rot', 'FLOAT_VECTOR'), iop.inputs['Rotation'])
    ng.links.new(named('scl', 'FLOAT_VECTOR'), iop.inputs['Scale'])
    ng.links.new(iop.outputs[0], go.inputs[0])
    mod = ob.modifiers.new('Scatter', 'NODES')
    mod.node_group = ng
    return ob


def template_collection(name):
    c = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(c)
    lc = bpy.context.view_layer.layer_collection.children[name]
    lc.exclude = True
    COLL[name] = c
    return c


def compound_sites():
    """Compound centres: along the valley floor (Lower Nyos) and on the ridge (Upper Nyos)."""
    rng = np.random.default_rng(1986)
    sites = []
    s0, s1 = valley_s_at_y(VILLAGE_Y[0]), valley_s_at_y(VILLAGE_Y[1])
    for s in np.arange(s0, s1, 26.0):
        for side in (-1, 1):
            if rng.random() < 0.8:
                off = side * rng.uniform(28.0, 150.0)
                sites.append(valley_point(s + rng.uniform(-8, 8), off) + ('lower',))
    for k in range(9):
        a = rng.uniform(0, 2 * np.pi)
        r = rng.uniform(20, 140)
        sites.append((UPPER[0] + r * math.cos(a), UPPER[1] + r * math.sin(a) * 1.4, 'upper'))
    return sites


def build_houses():
    tc = template_collection('HouseTemplates')
    for v in range(4):
        obj_from_bm(f'HouseV{v}', house_bm(v), [MAT[m] for m in HOUSE_MATS], collection='HouseTemplates')
    rng = np.random.default_rng(7)
    pts, rot, var, tint, upper = [], [], [], [], []
    for cx, cy, where in compound_sites():
        axis = rng.uniform(0, np.pi)
        n = rng.integers(2, 5)
        for k in range(n):
            a = axis + k * 2 * np.pi / n + rng.uniform(-0.3, 0.3)
            r = rng.uniform(6.0, 11.0) if n > 1 else 0.0
            x, y = cx + r * math.cos(a), cy + r * math.sin(a)
            v = int(rng.choice([0, 0, 1, 2, 2, 3]))
            pts.append((x, y, gz(x, y) - 0.15))
            rot.append((0.0, 0.0, a + np.pi / 2 + rng.uniform(-0.15, 0.15)))
            var.append(v)
            tint.append(rng.random())
            upper.append(where == 'upper')
    pts = np.array(pts)
    n = len(pts)
    base = np.stack([rng.uniform(0.92, 1.08, n), rng.uniform(0.92, 1.08, n), rng.uniform(0.94, 1.06, n)], -1)
    lit_p = rng.random(n)
    ob = gn_scatter('Houses', pts, var, rot, base, tc, 'Village', extra={'tint': tint, 'lit': np.zeros(n)})
    HOUSES.update(obj=ob, pts=pts, upper=np.array(upper), lit_p=lit_p, n=n, base=base)
    print('houses', n, 'upper', int(np.sum(upper)))


