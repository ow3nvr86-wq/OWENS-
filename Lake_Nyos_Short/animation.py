_PERM = {}


def _perm(seed):
    if seed not in _PERM:
        rng = np.random.default_rng(seed)
        p = rng.permutation(256)
        ang = rng.uniform(0, 2 * np.pi, 256)
        _PERM[seed] = (np.concatenate([p, p]), np.cos(ang), np.sin(ang))
    return _PERM[seed]


def perlin(x, y, seed=0):
    perm, gx, gy = _perm(seed)
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    x0 = np.floor(x)
    y0 = np.floor(y)
    xf, yf = x - x0, y - y0
    xi = x0.astype(np.int64) & 255
    yi = y0.astype(np.int64) & 255

    def g(ix, iy, dx, dy):
        h = perm[perm[ix] + iy]
        return gx[h] * dx + gy[h] * dy

    u = xf * xf * xf * (xf * (xf * 6 - 15) + 10)
    v = yf * yf * yf * (yf * (yf * 6 - 15) + 10)
    n00 = g(xi, yi, xf, yf)
    n10 = g((xi + 1) & 255, yi, xf - 1, yf)
    n01 = g(xi, (yi + 1) & 255, xf, yf - 1)
    n11 = g((xi + 1) & 255, (yi + 1) & 255, xf - 1, yf - 1)
    a = n00 + u * (n10 - n00)
    b = n01 + u * (n11 - n01)
    return (a + v * (b - a)) * 1.4


def fbm(x, y, octaves=5, seed=0, lac=2.03, gain=0.5):
    s = np.zeros_like(np.asarray(x, float))
    amp, f = 1.0, 1.0
    for o in range(octaves):
        s = s + amp * perlin(x * f, y * f, seed + o * 17)
        amp *= gain
        f *= lac
    return s


def sstep(x, a, b):
    t = np.clip((np.asarray(x, float) - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)



# ============================================================================
# Layout and terrain.  +y is north, metres; the lake surface is z = 0.
# Lake Nyos: about 2 km x 1.2 km (1.58 km2), up to 208 m deep, in a maar crater whose lowest point is the
# natural spillway at the northern end.  The valley below it runs north to the villages (Lower Nyos on the
# valley floor, Upper Nyos on the ridge) and branches.  The layout is illustrative, not a survey.
# ============================================================================
AX, AY = 620.0, 900.0                    # lake semi-axes (x, y)
DEPTH = 208.0
VALLEY = [(0.0, 1040.0), (35.0, 1480.0), (-25.0, 2050.0), (15.0, 2650.0), (-430.0, 3350.0), (-1100.0, 4250.0), (-1700.0, 5200.0)]
VALLEY_B = [(15.0, 2650.0), (480.0, 3380.0), (1000.0, 4300.0), (1500.0, 5300.0)]
VILLAGE_Y = (1780.0, 2480.0)             # Lower Nyos along the valley floor
UPPER = (420.0, 2050.0)                  # Upper Nyos on the eastern ridge (people on high ground survived)
RAFT = (-140.0, 120.0)                   # today's degassing raft


def _seg_dist(X, Y, pts):
    """Distance from (X, Y) to a polyline, and the along-line coordinate of the nearest point."""
    best = np.full(np.shape(X), 1e9)
    along = np.zeros(np.shape(X))
    s0 = 0.0
    for (ax, ay), (bx, by) in zip(pts[:-1], pts[1:]):
        dx, dy = bx - ax, by - ay
        L2 = dx * dx + dy * dy
        t = np.clip(((X - ax) * dx + (Y - ay) * dy) / L2, 0, 1)
        d = np.hypot(X - (ax + t * dx), Y - (ay + t * dy))
        m = d < best
        best = np.where(m, d, best)
        along = np.where(m, s0 + t * math.sqrt(L2), along)
        s0 += math.sqrt(L2)
    return best, along


def lake_polar(x, y):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    re = np.hypot(x / AX, y / AY) * (1.0 + 0.045 * fbm(x / 420.0 + 7.1, y / 420.0 + 2.2, 2, seed=5))
    th = np.arctan2(y / AY, x / AX)
    return re, th


def rim_height(th):
    d = np.angle(np.exp(1j * (th - np.pi / 2)))                  # wrapped angle from due north
    n = 0.5 * np.sin(3 * th + 1.1) + 0.35 * np.sin(5 * th + 0.4) + 0.2 * np.sin(9 * th + 2.0)
    return 128.0 + 22.0 * n - 100.0 * np.exp(-(d / 0.36) ** 2)


def outer_height(x, y):
    plateau = 150.0 + 50.0 * fbm(x / 1400.0 + 1.3, y / 1400.0 + 2.1, 4, seed=3) + 0.04 * np.maximum(-y - 1000.0, 0)
    plateau = plateau - 0.07 * np.maximum(y - 1700.0, 0) + 70.0 * np.exp(-((x - 470.0) ** 2 + (y - 2060.0) ** 2) / 260.0 ** 2)
    plateau = plateau - 260.0 * sstep(y, -200.0, 2600.0) - 60.0 * sstep(y, 2600.0, 6000.0)
    detail = 9.0 * fbm(x / 160.0, y / 160.0, 3, seed=11)
    d1, s1 = _seg_dist(x, y, VALLEY)
    d2, s2 = _seg_dist(x, y, VALLEY_B)
    w1 = 105.0 + 70.0 * sstep(s1, 0.0, 900.0)
    v = 78.0 * np.exp(-(d1 / w1) ** 2) * (0.75 + 0.25 * sstep(s1, 0, 600))
    v = np.maximum(v, 70.0 * np.exp(-(d2 / 150.0) ** 2) * sstep(s2, 0.0, 300.0))
    # a smooth valley floor for the village
    floor = sstep(-d1, -150.0, -40.0) * sstep(y, VILLAGE_Y[0] - 300, VILLAGE_Y[0]) * sstep(-y, -VILLAGE_Y[1] - 300, -VILLAGE_Y[1])
    return plateau + detail * (1.0 - 0.7 * floor) - v


def height(x, y):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    re, th = lake_polar(x, y)
    rim = rim_height(th)
    bed = -DEPTH * sstep(1.0 - re, 0.0, 0.42) ** 0.85 + 3.0 * fbm(x / 60.0, y / 60.0, 2, seed=8) * sstep(1.0 - re, 0.02, 0.2)
    wall = rim * sstep(re, 1.0, 1.2) ** 0.75 + 4.0 * fbm(x / 50.0, y / 50.0, 2, seed=9) * sstep(re, 1.0, 1.05)
    outer = outer_height(x, y)
    z = np.where(re < 1.0, bed, wall)
    k = sstep(re, 1.2, 1.95)
    return np.where(re < 1.2, z, rim * (1 - k) + outer * k)


def gz(x, y):
    return float(height(x, y))


def G(x, y, dz):
    return Vector((x, y, gz(x, y) + dz))


def valley_point(s, side=0.0):
    """Point along the main valley polyline at arc length s, offset 'side' metres to the east."""
    pts = VALLEY
    for (ax, ay), (bx, by) in zip(pts[:-1], pts[1:]):
        L = math.hypot(bx - ax, by - ay)
        if s <= L:
            t = s / L
            nx, ny = (by - ay) / L, -(bx - ax) / L
            return (ax + t * (bx - ax) + nx * side, ay + t * (by - ay) + ny * side)
        s -= L
    return pts[-1]


def valley_s_at_y(y):
    """Arc length along the main valley where it crosses latitude y (first two segments only)."""
    s = 0.0
    for (ax, ay), (bx, by) in zip(VALLEY[:-1], VALLEY[1:]):
        L = math.hypot(bx - ax, by - ay)
        if ay <= y <= by:
            return s + (y - ay) / (by - ay) * L
        s += L
    return s


