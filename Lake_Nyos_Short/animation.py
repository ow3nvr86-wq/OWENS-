def build_rays():
    """A few long, faint shafts of light under the surface (local z: 1 at the top, 0 at the bottom)."""
    rng = np.random.default_rng(5)
    bm = bmesh.new()
    for k in range(26):
        x, y = rng.uniform(-260, 240), rng.uniform(-420, 300)
        L = rng.uniform(60, 120)
        r = rng.uniform(1.0, 3.5)
