def shake_offset(f, s):
    amp = SHAKE.get(s['name'], 0.0)
    if amp <= 0:
        return Vector((0, 0, 0))
    t = tsec(f)
    k = 1.0
    if s['name'] == 'erupt':
        f0 = EV['fountain'][0]
        k = 0.2 * ramp(t, EV['bubbles'][0], f0) + 3.0 * math.exp(-max(t - f0, 0) * 0.7) * (t >= f0)
    return Vector((math.sin(t * 37.0), math.sin(t * 29.0 + 1), math.sin(t * 23.0 + 2))) * amp * k


