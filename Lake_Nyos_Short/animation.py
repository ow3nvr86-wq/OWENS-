# ============================================================================
# The CO2 cloud: a 2-D shallow-water simulation of a dense gas current on the real terrain of this scene.
# CO2 is ~1.5x as dense as air, so it flows like a liquid with reduced gravity g' = g (rho_gas - rho_air) /
# rho_gas.  Well-balanced finite volumes (hydrostatic reconstruction + Rusanov flux), Manning friction from
# trees and rough ground, slow dilution by mixing with air.  Run once and cached in build/gas_sim.npz.
# Volumes and timing are illustrative (see research_sources.md); the visual is compressed in time.
# ============================================================================
GAS_DX = 20.0
GAS_BOX = (-1500.0, 1500.0, -1100.0, 4700.0)
G_RED = 9.81 * (1.98 - 1.20) / 1.98            # ~3.9 m/s2
GAS_N = 0.12                                     # Manning roughness (grass, scrub, trees)
GAS_TAU = 1500.0                                 # e-folding time of dilution below the visualised level (s)
GAS_INIT, GAS_SRC, GAS_SRC_T = 55.0, 0.55, 210.0  # initial layer over the lake (m), injection (m/s) and its duration (s)
GAS_T_END, GAS_SNAP = 900.0, 3.0
GAS = {}


def _gas_grid():
    x0, x1, y0, y1 = GAS_BOX
    nx, ny = int((x1 - x0) / GAS_DX), int((y1 - y0) / GAS_DX)
    xc = x0 + GAS_DX * (np.arange(nx) + 0.5)
    yc = y0 + GAS_DX * (np.arange(ny) + 0.5)
    X, Y = np.meshgrid(xc, yc)
    return xc, yc, X, Y


def _sw_flux_x(h, hu, hv, zb):
    """Fluxes through the x-faces of a padded grid; returns (left-cell, right-cell) versions for h, hu, hv."""
    g = G_RED
    hL, hR = h[:, :-1], h[:, 1:]
    zL, zR = zb[:, :-1], zb[:, 1:]
    uL = np.where(hL > 1e-3, hu[:, :-1] / np.maximum(hL, 1e-3), 0.0)
    uR = np.where(hR > 1e-3, hu[:, 1:] / np.maximum(hR, 1e-3), 0.0)
    vL = np.where(hL > 1e-3, hv[:, :-1] / np.maximum(hL, 1e-3), 0.0)
    vR = np.where(hR > 1e-3, hv[:, 1:] / np.maximum(hR, 1e-3), 0.0)
    zf = np.maximum(zL, zR)
    hLs = np.maximum(0.0, hL + zL - zf)
    hRs = np.maximum(0.0, hR + zR - zf)
    a = np.maximum(np.abs(uL) + np.sqrt(g * hLs), np.abs(uR) + np.sqrt(g * hRs))
    f0 = 0.5 * (hLs * uL + hRs * uR) - 0.5 * a * (hRs - hLs)
    f1 = 0.5 * (hLs * uL * uL + 0.5 * g * hLs ** 2 + hRs * uR * uR + 0.5 * g * hRs ** 2) - 0.5 * a * (hRs * uR - hLs * uL)
    f2 = 0.5 * (hLs * uL * vL + hRs * uR * vR) - 0.5 * a * (hRs * vR - hLs * vL)
    f1L = f1 + 0.5 * g * (hL ** 2 - hLs ** 2)
    f1R = f1 + 0.5 * g * (hR ** 2 - hRs ** 2)
    return f0, f1L, f1R, f2, a


def run_gas_sim():
    path = os.path.join(BUILD, 'gas_sim.npz')
    xc, yc, X, Y = _gas_grid()
    if os.path.exists(path):
        d = np.load(path)
        GAS.update(xc=xc, yc=yc, zb=d['zb'], times=d['times'], h=d['h'].astype(np.float32))
        return
    t_wall = __import__('time').time()
    re, _ = lake_polar(X, Y)
    zb = np.where(re < 1.0, 0.0, height(X, Y))
    lake = re < 0.97
    h = np.where(re < 1.12, np.maximum(GAS_INIT - zb, 0.0), 0.0)
    hu = np.zeros_like(h)
    hv = np.zeros_like(h)
    times = np.arange(0.0, GAS_T_END + 1e-6, GAS_SNAP)
    snaps = []
    t, k = 0.0, 0
    dx = GAS_DX
    while k < len(times):
        if t >= times[k] - 1e-9:
            snaps.append(h.astype(np.float16))
            k += 1
            if k % 50 == 0:
                print(f'gas sim t={t:6.1f}s max h={h.max():6.1f} m  volume={h.sum() * dx * dx / 1e9:.3f} km3', flush=True)
            continue
        hp = np.pad(h, 1, mode='edge')
        hup = np.pad(hu, 1, mode='edge')
        hvp = np.pad(hv, 1, mode='edge')
        zp = np.pad(zb, 1, mode='edge')
        fx0, fx1L, fx1R, fx2, ax = _sw_flux_x(hp[1:-1], hup[1:-1], hvp[1:-1], zp[1:-1])
        gy0, gy1L, gy1R, gy2, ay = _sw_flux_x(hp[:, 1:-1].T, hvp[:, 1:-1].T, hup[:, 1:-1].T, zp[:, 1:-1].T)
        amax = max(float(ax.max()), float(ay.max()), 1.0)
        dt = min(0.45 * dx / amax, 1.0, times[k] - t)
        # x-direction: face j sits between padded cells j and j+1; cell i (unpadded) = padded i+1
        dh = -(fx0[:, 1:] - fx0[:, :-1]) / dx
        dhu = -(fx1L[:, 1:] - fx1R[:, :-1]) / dx
        dhv = -(fx2[:, 1:] - fx2[:, :-1]) / dx
        dh += -((gy0[:, 1:] - gy0[:, :-1]) / dx).T
        dhv += -((gy1L[:, 1:] - gy1R[:, :-1]) / dx).T
        dhu += -((gy2[:, 1:] - gy2[:, :-1]) / dx).T
        h = np.maximum(h + dt * dh, 0.0)
        hu = hu + dt * dhu
        hv = hv + dt * dhv
        # Manning friction (implicit), dilution, the continuing release over the lake
        hs = np.maximum(h, 0.05)
        sp = np.hypot(hu, hv) / hs
        damp = 1.0 + dt * G_RED * GAS_N ** 2 * sp / hs ** (4.0 / 3.0)
        hu /= damp
        hv /= damp
        h *= math.exp(-dt / GAS_TAU)
        if t < GAS_SRC_T:
            h = np.where(lake, h + GAS_SRC * dt * (1.0 - t / GAS_SRC_T) * 2.0, h)
        dry = h < 0.02
        h[dry] = 0.0
        hu[dry] = 0.0
        hv[dry] = 0.0
        t += dt
    H = np.array(snaps)
    np.savez_compressed(path, zb=zb.astype(np.float32), times=times, h=H)
    print(f'gas sim done in {__import__("time").time() - t_wall:.0f} s; {len(times)} snapshots')
    GAS.update(xc=xc, yc=yc, zb=zb.astype(np.float32), times=times, h=H.astype(np.float32))


def gas_h_at(ts):
    """Thickness field at simulation time ts (linear between snapshots)."""
    times = GAS['times']
    f = np.clip(ts / GAS_SNAP, 0, len(times) - 1.001)
    i = int(f)
    w = f - i
    return GAS['h'][i] * (1 - w) + GAS['h'][i + 1] * w


def gas_sample(field, x, y):
    xc, yc = GAS['xc'], GAS['yc']
    fx = np.clip((np.asarray(x) - xc[0]) / GAS_DX, 0, len(xc) - 1.001)
    fy = np.clip((np.asarray(y) - yc[0]) / GAS_DX, 0, len(yc) - 1.001)
    i, j = fy.astype(int), fx.astype(int)
    wy, wx = fy - i, fx - j
    return (field[i, j] * (1 - wx) * (1 - wy) + field[i, j + 1] * wx * (1 - wy) +
            field[i + 1, j] * (1 - wx) * wy + field[i + 1, j + 1] * wx * wy)


def gas_arrival(x, y, thr=3.0):
    times = GAS['times']
    hs = gas_sample(GAS['h'].transpose(1, 2, 0), x, y)
    idx = np.nonzero(hs > thr)[0]
    return float(times[idx[0]]) if len(idx) else 1e9


