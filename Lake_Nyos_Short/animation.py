def tree_bm(seed, h=11.0, crown=3.6, blobs=6, trunk_mi=1):
    rng = np.random.default_rng(seed)
    bm = bmesh.new()
    add_cyl(bm, 0.26, 0.12, h * 0.62, seg=7, matrix=Matrix.Translation((0, 0, h * 0.31 - 0.3)), mi=trunk_mi)
    for k in range(blobs):
        a = rng.uniform(0, 2 * np.pi)
        r = rng.uniform(0.2, 0.75) * crown
        cz = h * rng.uniform(0.55, 0.9)
        s = crown * rng.uniform(0.55, 0.85)
        res = bmesh.ops.create_icosphere(bm, subdivisions=2, radius=s,
                                         matrix=Matrix.Translation((r * math.cos(a), r * math.sin(a), cz)))
        for vv in res['verts']:
            nrm = vv.co - Vector((r * math.cos(a), r * math.sin(a), cz))
            vv.co += nrm.normalized() * float(rng.normal(0, 0.12)) * s
    return bm


def eucalyptus_bm(seed):
    rng = np.random.default_rng(seed)
    bm = bmesh.new()
    add_cyl(bm, 0.22, 0.08, 17.0, seg=7, matrix=Matrix.Translation((0, 0, 8.2)), mi=1)
    for k in range(7):
        cz = rng.uniform(9.0, 17.0)
        s = rng.uniform(1.0, 1.8)
        bmesh.ops.create_icosphere(bm, subdivisions=1, radius=s,
                                         matrix=Matrix.Translation((rng.uniform(-1.2, 1.2), rng.uniform(-1.2, 1.2), cz))
                                         @ Matrix.Diagonal((1.0, 1.0, 1.6, 1.0)))
    return bm


def banana_bm(seed):
    rng = np.random.default_rng(seed)
    bm = bmesh.new()
    add_cyl(bm, 0.14, 0.10, 2.2, seg=6, matrix=Matrix.Translation((0, 0, 1.1)), mi=1)
    for k in range(8):
        a = k * 2 * np.pi / 8 + rng.uniform(-0.3, 0.3)
        tilt = rng.uniform(0.5, 1.2)
        L = rng.uniform(1.6, 2.3)
        m = (Matrix.Translation((0, 0, 2.1)) @ Matrix.Rotation(a, 4, 'Z') @ Matrix.Rotation(tilt, 4, 'Y')
             @ Matrix.Translation((0, 0, L / 2)) @ Matrix.Diagonal((0.04, 0.32, L / 2, 1.0)))
        bmesh.ops.create_icosphere(bm, subdivisions=1, radius=1.0, matrix=m)
    return bm


def build_trees():
    tc = template_collection('TreeTemplates')
    obj_from_bm('TreeV0', tree_bm(1, h=9.0, crown=3.4), [MAT['leaves'], MAT['bark']], collection='TreeTemplates', smooth=True)
    obj_from_bm('TreeV1', tree_bm(2, h=12.0, crown=4.0), [MAT['leaves'], MAT['bark']], collection='TreeTemplates', smooth=True)
    obj_from_bm('TreeV2', tree_bm(3, h=6.0, crown=2.6, blobs=4), [MAT['leaves'], MAT['bark']], collection='TreeTemplates', smooth=True)
    obj_from_bm('TreeV3', eucalyptus_bm(4), [MAT['leaves'], MAT['bark_pale']], collection='TreeTemplates', smooth=True)
    rng = np.random.default_rng(12)
    pts = []
    for (x0, x1, y0, y1, step) in ((-1100, 1100, -1300, 3000, 9.0), (-5000, 5000, -4000, 7000, 40.0)):
        gx_, gy_ = np.meshgrid(np.arange(x0, x1, step), np.arange(y0, y1, step))
        p = np.stack([gx_.ravel(), gy_.ravel()], -1) + rng.uniform(-0.45, 0.45, (gx_.size, 2)) * step
        if step > 10:
            p = p[~((p[:, 0] > -1100) & (p[:, 0] < 1100) & (p[:, 1] > -1300) & (p[:, 1] < 3000))]
        pts.append(p)
    p = np.concatenate(pts)
    x, y = p[:, 0], p[:, 1]
    re, _ = lake_polar(x, y)
    dv, _ = _seg_dist(x, y, VALLEY)
    dvb, _ = _seg_dist(x, y, VALLEY_B)
    dv = np.minimum(dv, dvb)
    # gallery forest along the streams, open grassland with scattered trees elsewhere; none in the lake
    dens = 0.035 + 0.75 * np.exp(-(dv / 70.0) ** 2) + 0.1 * np.clip(fbm(x / 300.0, y / 300.0, 3, seed=31), 0, 1)
    dens = np.where(re < 1.04, 0.0, dens)
    clearing = (dv < 200.0) & (y > VILLAGE_Y[0] - 120) & (y < VILLAGE_Y[1] + 80)
    dens = np.where(clearing, 0.06, dens)
    dens = np.where((re < 1.25) & (re >= 1.04), dens * 0.6, dens)
    keep = rng.random(len(x)) < dens
    # keep the house compounds clear
    hp = HOUSES['pts']
    p = p[keep]
    from_h = np.full(len(p), 1e9)
    for hx, hy in hp[:, :2]:
        from_h = np.minimum(from_h, np.hypot(p[:, 0] - hx, p[:, 1] - hy))
    p = p[from_h > 7.0]
    dpath, _ = _seg_dist(p[:, 0], p[:, 1], [valley_point(s, 14.0 * math.sin(s / 90.0)) for s in np.arange(300.0, 2300.0, 10.0)])
    p = p[dpath > 9.0]
    n = len(p)
    z = height(p[:, 0], p[:, 1]) - 0.2
    s = rng.uniform(0.75, 1.3, n)
    var = np.where(rng.random(n) < 0.12, 3, rng.integers(0, 3, n))
    gn_scatter('Forest', np.stack([p[:, 0], p[:, 1], z], -1), var, np.stack([np.zeros(n), np.zeros(n), rng.uniform(0, 6.28, n)], -1),
               np.stack([s, s, s * rng.uniform(0.9, 1.15, n)], -1), tc, 'Trees', extra={'shade': rng.random(n)})
    print('trees', n)
    # banana plants around the compounds
    bc = template_collection('BananaTemplates')
    for k in range(2):
        obj_from_bm(f'BananaV{k}', banana_bm(20 + k), [MAT['banana'], MAT['bark']], collection='BananaTemplates', smooth=True)
    q = []
    for hx, hy, hz in hp:
        for j in range(rng.integers(1, 4)):
            a = rng.uniform(0, 2 * np.pi)
            r = rng.uniform(5.5, 10.0)
            q.append((hx + r * math.cos(a), hy + r * math.sin(a)))
    q = np.array(q)
    d = np.full(len(q), 1e9)
    for hx, hy in hp[:, :2]:
        d = np.minimum(d, np.hypot(q[:, 0] - hx, q[:, 1] - hy))
    q = q[d > 4.5]
    n = len(q)
    s = rng.uniform(0.8, 1.25, n)
    gn_scatter('Bananas', np.stack([q[:, 0], q[:, 1], height(q[:, 0], q[:, 1]) - 0.1], -1), rng.integers(0, 2, n),
               np.stack([np.zeros(n), np.zeros(n), rng.uniform(0, 6.28, n)], -1), np.stack([s, s, s], -1), bc, 'Village')
    print('bananas', n)


def build_paths():
    """Red-earth footpaths along the valley and up to Upper Nyos."""
    lines = [[valley_point(s, 14.0 * math.sin(s / 90.0)) for s in np.arange(300.0, 2300.0, 10.0)],
             [(valley_point(1150.0, 20.0)[0] + (UPPER[0] - valley_point(1150.0, 20.0)[0]) * k,
               valley_point(1150.0, 20.0)[1] + (UPPER[1] - valley_point(1150.0, 20.0)[1]) * k + 40 * math.sin(k * 3.0))
              for k in np.linspace(0, 1, 60)]]
    bm = bmesh.new()
    for pts in lines:
        for a, b in zip(pts[:-1], pts[1:]):
            d = Vector((b[0] - a[0], b[1] - a[1], 0)).normalized()
            nrm = Vector((-d.y, d.x, 0)) * 0.95
            q = [Vector((a[0], a[1], 0)) - nrm, Vector((b[0], b[1], 0)) - nrm, Vector((b[0], b[1], 0)) + nrm,
                 Vector((a[0], a[1], 0)) + nrm]
            add_quad(bm, [Vector((v.x, v.y, gz(v.x, v.y) + 0.07)) for v in q])
    obj_from_bm('Paths', bm, MAT['path'], collection='Village')


