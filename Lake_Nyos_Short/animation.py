def mesh_obj(name, verts, faces, mat=None, collection='World', smooth=True, loc=(0, 0, 0)):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], [], [tuple(f) for f in faces])
    me.update()
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    ob.location = loc
    if mat is not None:
        me.materials.append(mat)
    coll(collection).objects.link(ob)
    return ob


def obj_from_bm(name, bm, mats=None, collection='World', smooth=False, loc=(0, 0, 0)):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    ob.location = loc
    if mats is not None:
        for m in (mats if isinstance(mats, (list, tuple)) else [mats]):
            me.materials.append(m)
    coll(collection).objects.link(ob)
    return ob


def add_box(bm, x0, y0, z0, x1, y1, z1, matrix=Matrix(), mi=0):
    m = matrix @ Matrix.Translation(((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)) @ Matrix.Diagonal(
        (abs(x1 - x0), abs(y1 - y0), abs(z1 - z0), 1))
    r = bmesh.ops.create_cube(bm, size=1.0, matrix=m)
    _set_mi(bm, r['verts'], mi)


def add_cyl(bm, r1, r2, depth, seg=12, matrix=Matrix(), mi=0):
    r = bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=seg, radius1=r1, radius2=r2,
                              depth=depth, matrix=matrix)
    _set_mi(bm, r['verts'], mi)


def add_sphere(bm, r, u=12, v=8, matrix=Matrix(), mi=0):
    res = bmesh.ops.create_uvsphere(bm, u_segments=u, v_segments=v, radius=r, matrix=matrix)
    _set_mi(bm, res['verts'], mi)


def _set_mi(bm, verts, mi):
    if not mi:
        return
    vs = set(verts)
    for f in bm.faces:
        if f.verts[0] in vs:
            f.material_index = mi


def add_quad(bm, pts, mi=0):
    vs = [bm.verts.new(p) for p in pts]
    f = bm.faces.new(vs)
    f.material_index = mi
    return f


def empty(name, loc=(0, 0, 0), collection='Rig'):
    e = bpy.data.objects.new(name, None)
    e.location = loc
    coll(collection).objects.link(e)
    return e


def seg_matrix(p0, p1):
    """Matrix mapping a unit cylinder along +Z centred at the origin onto segment p0-p1 (length via scale)."""
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    q = Vector((0, 0, 1)).rotation_difference(d.normalized())
    return Matrix.Translation((p0 + p1) / 2) @ q.to_matrix().to_4x4()


# --- shader node helpers ---------------------------------------------------
def new_mat(name):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    return m, nt, out


def nd(nt, kind, **inputs):
    n = nt.nodes.new(kind)
    for k, v in inputs.items():
        if k.startswith('p_'):
            setattr(n, k[2:], v)
        else:
            sock = n.inputs[k]
            if isinstance(v, bpy.types.NodeSocket):
                nt.links.new(v, sock)
            else:
                sock.default_value = v
    return n


def mth(nt, op, a, b=None, c=None, clamp=False):
    n = nt.nodes.new('ShaderNodeMath')
    n.operation = op
    n.use_clamp = clamp
    for i, v in enumerate((a, b, c)):
        if v is None:
            continue
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, n.inputs[i])
        else:
            n.inputs[i].default_value = v
    return n.outputs[0]


def mixc(nt, fac, a, b):
    n = nt.nodes.new('ShaderNodeMix')
    n.data_type = 'RGBA'
    for idx, v in ((0, fac), (6, a), (7, b)):
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, n.inputs[idx])
        else:
            n.inputs[idx].default_value = v
    return n.outputs[2]


def rgba(c):
    return (c[0], c[1], c[2], 1.0)


def principled(nt, out, **kw):
    p = nt.nodes.new('ShaderNodeBsdfPrincipled')
    for k, v in kw.items():
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, p.inputs[k])
        else:
            p.inputs[k].default_value = v
    if out is not None:
        nt.links.new(p.outputs[0], out.inputs['Surface'])
    return p


def noise(nt, scale, detail=2.0, rough=0.5, vec=None, out='Fac'):
    n = nd(nt, 'ShaderNodeTexNoise', Scale=scale, Detail=detail, Roughness=rough)
    if vec is not None:
        nt.links.new(vec, n.inputs['Vector'])
    return n.outputs[out]


def obj_coord(nt):
    return nd(nt, 'ShaderNodeTexCoord').outputs['Object']


def attr(nt, name, kind='INSTANCER', out='Fac'):
    return nd(nt, 'ShaderNodeAttribute', p_attribute_name=name, p_attribute_type=kind).outputs[out]


def value(nt, name, v):
    """A named Value node: per-shot settings (set before each shot, never animated within a shot)."""
    n = nt.nodes.new('ShaderNodeValue')
    n.name = name
    n.outputs[0].default_value = v
    return n.outputs[0]


def sep(nt, vec):
    return nd(nt, 'ShaderNodeSeparateXYZ', Vector=vec)


def comb(nt, x, y, z):
    return nd(nt, 'ShaderNodeCombineXYZ', X=x, Y=y, Z=z).outputs[0]


def ramp_node(nt, fac, stops):
    r = nd(nt, 'ShaderNodeValToRGB', Fac=fac)
    els = r.color_ramp.elements
    while len(els) < len(stops):
        els.new(0.5)
    for el, (pos, col) in zip(els, stops):
        el.position = pos
        el.color = rgba(col) if len(col) == 3 else col
    return r.outputs['Color']


