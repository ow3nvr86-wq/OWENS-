def basis_matrix(o, r, u):
    o, r, u = Vector(o), Vector(r).normalized(), Vector(u).normalized()
    n = r.cross(u).normalized()
    return Matrix(((r.x, u.x, n.x, o.x), (r.y, u.y, n.y, o.y), (r.z, u.z, n.z, o.z), (0, 0, 0, 1)))


def card(name, mat, w, h, o, yaw=0.0, pitch=90.0, collection='World', seg=1):
    """A textured rectangle w x h, centred at o. pitch=90 stands it up facing -Y (rotated by yaw about Z)."""
    xs, ys = np.linspace(-w / 2, w / 2, seg + 1), np.linspace(-h / 2, h / 2, seg + 1)
    X, Y = np.meshgrid(xs, ys)
    verts = np.stack([X, Y, np.zeros_like(X)], -1).reshape(-1, 3)
    ii = np.arange((seg + 1) ** 2).reshape(seg + 1, seg + 1)
    faces = np.stack([ii[:-1, :-1], ii[:-1, 1:], ii[1:, 1:], ii[1:, :-1]], -1).reshape(-1, 4)
    uv = np.stack([(X + w / 2) / w, (Y + h / 2) / h], -1).reshape(-1, 2)
    loops = faces.ravel()
    ob = mesh_obj(name, verts, faces, mat, collection, smooth=False, uvs=uv[loops])
    ob.rotation_euler = (R(pitch), 0, R(yaw))
    ob.location = o
    return ob


# --- shader node helpers ---------------------------------------------------
def new_mat(name):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    return m, nt, out


def nd(nt, kind, **inputs):
    n = nt.nodes.new(kind)
    for k, v in inputs.items():
        if k.startswith('p_'):
            setattr(n, k[2:], v)
        else:
            sock = n.inputs[k]
            if isinstance(v, bpy.types.NodeSocket):
                nt.links.new(v, sock)
            else:
                sock.default_value = v
    return n


def mth(nt, op, a, b=None, c=None, clamp=False):
    n = nt.nodes.new('ShaderNodeMath')
    n.operation = op
    n.use_clamp = clamp
    for i, v in enumerate((a, b, c)):
        if v is None:
            continue
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, n.inputs[i])
        else:
            n.inputs[i].default_value = v
    return n.outputs[0]


def mixc(nt, fac, a, b):
    n = nt.nodes.new('ShaderNodeMix')
    n.data_type = 'RGBA'
    for idx, v in ((0, fac), (6, a), (7, b)):
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, n.inputs[idx])
        else:
            n.inputs[idx].default_value = v
    return n.outputs[2]


def rgba(c):
    return (c[0], c[1], c[2], 1.0)


def principled(nt, out, **kw):
    p = nt.nodes.new('ShaderNodeBsdfPrincipled')
    for k, v in kw.items():
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, p.inputs[k])
        else:
            p.inputs[k].default_value = v
    if out is not None:
        nt.links.new(p.outputs[0], out.inputs['Surface'])
    return p


def noise(nt, scale, detail=2.0, rough=0.5, vec=None, out='Fac'):
    n = nd(nt, 'ShaderNodeTexNoise', Scale=scale, Detail=detail, Roughness=rough)
    if vec is not None:
        nt.links.new(vec, n.inputs['Vector'])
    return n.outputs[out]


def obj_coord(nt):
    return nd(nt, 'ShaderNodeTexCoord').outputs['Object']


def value(nt, name, v):
    n = nt.nodes.new('ShaderNodeValue')
    n.name = name
    n.outputs[0].default_value = v
    return n.outputs[0]


def sep(nt, vec):
    return nd(nt, 'ShaderNodeSeparateXYZ', Vector=vec)


def comb(nt, x, y, z):
    return nd(nt, 'ShaderNodeCombineXYZ', X=x, Y=y, Z=z).outputs[0]


def ramp_node(nt, fac, stops):
    r = nd(nt, 'ShaderNodeValToRGB', Fac=fac)
    els = r.color_ramp.elements
    while len(els) < len(stops):
        els.new(0.5)
    for el, (pos, col) in zip(els, stops):
        el.position = pos
        el.color = rgba(col) if len(col) == 3 else col
    return r.outputs['Color']


