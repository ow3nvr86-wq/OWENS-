def jmat(ob):
    M = ob.matrix_basis.copy()
    p = ob.parent
    while p is not None:
        M = p.matrix_basis @ M
        p = p.parent
    return M


def reach(name, side, target, bend=None):
    """Shoulder/elbow angles that put the hand (centre) at a world-space target. Returns (sh tuple, elbow)."""
    J = CH[name]['J']
    sh = J['sh' + side]
    M = jmat(J['chest']) @ Matrix.Translation(sh.location)
    d = M.inverted() @ Vector(target)
    D = d.length
    L = 0.59
    if bend is None:
        bend = math.degrees(2 * math.acos(min(D / L, 0.999))) if D < L else 6.0
        bend = max(bend, 6.0)
    dn = d.normalized()
    sw1 = math.asin(max(-1.0, min(1.0, dn.y)))
    ph1 = math.atan2(-dn.x, -dn.z)
    sw2 = math.pi - sw1
    ph2 = math.atan2(dn.x, dn.z)
    sw, ph = (sw1, ph1) if abs(ph1) <= abs(ph2) else (sw2, ph2)
    sg = -1 if side == 'R' else 1
    return (math.degrees(sw) - bend * 0.5, math.degrees(ph) * sg, 0.0), bend


def look_at(name, target, head=0.7):
    """Head turn/nod and eye angles toward a world-space point. Returns a pose fragment."""
    J = CH[name]['J']
    M = jmat(J['chest']) @ Matrix.Translation(J['neck'].location + HC)
    d = M.inverted() @ Vector(target)
    yaw = math.degrees(math.atan2(-d.x, d.y))
    pitch = math.degrees(math.atan2(d.z, math.hypot(d.x, d.y)))
    return dict(turn=yaw * head, nod=-pitch * head, look=(yaw * (1 - head) * 1.2, pitch * (1 - head) * 1.2))


def apply_reach(name, P, side, target, bend=None):
    pose(name, P)
    P['sh' + side], P['el' + side] = reach(name, side, target, bend)
    return P


