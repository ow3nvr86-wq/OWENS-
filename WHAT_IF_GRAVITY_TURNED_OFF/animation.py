def float_pose(t, seed, u, calm=0.0):
    """Arms drifting out for balance, legs relaxed and slightly bent, slow swimming motion."""
    s1, s2 = math.sin(1.3 * t + seed), math.sin(0.9 * t + 2 * seed)
    a = (1 - calm)
    P = dict(shR=(-15 + 18 * s1 * a, 55 + 12 * s2 * a, 0), shL=(-15 - 18 * s2 * a, 55 + 12 * s1 * a, 0), elR=28 + 10 * s2, elL=28 + 10 * s1,
             hipR=(18 + 8 * s1, 8), hipL=(10 - 8 * s1, 6), knR=30 + 8 * s2, knL=22 - 6 * s2, lean=4 + 3 * s1, dz=0.0)
    return P, u


def blend_pose(A, B, u):
    out = dict(A)
    for k, vb in B.items():
        va = A.get(k, REST.get(k))
        if va is None:
            out[k] = vb
        elif isinstance(vb, tuple):
            out[k] = tuple(x + (y - x) * u for x, y in zip(va, vb))
        elif isinstance(vb, (int, float)):
            out[k] = va + (vb - va) * u
        else:
            out[k] = vb if u > 0.5 else va
    return out


