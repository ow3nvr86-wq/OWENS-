CARD_BODY = {}


def update_car(name, tau, t):
    c = CARS[name]
    b = SIM[name]
    pos, rot = b.state(tau)
    c['root'].location = Vector(pos)
    c['root'].rotation_euler = tuple(rot)
    # suspension: wheels droop when the weight is gone; body bounces after the landing
    if tau < 0:
        droop, body = 0.0, 0.0
    elif tau < b.t_land:
        droop, body = 0.10 * smooth(tau / 0.6), 0.0
    else:
        s = tau - b.t_land
        droop = 0.10 * max(0.0, 1 - s / 0.05)
        amp = min(0.22, 0.03 * b.v_impact)
        body = -amp * math.exp(-4.5 * s) * math.cos(13.0 * s)
    CARD_BODY[name] = body
    c['body'].location = (0, 0, body)
    # wheels: rolling before; still spinning in the air (MoveN's driver brakes at tau 1.4); rolling again after landing
    v = float(np.linalg.norm(b.vpre[:2]))
    if v > 0:
        if tau < 0:
            dist = v * tau
        elif tau < 1.4 or name != 'MoveN':
            dist = v * min(tau, b.t_land)
        else:
            dist = v * 1.4 + v * 0.15 * (1 - math.exp(-(tau - 1.4) / 0.15))
        if tau > b.t_land:
            sp = np.linalg.norm(b.state(tau + 0.05)[0][:2] - b.state(tau)[0][:2]) / 0.05
            dist += sp * (tau - b.t_land)
        ang = dist / c['wr']
    else:
        ang = 0.0
    for wob in c['wheels']:
        wob.location.z = c['wr'] - droop
        wob.rotation_euler = (ang, 0, 0)


