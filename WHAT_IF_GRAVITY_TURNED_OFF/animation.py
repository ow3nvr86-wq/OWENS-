# fountain nozzles: (position offset from FOUNTAIN, velocity, emission rate per second, droplet radius)
NOZZLES = [((0, 0, 1.82), (0, 0, 9.0), 650.0, 0.026)]
for _k in range(6):
    _a = 2 * math.pi * _k / 6
    NOZZLES.append(((2.6 * math.cos(_a), 2.6 * math.sin(_a), 0.82), (-1.15 * math.cos(_a), -1.15 * math.sin(_a), 5.6), 130.0, 0.022))
POOL_Z = 0.60


def kin(p, v, t0, t1):
    """Propagate (p, v) from sim time t0 to t1 with the scenario's piecewise acceleration (vectorised)."""
    p, v = p.copy(), v.copy()
    t0 = np.broadcast_to(np.asarray(t0, float), (len(p),)).copy()
    for a_lo, a_hi, acc in ((-1e9, 0.0, -G), (0.0, T_RET, A_UP), (T_RET, 1e9, -G)):
        s0 = np.clip(t0, a_lo, a_hi)
        s1 = np.clip(np.full_like(t0, t1), a_lo, a_hi)
        d = np.maximum(s1 - s0, 0.0)
        p[:, 2] += v[:, 2] * d + 0.5 * acc * d * d
        p[:, :2] += v[:, :2] * d[:, None]
        v[:, 2] += acc * d
    return p, v


def fountain_droplets(tau):
    Ps, Rs = [], []
    for k, (off, vel, rate, rad) in enumerate(NOZZLES):
        t_first = -3.0
        nb = int((tau - t_first) * rate)
        if nb <= 0:
            continue
        tb = t_first + (np.arange(nb) + 0.5) / rate
        rng = np.random.default_rng(1000 + k)
        jit = rng.normal(0, 1, (nb, 3)) * np.array([0.07, 0.07, 0.15]) * (1 if k == 0 else 0.6)
        v0 = np.array(vel)[None, :] + jit
        p0 = np.array(FOUNTAIN + Vector(off))[None, :] + rng.normal(0, 0.02, (nb, 3))
        p, v = kin(p0, v0, tb, tau)
        dx, dy = p[:, 0] - FOUNTAIN.x, p[:, 1] - FOUNTAIN.y
        inside = dx * dx + dy * dy < 4.5 ** 2
        alive = p[:, 2] > np.where(inside, POOL_Z, 0.15)
        size = rad * (0.6 + 0.8 * rng.random(nb))
        Ps.append(p[alive])
        Rs.append(size[alive])
    if not Ps:
        return np.zeros((0, 3)), np.zeros(0)
    P, Rr = np.concatenate(Ps), np.concatenate(Rs)
    P, Rr = P[:MAXW], Rr[:MAXW]
    return P, Rr


def pool_state(tau):
    """The water resting in the basin drifts up as a slab, then falls back and splashes (z, wobble, spread)."""
    if tau < 0:
        return POOL_Z, 0.0, 1.0
    if tau < T_RET:
        return POOL_Z + 0.5 * A_UP * tau * tau, min(tau / 3.0, 1.0), 1.0
    z10 = POOL_Z + 0.5 * A_UP * T_RET ** 2
    v10 = A_UP * T_RET
    s = tau - T_RET
    z = z10 + v10 * s - 0.5 * G * s * s
    if z > POOL_Z:
        return z, 1.0, 1.0
    s_land = (v10 + math.sqrt(v10 * v10 + 2 * G * (z10 - POOL_Z))) / G
    return POOL_Z, max(0.0, 1.0 - (s - s_land) / 0.6), 1.0 + 0.6 * min((s - s_land) / 0.5, 1.0)


