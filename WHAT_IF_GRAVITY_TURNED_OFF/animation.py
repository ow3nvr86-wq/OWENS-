def camera_shot(name, lens, path, target, fstop=8.0, shake=0.0, ease=True, lenses=None):
    """path/target: list of (u, (x, y, z)) keys with u in 0..1 of the shot. lenses: [(u, mm)]."""
    s = SHOT[name]
    rig = empty('Rig_' + name)
    tgt = empty('Target_' + name)
    cd = bpy.data.cameras.new('Cam_' + name)
    cd.lens = lens
    cd.sensor_width = 24
    cd.sensor_fit = 'VERTICAL'
    cd.clip_start, cd.clip_end = 0.02, 5000
    cd.dof.use_dof = fstop < 50
    cd.dof.aperture_fstop = fstop
    cd.dof.aperture_blades = 7
    cd.dof.focus_object = tgt
    cam = bpy.data.objects.new('Cam_' + name, cd)
    coll('Rig').objects.link(cam)
    cam.parent = rig
    con = rig.constraints.new('TRACK_TO')
    con.target = tgt
    con.track_axis = 'TRACK_NEGATIVE_Z'
    con.up_axis = 'UP_Y'
    span = s['f1'] + 1 - s['f0']
    for u, p in path:
        rig.location = p
        rig.keyframe_insert('location', frame=s['f0'] + u * span)
    for u, p in target:
        tgt.location = p
        tgt.keyframe_insert('location', frame=s['f0'] + u * span)
    if lenses:
        for u, mm in lenses:
            cd.lens = mm
            cd.keyframe_insert('lens', frame=s['f0'] + u * span)
    for idb in (rig, tgt, cd):
        if idb.animation_data:
            for fc in idb.animation_data.action.fcurves:
                for kp in fc.keyframe_points:
                    kp.interpolation = 'BEZIER'
                    kp.easing = ease if isinstance(ease, str) else ('EASE_IN_OUT' if ease else 'AUTO')
                    if not ease:
                        kp.handle_left_type = kp.handle_right_type = 'VECTOR'
    m = bpy.context.scene.timeline_markers.new('M_' + name, frame=s['f0'])
    m.camera = cam
    CAMS[name] = cam
    RIGS[name] = (rig, tgt, cd)
    SHAKE[name] = shake
    return cam


def eval_loc(ob, f):
    ad = ob.animation_data
    v = Vector(ob.location)
    if ad and ad.action:
        for fc in ad.action.fcurves:
            if fc.data_path == 'location':
                v[fc.array_index] = fc.evaluate(f)
    return v


def cam_state(name, f):
    rig, tgt, cd = RIGS[name]
    loc = eval_loc(rig, f)
    tl = eval_loc(tgt, f)
    return {'loc': tuple(loc), 'fwd': tuple((tl - loc).normalized())}


def shake_offset(t, name):
    amp = SHAKE.get(name, 0.0)
    if amp <= 0:
        return Vector((0, 0, 0))
    return Vector((math.sin(t * 7.0) + 0.5 * math.sin(t * 13.1), math.sin(t * 5.3 + 1), math.sin(t * 4.1 + 2))) * amp


def chest_pt(name, local):
    return jmat(CH[name]['J']['chest']) @ Vector(local)


def head_pt(name, local=(0, 0, 0)):
    return jmat(CH[name]['J']['neck']) @ (HC + Vector(local))


def hug(name, P, w=0.25, fwd=0.3, z=-0.12):
    pose(name, P)
    P['shR'], P['elR'] = reach(name, 'R', chest_pt(name, (w, fwd, z)))
    P['shL'], P['elL'] = reach(name, 'L', chest_pt(name, (-w, fwd, z)))
    return P


def idle(t, seed=0.0):
    """Small breathing / weight-shift motion."""
    return dict(chest=1.5 * math.sin(t * 1.7 + seed), side=1.2 * math.sin(t * 0.6 + seed), dz=0.006 * math.sin(t * 1.7 + seed))


def park(name, loc=(0, 0, -50)):
    pose(name, dict(loc=loc))


def cart_follow(cart_ob, P, dist=0.9):
    yaw = R(P['yaw'])
    x, y, _ = P['loc']
    cart_ob.location = (x - math.sin(yaw) * dist, y + math.cos(yaw) * dist, 0)
    cart_ob.rotation_euler = (0, 0, yaw)


def push_cart(name, P, cart_ob):
    cart_follow(cart_ob, P)
    M = cart_ob.matrix_basis
    pose(name, P)
    P['shR'], P['elR'] = reach(name, 'R', M @ Vector((0.18, -0.48, 1.08)))
    P['shL'], P['elL'] = reach(name, 'L', M @ Vector((-0.18, -0.48, 1.08)))
    return P


def set_face(P, **kw):
    P.update(kw)
    return P


def blend_face(a, b, u):
    out = {}
    for k in set(a) | set(b):
        va, vb = a.get(k, REST.get(k)), b.get(k, REST.get(k))
        if isinstance(va, tuple):
            out[k] = tuple(lerp(x, y, u) for x, y in zip(va, vb))
        else:
            out[k] = lerp(va, vb, u)
    return out


