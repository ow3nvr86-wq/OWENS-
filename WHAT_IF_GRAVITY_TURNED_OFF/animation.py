def smooth(x):
    x = min(max(x, 0.0), 1.0)
    return x * x * (3 - 2 * x)


def ramp(t, a, b):
    return smooth((t - a) / (b - a)) if b > a else float(t >= a)


def lin(t, a, b):
    return min(max((t - a) / (b - a), 0.0), 1.0) if b > a else float(t >= a)


def u_of(name, t):
    """0..1 progress of time t through a shot."""
    s = SHOT[name]
    return min(max((t - s['t0']) / (s['t1'] - s['t0']), 0.0), 1.0)


def lerp(a, b, u):
    return a + (b - a) * u


def vlerp(a, b, u):
    return Vector(a).lerp(Vector(b), u)


def path_at(pts, u):
    """Piecewise-linear interpolation along [(u, value), ...]."""
    if u <= pts[0][0]:
        return pts[0][1]
    for (u0, a), (u1, b) in zip(pts[:-1], pts[1:]):
        if u <= u1:
            k = (u - u0) / (u1 - u0) if u1 > u0 else 1.0
            if isinstance(a, (tuple, list, Vector)):
                return Vector(a).lerp(Vector(b), k)
            return a + (b - a) * k
    return pts[-1][1]


def hash01(a, b, salt=0.0):
    v = np.sin(a * 12.9898 + b * 78.233 + salt * 37.719) * 43758.5453
    return v - np.floor(v)


