def billboard_obj(name, n, mat):
    faces = np.arange(4 * n).reshape(n, 4)
    ob = mesh_obj(name, np.zeros((4 * n, 3)), faces, mat, collection='FX', smooth=False,
                  uvs=np.tile(np.array([[0, 0], [1, 0], [1, 1], [0, 1]], np.float32), (n, 1)))
    ob.data.color_attributes.new('sm', 'FLOAT_COLOR', 'CORNER')
    ob.visible_shadow = False
    ob.visible_diffuse = False
    return ob


def emitter(kind, src, rate, life, vel, spread, size, opacity=1.0, glow=0.0, area=0.5, t0=-10.0, t1=1e9,
            rise=0.0, turb=0.4, salt=0.0):
    return dict(kind=kind, src=np.atleast_2d(np.array(src, float)), rate=rate, life=life, vel=np.array(vel, float),
                spread=spread, size=size, opacity=opacity, glow=glow, area=area, t0=t0, t1=t1, rise=rise, turb=turb, salt=salt)


def eval_emitter(e, t):
    K = len(e['src'])
    slots = int(math.ceil(e['life'] * e['rate'])) + 1
    k = np.repeat(np.arange(K), slots)
    j = np.tile(np.arange(slots), K)
    phase = hash01(k, 0.5, e['salt'])
    i = np.floor((t - e['t0']) * e['rate'] - phase) - j
    tb = e['t0'] + (i + phase) / e['rate']
    age = t - tb
    ok = (age >= 0) & (age <= e['life']) & (tb <= e['t1']) & (i >= 0)
    k, i, age = k[ok], i[ok], age[ok]
    r1, r2, r3, r4 = (hash01(k + 0.1 * q, i, e['salt'] + q) for q in range(4))
    a = r1 * 2 * np.pi
    rr = np.sqrt(r2) * e['area']
    start = e['src'][k] + np.stack([rr * np.cos(a), rr * np.sin(a), (r3 - 0.5) * e['area']], -1)
    dirn = np.stack([np.cos(a + 1.3), np.sin(a + 1.3), (r3 - 0.5) * 0.6], -1)
    u = age / e['life']
    pos = start + e['vel'][None, :] * age[:, None] + dirn * (e['spread'] * age)[:, None]
    pos[:, 2] += 0.5 * e['rise'] * age ** 2
    pos += e['turb'] * np.stack([np.sin(age * 1.3 + r4 * 6.3), np.cos(age * 1.1 + r1 * 6.3), 0.5 * np.sin(age * 0.9 + r2 * 6.3)], -1)
    s0, s1 = e['size']
    size = (s0 + (s1 - s0) * u ** 0.6) * (0.7 + 0.6 * r3)
    alpha = e['opacity'] * np.clip(u / 0.12, 0, 1) * np.clip((1 - u) / 0.45, 0, 1)
    return pos, size, u, r4, alpha, np.full_like(u, e['glow'])


def cam_basis(cs):
    fwd = Vector(cs['fwd']).normalized()
    right = fwd.cross(Vector((0, 0, 1)))
    if right.length < 1e-4:
        right = Vector((1, 0, 0))
    right.normalize()
    up = right.cross(fwd).normalized()
    return np.array(right), np.array(up)


def update_particles(t, shot, cs):
    right, up = cam_basis(cs)
    groups = {k: [] for k in MAXQ}
    for e in EMIT.get(shot, []):
        if e['t0'] <= t:
            groups[e['kind']].append(eval_emitter(e, t))
    camp, fwd = np.array(cs['loc']), np.array(cs['fwd'])
    for kind in MAXQ:
        ob, n = PART[kind], MAXQ[kind]
        V = np.zeros((n, 4, 3))
        C = np.zeros((n, 4, 4))
        if groups[kind]:
            pos, size, u, seed, alpha, glow = (np.concatenate(x) for x in zip(*groups[kind]))
            rel = pos - camp
            d = np.linalg.norm(rel, axis=1)
            front = rel @ fwd > 0.1
            pos, size, u, seed, alpha, glow, d = (a[front] for a in (pos, size, u, seed, alpha, glow, d))
            if kind == 'dot':
                size = size + 0.0012 * d
            if len(pos) > n:
                idx = np.argsort(d)[:n]
                pos, size, u, seed, alpha, glow, d = (a[idx] for a in (pos, size, u, seed, alpha, glow, d))
            m = len(pos)
            alpha = alpha * np.clip((d - size * 0.8) / (size * 1.5 + 0.2), 0, 1)
            rr, uu = right[None, :] * size[:, None], up[None, :] * size[:, None]
            V[:m] = np.stack([pos - rr - uu, pos + rr - uu, pos + rr + uu, pos - rr + uu], 1)
            C[:m] = np.stack([seed, u, glow, alpha], -1)[:, None, :]
        me = ob.data
        me.vertices.foreach_set('co', V.astype(np.float32).ravel())
        me.color_attributes['sm'].data.foreach_set('color', C.astype(np.float32).ravel())
        me.update()


