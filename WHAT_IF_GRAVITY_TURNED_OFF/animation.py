def cloth_mat(name, color, rough=0.85, weave=60.0):
    m, nt, out = new_mat(name)
    oc = obj_coord(nt)
    w = nd(nt, 'ShaderNodeTexWave', Scale=weave, Distortion=0.0, Vector=oc, p_wave_type='BANDS').outputs['Fac']
    n = noise(nt, 6.0, 2.0, 0.5, vec=oc)
    f = mth(nt, 'ADD', mth(nt, 'MULTIPLY', w, 0.08), mth(nt, 'MULTIPLY', n, 0.18))
    base = mixc(nt, f, rgba(color), rgba([c * 0.6 for c in color]))
    principled(nt, out, **{'Base Color': base, 'Roughness': rough, 'Sheen Weight': 0.4, 'Specular IOR Level': 0.3})
    MAT[name] = m
    return m


