COLL = {}


def coll(name):
    if name not in COLL:
        c = bpy.data.collections.new(name)
        bpy.context.scene.collection.children.link(c)
        COLL[name] = c
    return COLL[name]


def template_collection(name):
    c = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(c)
    bpy.context.view_layer.layer_collection.children[name].exclude = True
    COLL[name] = c
    return c


def link(ob, collection):
    coll(collection).objects.link(ob)
    return ob


def mesh_obj(name, verts, faces, mat=None, collection='World', smooth=True, loc=(0, 0, 0), uvs=None):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], [], [tuple(f) for f in faces])
    me.update()
    if uvs is not None:
        uvl = me.uv_layers.new(name='UVMap')
        uvl.data.foreach_set('uv', np.asarray(uvs, np.float32).ravel())
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    ob.location = loc
    if mat is not None:
        for m in (mat if isinstance(mat, (list, tuple)) else [mat]):
            me.materials.append(m)
    coll(collection).objects.link(ob)
    return ob


def obj_from_bm(name, bm, mats=None, collection='World', smooth=False, loc=(0, 0, 0)):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    ob.location = loc
    if mats is not None:
        for m in (mats if isinstance(mats, (list, tuple)) else [mats]):
            me.materials.append(m)
    coll(collection).objects.link(ob)
    return ob


def _set_mi(bm, verts, mi):
    if not mi:
        return
    vs = set(verts)
    for f in bm.faces:
        if f.verts[0] in vs:
            f.material_index = mi


def add_box(bm, x0, y0, z0, x1, y1, z1, matrix=Matrix(), mi=0):
    m = matrix @ Matrix.Translation(((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)) @ Matrix.Diagonal(
        (abs(x1 - x0), abs(y1 - y0), abs(z1 - z0), 1))
    r = bmesh.ops.create_cube(bm, size=1.0, matrix=m)
    _set_mi(bm, r['verts'], mi)


def add_cyl(bm, r1, r2, depth, seg=12, matrix=Matrix(), mi=0, caps=True):
    r = bmesh.ops.create_cone(bm, cap_ends=caps, cap_tris=False, segments=seg, radius1=r1, radius2=r2,
                              depth=depth, matrix=matrix)
    _set_mi(bm, r['verts'], mi)


def add_sphere(bm, r, u=12, v=8, matrix=Matrix(), mi=0):
    res = bmesh.ops.create_uvsphere(bm, u_segments=u, v_segments=v, radius=r, matrix=matrix)
    _set_mi(bm, res['verts'], mi)
    return res['verts']


def add_ellipsoid(bm, c, radii, u=16, v=10, mi=0, rot=Matrix()):
    m = Matrix.Translation(c) @ rot.to_4x4() @ Matrix.Diagonal((radii[0], radii[1], radii[2], 1))
    return add_sphere(bm, 1.0, u, v, m, mi)


def add_sbox(bm, c, half, e=0.3, u=16, v=10, mi=0, rot=Matrix()):
    """Rounded box (superellipsoid): e -> 0 is a sharp box, e = 1 an ellipsoid."""
    vs = add_sphere(bm, 1.0, u, v, Matrix(), mi)
    rm = rot.to_4x4() if rot.__class__ is Matrix and len(rot) == 3 else rot
    for vt in vs:
        p = vt.co
        q = Vector([math.copysign(abs(p[i]) ** e, p[i]) * half[i] for i in range(3)])
        vt.co = Matrix.Translation(c) @ rm @ q
    return vs


def seg_matrix(p0, p1):
    """Matrix mapping a unit cylinder along +Z centred at the origin onto segment p0-p1 (length via depth)."""
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    q = Vector((0, 0, 1)).rotation_difference(d.normalized())
    return Matrix.Translation((p0 + p1) / 2) @ q.to_matrix().to_4x4()


def add_capsule(bm, p0, p1, r0, r1=None, seg=10, mi=0, caps=True):
    r1 = r0 if r1 is None else r1
    p0, p1 = Vector(p0), Vector(p1)
    L = (p1 - p0).length
    add_cyl(bm, r0, r1, L, seg=seg, matrix=seg_matrix(p0, p1), mi=mi, caps=False)
    if caps:
        add_sphere(bm, r0, seg, max(4, seg // 2 + 1), Matrix.Translation(p0), mi)
        add_sphere(bm, r1, seg, max(4, seg // 2 + 1), Matrix.Translation(p1), mi)


