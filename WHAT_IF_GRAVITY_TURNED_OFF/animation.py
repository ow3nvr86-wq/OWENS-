def chor_space(t, name):
    root = SPACED['root']
    s = t - SHOT[name]['t0']
    if name == 'globe':
        root.rotation_euler = (R(-12), 0, 0.10 * s + 0.5)
        SPACED['clouds'].rotation_euler = (0, 0, 0.012 * s)
        for k in ('marker', 'free'):
            SPACED[k].location = SPACE + Vector((0, 0, -500))
        for nm in ('TangentLine', 'GapLine', 'GroundArc'):
            set_quads(SPACED[nm][0], np.zeros((200, 4, 3)))
        return
    # the illustration: the Earth turns (fast, for clarity); a free point keeps going straight
    root.rotation_euler = (0, 0, 0)
    om = 0.24
    s1 = max(0.0, s - 0.6)
    th0 = -math.pi / 2
    th = th0 + om * s1 + 0.0
    Rr = EARTH_R * 1.006
    root.rotation_euler = (0, 0, om * s1)
    mk = SPACE + Vector((Rr * math.cos(th), Rr * math.sin(th), 0.6))
    p0 = SPACE + Vector((Rr * math.cos(th0), Rr * math.sin(th0), 0.6))
    tdir = Vector((-math.sin(th0), math.cos(th0), 0))
    free = p0 + tdir * (om * Rr * s1)
    SPACED['marker'].location = mk
    SPACED['free'].location = free
    cam = Vector(CUR.get('camloc', (0, 0, 0)))
    line = [p0 - tdir * 25 + tdir * (110 * i / 200) for i in range(201)]
    set_quads(SPACED['TangentLine'][0], tube_quads(line, SPACED['TangentLine'][1] * ramp(s, 0.2, 0.6), cam))
    arc = [SPACE + Vector((Rr * math.cos(th0 + (th - th0) * i / 199), Rr * math.sin(th0 + (th - th0) * i / 199), 0.6)) for i in range(201)]
    set_quads(SPACED['GroundArc'][0], tube_quads(arc, SPACED['GroundArc'][1], cam))
    gap = [mk.lerp(free, i / 200) for i in range(201)] if s1 > 0.05 else [mk] * 201
    q = tube_quads(gap, SPACED['GapLine'][1], cam) if s1 > 0.05 else np.zeros((200, 4, 3))
    set_quads(SPACED['GapLine'][0], q)


