    t = _tt(dur)
    n = np.random.default_rng(seed).standard_normal(len(t))
    return _norm(_sweep_bp(n, lambda tc: 900 + 1600 * tc / dur, q=3.0, block=1024)) * np.sin(np.pi * t / dur)


