CH = {}
HC = Vector((0, 0, 0.17))                   # head centre in neck-joint space
HEAD_R = (0.125, 0.13, 0.145)


def on_head(x, z, out=0.0):
    a, b, c = HEAD_R
    k = 1 - (x / a) ** 2 - (z / c) ** 2
    return HC + Vector((x, b * math.sqrt(max(k, 0.0)) + out, z))


def part(name, bm, mats, parent, collection, smooth=True, loc=(0, 0, 0)):
    ob = obj_from_bm(name, bm, mats, collection, smooth=smooth)
    ob.parent = parent
    ob.location = loc
    return ob


def hair_mesh(bm, style, mi=0):
    a, b, c = HEAD_R
    vs = add_ellipsoid(bm, HC, (a * 1.07, b * 1.07, c * 1.09), 24, 14, mi)
    kill = []
    for v in vs:
        p = v.co - HC
        y = p.y
        if style == 'bald':
            keep = -0.05 < p.z < 0.035 and y < 0.03
        else:
            hl = 0.035 + 0.06 * min(max(y / 0.13, 0), 1) - 0.11 * min(max(-y / 0.13, 0), 1)
            keep = p.z > hl
        if not keep:
            kill.append(v)
    bmesh.ops.delete(bm, geom=kill, context='VERTS')
    if style == 'ponytail':
        add_ellipsoid(bm, HC + Vector((0, -0.15, 0.02)), (0.05, 0.06, 0.07), 12, 8, mi)
        add_ellipsoid(bm, HC + Vector((0, -0.17, -0.1)), (0.04, 0.045, 0.1), 12, 8, mi)
    if style == 'bun':
        add_ellipsoid(bm, HC + Vector((0, -0.08, 0.15)), (0.06, 0.06, 0.055), 12, 8, mi)
    if style == 'quiff':
        add_ellipsoid(bm, HC + Vector((0, 0.07, 0.13)), (0.09, 0.07, 0.05), 12, 8, mi)


def mouth_shapes():
    N = 10
    top = np.linspace(1, -1, N)
    bot = np.linspace(-1, 1, N)[1:-1]

    def key(w, ftop, fbot, zc=-0.062):
        pts = [(w * x, zc + ftop(x)) for x in top] + [(w * x, zc + fbot(x)) for x in bot]
        cz = np.mean([p[1] for p in pts])
        pts.append((0.0, cz))
        return [tuple(on_head(x, z, 0.003)) for x, z in pts]
    sq = lambda x: math.sqrt(max(1 - x * x, 0))
    shapes = {
        'neutral': key(0.03, lambda x: 0.0028, lambda x: -0.0028),
        'smile': key(0.045, lambda x: 0.004 + 0.013 * x * x, lambda x: -0.018 + 0.03 * x * x),
        'open': key(0.026, lambda x: 0.016 * sq(x), lambda x: -0.04 * sq(x)),
        'frown': key(0.032, lambda x: 0.004 - 0.014 * x * x, lambda x: -0.0015 - 0.014 * x * x),
    }
    n = len(shapes['neutral'])
    faces = [(n - 1, i, (i + 1) % (n - 1)) for i in range(n - 1)]
    return shapes, faces


