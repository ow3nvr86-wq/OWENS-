def gz_street(x, y):
    """Ground height (top surface) at a point of the street set."""
    if abs(x) < 6.5:
        return 0.0
    dx, dy = x - FOUNTAIN.x, y - FOUNTAIN.y
    if dx * dx + dy * dy < 4.6 ** 2:
        return 0.70
    return 0.15


def building(name, collection, x0, y0, x1, y1, h, fac, shop=None, awning=None, side=1):
    bm = bmesh.new()
    add_box(bm, x0, y0, 3.6, x1, y1, h, mi=0)
    # ground-floor shopfront: dark glass with a frame, set back a little
    fx = x0 if side > 0 else x1                    # the street-facing face
    inset = 0.15 * (1 if side > 0 else -1)
    add_box(bm, min(fx, fx + inset), y0, 0, max(fx, fx + inset) + (0 if side > 0 else 0), y1, 3.6, mi=1)
    add_box(bm, min(x0, x1) + (0.15 if side > 0 else 0), y0, 0, max(x0, x1) - (0 if side > 0 else 0.15), y1, 3.6, mi=2)
    add_box(bm, min(fx, fx - 0.25 * side), y0, 3.45, max(fx, fx - 0.25 * side), y1, 3.75, mi=3)     # fascia band
    add_box(bm, min(fx, fx - 0.4 * side), y0, h - 0.5, max(fx, fx - 0.4 * side), y1, h, mi=3)        # cornice
    for yy in np.arange(y0 + 0.2, y1, 3.0):                                                       # mullions
        add_box(bm, min(fx, fx - 0.08 * side), yy, 0, max(fx, fx - 0.08 * side), yy + 0.16, 3.5, mi=3)
    ob = obj_from_bm(name, bm, [MAT[fac], MAT['shopglass'], MAT['shop_in'], MAT['trim_stone']], collection)
    if shop:
        card(name + '_sign', MAT[shop], min(6.0, (y1 - y0) * 0.7), 0.75, Vector((fx - 0.27 * side, (y0 + y1) / 2, 3.6)),
             yaw=-90 if side > 0 else 90, collection=collection)
    if awning:
        bm = bmesh.new()
        ax = fx - side * 2.3
        add_quad(bm, [(fx - 0.02 * side, y0 + 0.5, 3.35), (fx - 0.02 * side, y1 - 0.5, 3.35), (ax, y1 - 0.5, 2.6), (ax, y0 + 0.5, 2.6)][::(1 if side < 0 else -1)], mi=0)
