def ico(sub=2):
    if sub not in _ICO:
        bm = bmesh.new()
        bmesh.ops.create_icosphere(bm, subdivisions=sub, radius=1.0)
        v = np.array([tuple(x.co) for x in bm.verts])
        f = [tuple(x.index for x in fc.verts) for fc in bm.faces]
        bm.free()
        _ICO[sub] = (v, f)
    return _ICO[sub]


def tree_skeleton(height, seed, spread=1.0):
    """Branch segments [(p0, p1, r0, r1)] and clumps [(centre, radius)] in tree-local coordinates."""
    rng = np.random.default_rng(seed)
    segs, clumps = [], []
    trunk_h = height * 0.42
    r_trunk = height * 0.035
    base = np.array([0.0, 0.0, 0.0])
    top = np.array([rng.normal(0, 0.03 * height), rng.normal(0, 0.03 * height), trunk_h])
    segs.append((base, top, r_trunk * 1.25, r_trunk))

    def grow(p, d, length, r, depth):
        q = p + d * length
        segs.append((p, q, r, r * 0.65))
        if depth == 0:
            clumps.append((q, length * 0.9 + height * 0.09))
            return
        k = 2 if depth > 1 else 3
        for i in range(k):
            a = rng.uniform(0, 2 * math.pi)
            nd_ = d + np.array([math.cos(a), math.sin(a), 0.0]) * rng.uniform(0.5, 0.9) * spread + np.array([0, 0, 0.35])
            nd_ /= np.linalg.norm(nd_)
            grow(q, nd_, length * rng.uniform(0.6, 0.78), r * 0.62, depth - 1)
        if depth == 1:
            clumps.append((q + np.array([0, 0, length * 0.2]), length * 0.8 + height * 0.06))
    nb = 4
    for i in range(nb):
        a = 2 * math.pi * i / nb + rng.normal(0, 0.3)
        d = np.array([math.cos(a) * 0.75 * spread, math.sin(a) * 0.75 * spread, 0.85])
        d /= np.linalg.norm(d)
        grow(top, d, height * 0.24, r_trunk * 0.7, 2)
    clumps.append((top + np.array([0, 0, height * 0.42]), height * 0.2))
    return segs, clumps


def make_tree(name, collection, origin, height, seed, n_bills=600, n_leaves=1500, bill_scale=1.0, spread=1.0,
              leaf_mat='leaves', sway=True, bark_seg=8, clump_scale=1.0, hang_low=0.25):
    rng = np.random.default_rng(seed + 100)
    segs, clumps = tree_skeleton(height, seed, spread)
    clumps = [(c, r * clump_scale) for c, r in clumps]
    o = Vector(origin)
    bm = bmesh.new()
    for p0, p1, r0, r1 in segs:
        add_capsule(bm, p0, p1, r0, r1, seg=bark_seg, caps=False)
        add_sphere(bm, r1, bark_seg, 5, Matrix.Translation(Vector(p1)))
    trunk = obj_from_bm(name + '_trunk', bm, MAT['bark'], collection, smooth=True, loc=o)
    # clumps: displaced icospheres
    iv, iface = ico(2)
    V, Fc = [], []
    for k, (c, r) in enumerate(clumps):
        ph = rng.uniform(0, 10, 3)
        d = iv
        disp = 1.0 + 0.16 * np.sin(d @ np.array([5.1, 3.7, 4.3]) + ph[0]) + 0.12 * np.sin(d @ np.array([-3.3, 6.1, 2.7]) * 1.7 + ph[1])
        sq = np.array([1.0, 1.0, 0.78])
        V.append(c + d * (r * disp)[:, None] * sq)
        Fc += [tuple(i + k * len(iv) for i in f) for f in iface]
    leaves = mesh_obj(name + '_clumps', np.concatenate(V), Fc, MAT[leaf_mat], collection, smooth=True, loc=o)
    # leaf polygons on the clump surfaces
    if n_leaves:
        allc = np.array([c for c, r in clumps])
        allr = np.array([r for c, r in clumps])
        ci = rng.choice(len(clumps), n_leaves, p=allr ** 2 / (allr ** 2).sum())
        d = rng.normal(0, 1, (n_leaves, 3))
        d /= np.linalg.norm(d, axis=1)[:, None]
        pos = allc[ci] + d * allr[ci, None] * rng.uniform(0.92, 1.08, (n_leaves, 1)) * np.array([1, 1, 0.78])
        L = 0.09 * height / 6.0 + 0.04
        a = rng.normal(0, 1, (n_leaves, 3))
        U = np.cross(d, a)
        U /= np.linalg.norm(U, axis=1)[:, None]
        Vv = np.cross(d, U)
        tilt = d * 0.35
        Vv = Vv + tilt
        Vv /= np.linalg.norm(Vv, axis=1)[:, None]
        prof = [(0, 0), (0.25, 0.32), (0.55, 0.38), (0.8, 0.25), (1.0, 0.0)]
        pts = []
        for s, wv in prof:
            pts.append((s, wv))
        for s, wv in prof[-2:0:-1]:
            pts.append((s, -wv))
        npt = len(pts)
        verts = np.zeros((n_leaves, npt, 3))
        for j, (s, wv) in enumerate(pts):
            verts[:, j] = pos + U * (s * L) + Vv * (wv * L * 0.55)
        faces = [tuple(range(i * npt, (i + 1) * npt)) for i in range(n_leaves)]
        mesh_obj(name + '_leaves', verts.reshape(-1, 3), faces, MAT[leaf_mat], collection, smooth=False, loc=o)
    # hanging banknotes: anchored on the lower/outer part of the clumps
    info = None
    if n_bills:
        allc = np.array([c for c, r in clumps])
        allr = np.array([r for c, r in clumps])
        ci = rng.choice(len(clumps), n_bills, p=allr ** 2 / (allr ** 2).sum())
        az = rng.uniform(0, 2 * math.pi, n_bills)
        el = rng.uniform(-0.75, hang_low, n_bills)
        d = np.stack([np.cos(az) * np.cos(el), np.sin(az) * np.cos(el), np.sin(el)], 1)
        anchor = allc[ci] + d * allr[ci, None] * np.array([1, 1, 0.78]) * rng.uniform(0.95, 1.05, (n_bills, 1))
        face = az + rng.normal(0, 0.5, n_bills)                   # direction the note faces (horizontal)
        N = np.stack([np.cos(face), np.sin(face), np.zeros(n_bills)], 1)
        U = np.stack([-np.sin(face), np.cos(face), np.zeros(n_bills)], 1)
        hang = rng.normal(0, 0.25, n_bills)                       # rest tilt
        ob = quad_mesh(name + '_bills', n_bills, MAT['bill'], collection)
        ob.location = o
        info = dict(ob=ob, anchor=anchor, N=N, U=U, hang=hang, ph=rng.uniform(0, 6.3, n_bills),
                    fr=rng.uniform(1.2, 2.4, n_bills), size=(BILL[0] * bill_scale, BILL[1] * bill_scale), sway=sway, hidden=None)
        update_tree_bills(info, 0.0, 1.0)
    TREES[name] = dict(trunk=trunk, clumps=leaves, info=info, segs=segs, clumpdata=clumps, origin=o)
    return TREES[name]


def update_tree_bills(info, t, amp=1.0, hidden=None):
    """Each note hangs from its top edge and swings gently in the breeze."""
    sw = info['hang'] + (0.18 * amp * np.sin(info['fr'] * t + info['ph']) if info['sway'] else 0.0)
    N, U = info['N'], info['U']
    Z = np.array([0, 0, 1.0])
    D = -np.cos(sw)[:, None] * Z + np.sin(sw)[:, None] * N           # down the note
    w, h = info['size'][0] / 2, info['size'][1]
    a = info['anchor']
    V = np.stack([a - U * w + D * h, a + U * w + D * h, a + U * w, a - U * w], 1)
    if hidden is not None:
        V[hidden] = 0.0
    set_quads(info['ob'], V)


def tree_points(name, n, seed, lower=True):
    """Points on the canopy (world space) for falling-note emitters."""
    T = TREES[name]
    rng = np.random.default_rng(seed)
    cl = T['clumpdata']
    allc = np.array([c for c, r in cl])
    allr = np.array([r for c, r in cl])
    ci = rng.choice(len(cl), n)
    az = rng.uniform(0, 2 * math.pi, n)
    el = rng.uniform(-0.6, 0.1 if lower else 0.8, n)
    d = np.stack([np.cos(az) * np.cos(el), np.sin(az) * np.cos(el), np.sin(el)], 1)
    return np.array(T['origin']) + allc[ci] + d * allr[ci, None] * 0.95

