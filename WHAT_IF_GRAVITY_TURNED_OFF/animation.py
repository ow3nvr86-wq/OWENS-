def city_facade(name, wall, glass, cw=3.0, rh=3.4):
    """Window grid: one window per bay (cw wide) per floor (rh high), with sills, per-window tint and blinds."""
    m, nt, out = new_mat(name)
    oc = nd(nt, 'ShaderNodeTexCoord').outputs['Object']
    s_ = sep(nt, oc)
    h = mth(nt, 'ADD', s_.outputs['X'], s_.outputs['Y'])
    z = s_.outputs['Z']
    u = mth(nt, 'FRACT', mth(nt, 'DIVIDE', h, cw))
    v = mth(nt, 'FRACT', mth(nt, 'DIVIDE', z, rh))
    win = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', u, 0.18), mth(nt, 'LESS_THAN', u, 0.82)),
              mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', v, 0.28), mth(nt, 'LESS_THAN', v, 0.86)))
    sill = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', u, 0.14), mth(nt, 'LESS_THAN', u, 0.86)),
               mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', v, 0.24), mth(nt, 'LESS_THAN', v, 0.28)))
    cell = comb(nt, mth(nt, 'FLOOR', mth(nt, 'DIVIDE', h, cw)), mth(nt, 'FLOOR', mth(nt, 'DIVIDE', z, rh)), 0.0)
    rnd = nd(nt, 'ShaderNodeTexWhiteNoise', p_noise_dimensions='3D', Vector=cell).outputs['Value']
    blind = mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', v, mth(nt, 'MULTIPLY_ADD', rnd, -0.5, 0.95)), mth(nt, 'GREATER_THAN', rnd, 0.45))
    gcol = mixc(nt, mth(nt, 'MULTIPLY', rnd, 0.7), rgba(glass), rgba([min(1, c * 1.8) for c in glass]))
    gcol = mixc(nt, blind, gcol, (0.70, 0.66, 0.58, 1))
    n = noise(nt, 0.35, 3.0, 0.55, vec=oc)
    wcol = mixc(nt, mth(nt, 'MULTIPLY', n, 0.45), rgba(wall), rgba([c * 0.72 for c in wall]))
    wcol = mixc(nt, sill, wcol, (0.78, 0.76, 0.72, 1))
    col = mixc(nt, win, wcol, gcol)
    rough = mth(nt, 'ADD', mth(nt, 'MULTIPLY', win, -0.72), 0.82)
    principled(nt, out, **{'Base Color': col, 'Roughness': rough, 'Specular IOR Level': mth(nt, 'ADD', mth(nt, 'MULTIPLY', win, 0.5), 0.35)})
    MAT[name] = m


