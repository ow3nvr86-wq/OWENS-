def tube_quads(pts, r, cam):
    """Camera-facing ribbon along a polyline (for glowing lines)."""
    P = np.asarray(pts, float)
    d = np.diff(P, axis=0)
    d /= np.linalg.norm(d, axis=1)[:, None] + 1e-9
    to_cam = np.asarray(cam, float)[None, :] - P[:-1]
    side = np.cross(d, to_cam)
    side /= np.linalg.norm(side, axis=1)[:, None] + 1e-9
    side *= r
    return np.stack([P[:-1] - side, P[1:] - side, P[1:] + side, P[:-1] + side], 1)


# ============================================================================
# The physics of the scenario (sim time tau, in seconds; gravity is off for 0 <= tau < 10)
#
#   tau < 0       normal life: things rest on the ground or move with their everyday velocity
#   0 <= tau < 10 no pull from Earth: every free object keeps its velocity (Newton's first law). The only
#                 acceleration left relative to the street is the apparent one from Earth's spin: the ground
#                 turns away beneath anything moving in a straight line. Near the equator that is
#                 omega^2 * R = (7.292e-5)^2 * 6.378e6 = 0.0339 m/s^2 "upward" -> 1.7 m after 10 s.
#   tau >= 10     gravity is back (9.81 m/s^2): everything falls with the velocity it already had; contacts
#                 with the ground bounce a little, slide and settle.
# Springs (car suspension) were squeezed by each car's weight; with no weight they push the car up (an estimate,
# used for the look only, and stated as such in README.txt).
# ============================================================================
A_UP = 0.0339
G = 9.81
T_RET = 10.0
SIM = {}
SDT = 1.0 / 240.0


class Body:
    def __init__(self, name, p0, v0=(0, 0, 0), vpre=(0, 0, 0), rot0=(0, 0, 0), w=(0, 0, 0), bottom=0.0, e=0.22,
                 mu=5.0, ground=None, settle=None, obj=None, fixed_pre=False):
        self.name, self.obj = name, obj
        self.p0, self.v0, self.vpre = np.array(p0, float), np.array(v0, float), np.array(vpre, float)
        self.rot0, self.w = np.array(rot0, float), np.array(w, float)
        self.bottom, self.e, self.mu = bottom, e, mu
        self.ground = ground or gz_street
        self.settle = settle
        self._post()
        SIM[name] = self

    def free(self, tau):
        return self.p0 + self.v0 * tau + np.array([0, 0, 0.5 * A_UP * tau * tau])

    def _post(self):
        n = int(30.0 / SDT)
        P = np.zeros((n, 3))
        RT = np.zeros((n, 3))
        p = self.free(T_RET).copy()
        v = self.v0 + np.array([0, 0, A_UP * T_RET])
        rot = self.rot0 + self.w * T_RET
        landed = None
        rl = None
        for i in range(n):
            tau = T_RET + i * SDT
            v[2] -= G * SDT
            p = p + v * SDT
            gzv = self.ground(p[0], p[1]) + self.bottom
            if p[2] <= gzv:
                p[2] = gzv
                if v[2] < 0:
                    if landed is None:
                        landed = tau
                        self.v_impact = -v[2]
                        rl = rot.copy()
                    v[2] = -self.e * v[2] if -v[2] > 1.2 else 0.0
                    v[:2] *= 0.55
                if abs(v[2]) < 1e-6:
                    sp = np.linalg.norm(v[:2])
                    if sp > 0:
                        v[:2] *= max(0.0, sp - self.mu * SDT) / sp
            if landed is None:
                rot = rot + self.w * SDT
            else:
                tgt = np.array(self.settle if self.settle is not None else (0.0, 0.0, rl[2]))
                k = min(1.0, (tau - landed) / 0.3)
                rot = rl + (tgt - rl) * (k * k * (3 - 2 * k))
            P[i], RT[i] = p, rot
        self.P, self.RT = P, RT
        self.t_land = landed if landed is not None else 1e9
        if landed is None:
            self.v_impact = 0.0

    def state(self, tau):
        if tau < 0:
            return self.p0 + self.vpre * tau, self.rot0.copy()
        if tau < T_RET:
            return self.free(tau), self.rot0 + self.w * tau
        i = min(int((tau - T_RET) / SDT), len(self.P) - 1)
        return self.P[i].copy(), self.RT[i].copy()

    def land_u(self, tau):
        """0 before landing, then 0->1 over the first 0.35 s after touching down."""
        return min(max((tau - self.t_land) / 0.35, 0.0), 1.0)


