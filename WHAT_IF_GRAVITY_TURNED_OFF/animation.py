"""WHAT IF GRAVITY TURNED OFF FOR 10 SECONDS?
A fully code-generated, cinematic 3D YouTube Short (1080x1920, 30 fps, 58.3 s): a hypothetical science scenario.
Earth's pull switches off for ten seconds: nothing rockets into the sky - everything simply keeps the motion it had,
while the ground turns away beneath it - and then gravity comes back.

Everything is generated by this Blender (bpy) script: a city street (cafe, shops, bus stop, parked and moving cars,
a plaza with a fountain, a park with a basketball court), an apartment interior, Earth in space with an illustration
of "straight line vs. curved ground", an airliner, a cast of reusable stylised characters and a dog, a small physics
model of the scenario (free motion, Earth-spin drift, return of gravity with landings and bounces), thousands of
fountain droplets, the lighting, cameras, compositor grade, synthesised music and sound design, the edit (titles,
countdown, word-by-word captions, grain, vignette) and the MP4 encode. Printed props come from tools/textures.py.

Accuracy notes (see sources.txt): the scenario is hypothetical and labelled on screen; numbers on screen are verified
(Earth's equatorial spin ~1,670 km/h; the ~1.7 m drift near the equator after 10 s follows from it); visuals that
are estimates (car springs, people's push-off speeds, slow motion) are listed in README.txt.

Run with Blender 4.2 LTS (headless):
  blender -b --factory-startup -P animation.py -- [options]

Stages (default: render):
  --stage render   build the 3D scene and render frames to renders/frames/
  --stage audio    synthesise music + sound design, mix with the narration (audio/*.wav, sound_design.txt)
  --stage edit     assemble frames, titles, countdown, captions, grain and audio in the Video Sequencer; encode
  --stage all      render + audio + edit

Options:
  --quality preview|final         preview = 270x480, 4 samples; final = 540x960, 6 samples (upscaled 2x in the edit)
  --frames A-B                    render only this frame range (resumable: existing frames are kept)
  --stills F1,F2,...              render single frames (look-dev checks)
  --out DIR                       frame folder (default renders/frames)
  --no-voice                      edit stage: leave the narration and captions out (to record your own voice)
  --output NAME                   edit stage: output file name
  --bitrate KBPS                  edit stage: video bitrate
  --save-blend PATH               also save the generated .blend

Timing comes from scene_timing.json (and build/vo_timing.json once tools/voiceover.py has run).
"""
