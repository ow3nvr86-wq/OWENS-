def update_litter(tau):
    L = LITTER
    p0, v0 = L['p0'], L['v0']
    n = len(p0)
    if tau < 0:
        p = p0.copy()
        ang = np.zeros((n, 3))
    elif tau < T_RET:
        p = p0 + v0 * tau
        p[:, 2] += 0.5 * A_UP * tau * tau
        ang = L['w'] * tau
    else:
        s = tau - T_RET
        p10 = p0 + v0 * T_RET
        p10[:, 2] += 0.5 * A_UP * T_RET ** 2
        # light paper falls at ~1 m/s terminal speed, fluttering
        z = p10[:, 2] + v0[:, 2] * min(s, 0.3) - np.minimum(s * 1.0, 0.5 * G * s * s)
        floor = np.where(np.abs(p10[:, 0]) > 6.5, 0.153, 0.004)
        p = p10 + v0 * s * 0.3
        p[:, 0] += 0.06 * np.sin(3.0 * s + L['ph'])
        p[:, 2] = np.maximum(z, floor)
        landed = z <= floor
        ang = L['w'] * T_RET + L['w'] * s
        ang[landed, 0] = 0.0
        ang[landed, 1] = 0.0
    yaw = L['yaw'] + ang[:, 2]
    cp, sp, cr, sr = np.cos(ang[:, 0]), np.sin(ang[:, 0]), np.cos(ang[:, 1]), np.sin(ang[:, 1])
    cy, sy = np.cos(yaw), np.sin(yaw)
    U = np.stack([cy * cr, sy * cr, sr], 1)
    V = np.stack([-sy * cp, cy * cp, sp], 1)
    w = 0.05 * L['size'][:, None]
    h = 0.07 * L['size'][:, None]
    Q = np.stack([p - U * w - V * h, p + U * w - V * h, p + U * w + V * h, p - U * w + V * h], 1)
    set_quads(L['ob'], Q)


