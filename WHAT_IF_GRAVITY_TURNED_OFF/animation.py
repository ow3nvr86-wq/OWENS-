def emission_mat(name, color, strength, key=None):
    m, nt, out = new_mat(name)
    s = value(nt, key, strength) if key else strength
    e = nd(nt, 'ShaderNodeEmission', Color=rgba(color), Strength=s)
    nt.links.new(e.outputs[0], out.inputs['Surface'])
    MAT[name] = m
    if key:
        register_value(m, key, key)
    return m


def image_mat(name, tex, rough=0.6, glow=0.0, back=None, alpha=False, spec=0.4, proj=None, scale=1.0):
    """Image-textured material. back = colour shown on back faces (cards, tags)."""
    m, nt, out = new_mat(name)
    t = nd(nt, 'ShaderNodeTexImage', p_image=teximg(tex), p_interpolation='Linear', p_extension='REPEAT' if proj else 'EXTEND')
    if proj == 'BOX':
        t.projection = 'BOX'
        t.projection_blend = 0.3
        v = nd(nt, 'ShaderNodeVectorMath', p_operation='SCALE', Vector=obj_coord(nt))
        v.inputs['Scale'].default_value = scale
        nt.links.new(v.outputs[0], t.inputs['Vector'])
    col = t.outputs['Color']
    if back is not None:
        bf = nd(nt, 'ShaderNodeNewGeometry').outputs['Backfacing']
        col = mixc(nt, bf, col, rgba(back))
    p = principled(nt, out, **{'Base Color': col, 'Roughness': rough, 'Specular IOR Level': spec})
    if alpha:
        nt.links.new(t.outputs['Alpha'], p.inputs['Alpha'])
    if glow:
        nt.links.new(col, p.inputs['Emission Color'])
        p.inputs['Emission Strength'].default_value = glow
    MAT[name] = m
    return m


