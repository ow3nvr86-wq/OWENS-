def tau_at(name, t):
    k = TAUK.get(name)
    if k is None:
        return None
    return float(np.interp(t, k[:, 0], k[:, 1]))


def t_of_tau(name, tau):
    """Inverse of tau_at for a shot (video time at which sim time tau is shown), or None."""
    k = TAUK.get(name)
    if k is None or not (k[0, 1] <= tau <= k[-1, 1]):
        return None
    return float(np.interp(tau, k[:, 1], k[:, 0]))


