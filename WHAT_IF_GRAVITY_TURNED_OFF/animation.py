def build_emitters():
    def motes(name, centre, area=6.0, rate=60.0):
        EMIT.setdefault(name, []).append(emitter('dot', [centre], rate, 6.0, (0.0, 0.0, 0.02), 0.03, (0.006, 0.01), opacity=0.45,
                                                 area=area, t0=SHOT[name]['t0'] - 6.0, rise=0.0, turb=0.25, salt=len(EMIT.get(name, []))))
    for nm, c in (('cup', M_(0.2, 0.8, 1.6)), ('street', (-6.5, 0.0, 1.5)), ('hoop', (23.0, 43.0, 2.5)), ('dog', (7.5, 0.5, 1.2)),
                  ('room', Rm(0.5, 0.5, 1.4)), ('traffic', (1.0, 38.0, 1.5)), ('wide', (-3.0, 8.0, 3.0)), ('table', (-8.6, 8.4, 1.0)),
                  ('tension', MAYA_AT + Vector((0.5, 0.5, 2.6))), ('aftermath', (-3.0, 4.0, 2.0)), ('coffee', M_(0.2, 0.6, 1.5)),
                  ('plane', (-7.0, 6.0, 3.0))):
        motes(nm, c, 4.0 if nm in ('cup', 'coffee', 'table', 'tension', 'room', 'dog') else 10.0, 40.0 if nm in ('cup', 'coffee') else 70.0)

    # impact dust where heavy things land (times from the sim, mapped into each return shot)
    def impact_dust(shot, names, size=(0.35, 1.6), op=0.5):
        for nm in names:
            b = SIM[nm]
            tt = t_of_tau(shot, b.t_land)
            if tt is None:
                continue
            p = b.state(b.t_land + 0.01)[0]
            EMIT.setdefault(shot, []).append(emitter('dust', [tuple(p)], 30.0, 2.2, (0, 0, 0.15), 0.9, size, opacity=op, area=1.2,
                                                     t0=tt, t1=tt + 0.25, rise=0.05, turb=0.2, salt=hash(nm) % 50))
    heavy = [nm for nm, _x, _y, _yaw, _p in PARKED] + ['Bus', 'MoveN', 'MoveS']
    for shot in ('drop_wide', 'cars_slam', 'drop_street', 'aftermath'):
        impact_dust(shot, heavy, (0.5, 2.4) if shot == 'drop_wide' else (0.35, 1.6), 0.45)
    # fountain splash spray
    for shot in ('fountain_fall',):
        EMIT.setdefault(shot, []).append(emitter('dust', [tuple(FOUNTAIN + Vector((0, 0, 0.8)))], 40.0, 1.6, (0, 0, 0.4), 1.2, (0.3, 1.4),
                                                 opacity=0.35, area=3.5, t0=SHOT[shot]['t0'] - 1.0, rise=0.1, turb=0.3, salt=7))


