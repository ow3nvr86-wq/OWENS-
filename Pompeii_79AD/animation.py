def cauliflower_bm(bm, center, radii, seed, lumps=7, detail=2, mi=0, rough=0.35):
    """A lumpy, billowing blob (tree canopy or cloud puff): an icosphere with fractal-noise displacement."""
    res = bmesh.ops.create_icosphere(bm, subdivisions=detail, radius=1.0, matrix=Matrix.Translation(center))
    off = Vector((seed * 13.1, seed * 7.7, seed * 3.3))
    for v in res['verts']:
        d = v.co - Vector(center)
        k = 1.0 + rough * mnoise.fractal(d * 1.8 + off, 0.6, 2.0, 4) + 0.12 * math.sin(d.x * lumps) * math.sin(d.y * lumps)
        v.co = Vector(center) + Vector((d.x * radii[0], d.y * radii[1], d.z * radii[2])) * k
    if mi:
        for f in bm.faces:
            if f.verts[0] in set(res['verts']):
                f.material_index = mi


