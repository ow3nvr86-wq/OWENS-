def build_town(ruined=False):
    rng = random.Random(31 if not ruined else 32)
    tag = 'Ruin' if ruined else ''
    cname = 'CityRuin' if ruined else 'City'
    wb, rb, cb = bmesh.new(), bmesh.new(), bmesh.new()
    I = Matrix()
    for (x0, y0, x1, y1) in town_blocks():
        d = rng.uniform(9.0, 13.0)
        hero_w = abs(x1 - (XS - 4.0)) < 0.1 and y0 >= HERO_Y[0] and y1 <= HERO_Y[1]
        hero_e = abs(x0 - (XS + 4.0)) < 0.1 and y0 >= HERO_Y[0] and y1 <= HERO_Y[1]
        strips = []
        # long (north-south) sides run the full length; short sides fit between them
        if not hero_e:
            strips.append(('y', x0, y0, x0 + d, y1))
        if not hero_w:
            strips.append(('y', x1 - d, y0, x1, y1))
        strips.append(('x', x0 + d, y0, x1 - d, y0 + d))
        strips.append(('x', x0 + d, y1 - d, x1 - d, y1))
        for axis, a0, b0, a1, b1 in strips:
            L = (b1 - b0) if axis == 'y' else (a1 - a0)
            s = 0.0
            while s < L - 0.5:
                seg = min(rng.uniform(7.0, 16.0), L - s)
                if L - s - seg < 4.0:
                    seg = L - s
                if axis == 'y':
                    sx0, sy0, sx1, sy1 = a0, b0 + s, a1, b0 + s + seg
                else:
                    sx0, sy0, sx1, sy1 = a0 + s, b0, a0 + s + seg, b1
                h = rng.choice([4.3, 4.7, 5.1, 5.5, 6.0, 6.8])
                mi = rng.randrange(len(PLASTER))
                if ruined:
                    ruin_room(wb, rng, sx0, sy0, sx1, sy1, mi)
                else:
                    add_box(wb, sx0, sy0, Z0 - 0.5, sx1, sy1, Z0 + h, mi=mi)
                    pitched_roof(rb, I, sx0, sy0, sx1, sy1, Z0 + h, along_x=(axis == 'x'), mi=0, over=0.35)
                s += seg
        # the courtyard / garden inside the block, and an atrium house
        cx0, cy0, cx1, cy1 = x0 + d, y0 + d, x1 - d, y1 - d
        if cx1 - cx0 > 6 and cy1 - cy0 > 10:
            add_quad(cb, [(cx0, cy0, Z0 + 0.04), (cx1, cy0, Z0 + 0.04), (cx1, cy1, Z0 + 0.04), (cx0, cy1, Z0 + 0.04)],
                     mi=0 if (rng.random() < 0.6 and not ruined) else 1)
            if cy1 - cy0 > 24:
                ay0 = rng.uniform(cy0, cy1 - 18)
                atrium(wb, rb, rng, cx0, ay0, cx1, ay0 + 16, ruined)
    obj_from_bm('Walls' + tag, wb, [MAT[f'plaster{i}'] for i in range(len(PLASTER))], collection=cname)
    if not ruined:
        obj_from_bm('Roofs', rb, [MAT['tiles'], MAT['dark']], collection=cname)
    else:
        rb.free()
    obj_from_bm('Courts' + tag, cb, [MAT['garden'], MAT['earth']], collection=cname)


def ruin_room(bm, rng, x0, y0, x1, y1, mi):
    """An excavated house: thin walls of broken height outlining its rooms."""
    t = 0.45
    for (a0, b0, a1, b1) in ((x0, y0, x1, y0 + t), (x0, y1 - t, x1, y1), (x0, y0, x0 + t, y1), (x1 - t, y0, x1, y1)):
        n = max(1, int(max(a1 - a0, b1 - b0) / 3.5))
        for k in range(n):
            if rng.random() < 0.12:
                continue
            if a1 - a0 > b1 - b0:
                p0, p1 = a0 + (a1 - a0) * k / n, a0 + (a1 - a0) * (k + 1) / n
                add_box(bm, p0, b0, Z0 - 0.3, p1, b1, Z0 + rng.uniform(1.2, 5.5), mi=mi)
            else:
                p0, p1 = b0 + (b1 - b0) * k / n, b0 + (b1 - b0) * (k + 1) / n
                add_box(bm, a0, p0, Z0 - 0.3, a1, p1, Z0 + rng.uniform(1.2, 5.5), mi=mi)


def atrium(wb, rb, rng, x0, y0, x1, y1, ruined):
    """A house round an atrium: a ring of rooms under a compluviate roof that slopes in to the opening."""
    h = rng.uniform(5.0, 6.5)
    mi = rng.randrange(len(PLASTER))
    if ruined:
        ruin_room(wb, rng, x0, y0, x1, y1, mi)
        ruin_room(wb, rng, x0 + 4, y0 + 4, x1 - 4, y1 - 4, mi)
        return
    t = 0.5
    for (a0, b0, a1, b1) in ((x0, y0, x1, y0 + t), (x0, y1 - t, x1, y1), (x0, y0, x0 + t, y1), (x1 - t, y0, x1, y1)):
        add_box(wb, a0, b0, Z0 - 0.3, a1, b1, Z0 + h, mi=mi)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    ix, iy = (x1 - x0) * 0.17, (y1 - y0) * 0.17
    o = [(x0 - 0.3, y0 - 0.3), (x1 + 0.3, y0 - 0.3), (x1 + 0.3, y1 + 0.3), (x0 - 0.3, y1 + 0.3)]
    i = [(cx - ix, cy - iy), (cx + ix, cy - iy), (cx + ix, cy + iy), (cx - ix, cy + iy)]
    for k in range(4):
        q = [(o[k][0], o[k][1], Z0 + h + 0.9), (o[(k + 1) % 4][0], o[(k + 1) % 4][1], Z0 + h + 0.9),
             (i[(k + 1) % 4][0], i[(k + 1) % 4][1], Z0 + h + 0.2), (i[k][0], i[k][1], Z0 + h + 0.2)]
        f = add_quad(rb, q, mi=0)
        f.normal_update()
        if f.normal.z < 0:
            f.normal_flip()
    add_quad(rb, [(i[0][0], i[0][1], Z0 + 0.3), (i[1][0], i[1][1], Z0 + 0.3), (i[2][0], i[2][1], Z0 + 0.3), (i[3][0], i[3][1], Z0 + 0.3)], mi=1)


def build_walls():
    """The city walls on the edge of the spur, with towers and the north gate (where the hero street ends)."""
    n = 420
    bm = bmesh.new()
    ts = 3.6
    for k in range(n):
        t0, t1 = 2 * math.pi * k / n, 2 * math.pi * (k + 1) / n
        p0 = Vector((WALL_A * math.cos(t0), WALL_B * math.sin(t0), 0))
        p1 = Vector((WALL_A * math.cos(t1), WALL_B * math.sin(t1), 0))
        mid = (p0 + p1) / 2
        if abs(mid.x - XS) < 7.5 and mid.y > 0:
            continue                                   # the gate opening
        nrm = Vector((mid.x / WALL_A ** 2, mid.y / WALL_B ** 2, 0)).normalized()
        zb = min(ground_z(*(mid + nrm * 6.0).xy), Z0) - 2.0
        q = [p0 + nrm * ts / 2, p1 + nrm * ts / 2, p1 - nrm * ts / 2, p0 - nrm * ts / 2]
        top = Z0 + 6.5
        vs_b = [bm.verts.new((v.x, v.y, zb)) for v in q]
        vs_t = [bm.verts.new((v.x, v.y, top)) for v in q]
        bm.faces.new(vs_t)
        bm.faces.new((vs_b[0], vs_b[1], vs_t[1], vs_t[0]))
        bm.faces.new((vs_b[2], vs_b[3], vs_t[3], vs_t[2]))
        if k % 2 == 0:                                 # merlons along the outer edge
            c = p0 * 0.5 + p1 * 0.5 + nrm * (ts / 2 - 0.4)
            add_box(bm, c.x - 0.6, c.y - 0.6, top, c.x + 0.6, c.y + 0.6, top + 1.2,
                    matrix=Matrix(), mi=0)
        if k % 18 == 9 and mid.y > -WALL_B * 0.6:
            c = mid + nrm * 2.0
            M = Matrix.Translation((c.x, c.y, 0)) @ Matrix.Rotation(math.atan2(nrm.y, nrm.x), 4, 'Z')
            add_box(bm, -5, -4.5, zb, 5, 4.5, Z0 + 11.0, matrix=M, mi=0)
    # the gate: piers and an arch over the road
    yg = WALL_B * math.sqrt(1 - (XS / WALL_A) ** 2)
    add_box(bm, XS - 9.5, yg - 3, Z0 - 1, XS - 7.2, yg + 3, Z0 + 7.0, mi=0)
    add_box(bm, XS + 7.2, yg - 3, Z0 - 1, XS + 9.5, yg + 3, Z0 + 7.0, mi=0)
    add_box(bm, XS - 7.4, yg - 3, Z0 + 5.0, XS + 7.4, yg + 3, Z0 + 7.0, mi=0)
    obj_from_bm('CityWalls', bm, MAT['tuff'], collection='City')


def build_amphitheatre():
    """The amphitheatre (built about 70 BC) in the south-east corner: a sunken arena ringed by stepped seating."""
    cx, cy = AMPHI
    bm = bmesh.new()
    n = 96
    rings = [(1.0, Z0 + 10.5)] + [(1.0 - 0.042 * k, Z0 + 10.0 - 0.62 * k) for k in range(1, 13)]
    A, B = 68.0, 52.0

    def P(s, t, z):
        return (cx + A * s * math.cos(t), cy + B * s * math.sin(t), z)
    for k in range(n):
        t0, t1 = 2 * math.pi * k / n, 2 * math.pi * (k + 1) / n
        add_quad(bm, [P(1.0, t0, Z0 - 0.5), P(1.0, t1, Z0 - 0.5), P(1.0, t1, Z0 + 10.5), P(1.0, t0, Z0 + 10.5)], mi=1)
        for j in range(len(rings) - 1):
            s0, z0 = rings[j]
            s1, z1 = rings[j + 1]
            add_quad(bm, [P(s0, t0, z0), P(s0, t1, z0), P(s1, t1, z0), P(s1, t0, z0)], mi=0)
            add_quad(bm, [P(s1, t0, z0), P(s1, t1, z0), P(s1, t1, z1), P(s1, t0, z1)], mi=0)
        s, z = rings[-1]
        add_quad(bm, [P(s, t0, z), P(s, t1, z), P(s, t1, Z0 + 0.4), P(s, t0, Z0 + 0.4)], mi=1)
    m = bm.verts.new((cx, cy, Z0 + 0.4))
    ring = [bm.verts.new(P(rings[-1][0], 2 * math.pi * k / n, Z0 + 0.4)) for k in range(n)]
    for k in range(n):
        f = bm.faces.new((m, ring[k], ring[(k + 1) % n]))
        f.material_index = 2
    obj_from_bm('Amphitheatre', bm, [MAT['tuff'], MAT['plaster3'], MAT['sand']], collection='City')


