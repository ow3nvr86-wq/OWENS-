def lathe(bm, profile, seg=16, matrix=Matrix(), mi=0, cap=True):
    """Revolve a (radius, z) profile about z."""
    rings = []
    for r, z in profile:
        rings.append([bm.verts.new(matrix @ Vector((r * math.cos(2 * math.pi * k / seg), r * math.sin(2 * math.pi * k / seg), z)))
                      for k in range(seg)])
    for a, b in zip(rings[:-1], rings[1:]):
        for k in range(seg):
            f = bm.faces.new((a[k], a[(k + 1) % seg], b[(k + 1) % seg], b[k]))
            f.material_index = mi
    if cap:
        f = bm.faces.new(rings[0][::-1])
        f.material_index = mi
    return rings


