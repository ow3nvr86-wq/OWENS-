#   x = east, y = north (the town's main axis is turned so that Vesuvius lies due north), metres.
#   Pompeii: a walled oval about 1.2 x 0.7 km (66 ha) centred on the origin, on a low spur at z = Z0.
#   Vesuvius: a broad single cone (its pre-79 shape is not known exactly) about 8.3 km north.
