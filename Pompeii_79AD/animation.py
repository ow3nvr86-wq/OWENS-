def pitched_roof(bm, M, x0, y0, x1, y1, h, along_x, mi=1, pitch=0.32, over=0.45):
    """A tiled gable roof over the rectangle (x0,y0)-(x1,y1) at eave height h; ridge along x or y."""
    if along_x:
        a, b = (x0 - over, x1 + over), (y0 - over, y1 + over)
        rise = (b[1] - b[0]) / 2 * pitch
        ym = (b[0] + b[1]) / 2
        P = [(a[0], b[0], h), (a[1], b[0], h), (a[1], ym, h + rise), (a[0], ym, h + rise), (a[1], b[1], h), (a[0], b[1], h)]
        quads = [(0, 1, 2, 3), (3, 2, 4, 5)]
        tris = [(0, 3, 5), (1, 4, 2)]
    else:
        a, b = (x0 - over, x1 + over), (y0 - over, y1 + over)
        rise = (a[1] - a[0]) / 2 * pitch
        xm = (a[0] + a[1]) / 2
        P = [(a[0], b[0], h), (xm, b[0], h + rise), (xm, b[1], h + rise), (a[0], b[1], h), (a[1], b[0], h), (a[1], b[1], h)]
        quads = [(0, 1, 2, 3), (1, 4, 5, 2)]
        tris = [(0, 4, 1), (3, 2, 5)]
    vs = [bm.verts.new(M @ Vector(p)) for p in P]
    for q in quads:
        f = bm.faces.new([vs[i] for i in q])
        f.material_index = mi
        f.normal_update()
        if f.normal.z < 0:
            f.normal_flip()
    for t in tris:
        f = bm.faces.new([vs[i] for i in t])
        f.material_index = mi


