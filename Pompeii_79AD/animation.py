def terrain_material():
    """The Campanian plain and Vesuvius: fields, vineyards and woods (attribute 'veg'), bare rock on steep
    slopes and near the summit, beaches; then grey under the ash ('ashcover') and green again ('regrow')."""
    m, nt, out = new_mat('terrain')
    geo = nd(nt, 'ShaderNodeNewGeometry')
    wp = geo.outputs['Position']
    nz = sep(nt, geo.outputs['Normal']).outputs['Z']
    z = sep(nt, wp).outputs['Z']
    veg = attr(nt, 'veg', 'GEOMETRY')
    cam = nd(nt, 'ShaderNodeCameraData').outputs['View Distance']
    fine = mth(nt, 'SUBTRACT', 1.0, mth(nt, 'DIVIDE', cam, 2500.0), clamp=True)
    n1 = noise(nt, 0.0025, 6.0, 0.6, vec=wp)
    n2 = noise(nt, 0.02, 4.0, 0.6, vec=wp)
    fields = nd(nt, 'ShaderNodeTexVoronoi', Vector=wp, Scale=0.006)
    fc = sep(nt, fields.outputs['Color'])
    fieldcol = ramp_node(nt, fc.outputs['X'], [(0.0, (0.20, 0.21, 0.09)), (0.35, (0.30, 0.27, 0.14)), (0.6, (0.16, 0.19, 0.08)),
                                               (0.8, (0.36, 0.30, 0.18)), (1.0, (0.22, 0.24, 0.12))])
    wood = mixc(nt, n2, (0.06, 0.09, 0.035, 1), (0.10, 0.12, 0.05, 1))
    col = mixc(nt, mth(nt, 'MULTIPLY', veg, mth(nt, 'MULTIPLY_ADD', n1, 1.2, 0.2), clamp=True), fieldcol, wood)
    rock = mixc(nt, n2, (0.17, 0.15, 0.13, 1), (0.10, 0.09, 0.085, 1))
