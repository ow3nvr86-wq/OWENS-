# --- poses ----------------------------------------------------------------------------------------
def heading(d):
    """Root z-rotation that turns the figure's forward (-y) to the world direction d."""
    return math.atan2(d[0], -d[1])


def rest(p):
    for k in ('hips', 'torso', 'head'):
        p[k].rotation_euler = (0, 0, 0)
    p['hips'].location = (0, 0, 0.93)
    for side, sg in (('L', 1), ('R', -1)):
        p['arm' + side].rotation_euler = (0.05, 0, sg * 0.06)
        p['fore' + side].rotation_euler = (-0.12, 0, 0)
        p['thigh' + side].rotation_euler = (0, 0, sg * 0.03)
        p['shin' + side].rotation_euler = (0, 0, 0)


def pose_walk(p, t, period=1.1, phase=0.0, amp=1.0, lean=0.05, arms=True):
    ph = 2 * math.pi * t / period + phase
    for side, sg in (('L', 1), ('R', -1)):
        a = ph if sg > 0 else ph + math.pi
        s, c = math.sin(a), math.cos(a)
        p['thigh' + side].rotation_euler = (-0.34 * amp * s, 0, sg * 0.03)
        p['shin' + side].rotation_euler = (0.08 + 0.45 * amp * max(0.0, c), 0, 0)
        if arms:
            p['arm' + side].rotation_euler = (0.3 * amp * s, 0, sg * 0.06)
            p['fore' + side].rotation_euler = (-0.25 - 0.1 * amp * max(0, -s), 0, 0)
    p['hips'].location = (0, 0, 0.93 - 0.025 * amp + 0.025 * amp * abs(math.cos(ph)))
    p['hips'].rotation_euler = (0, 0, 0.06 * amp * math.sin(ph))
    p['torso'].rotation_euler = (lean, 0, -0.08 * amp * math.sin(ph))
    p['head'].rotation_euler = (-lean * 0.6, 0, 0.04 * math.sin(ph * 0.5))


def pose_idle(p, t, seed=0.0, look=0.0):
    rest(p)
    b = math.sin(t * 1.3 + seed)
    p['torso'].rotation_euler = (0.02 * b, 0, 0.03 * math.sin(t * 0.4 + seed))
    p['hips'].rotation_euler = (0, 0.02 * math.sin(t * 0.35 + seed), 0)
    p['head'].rotation_euler = (0.03 * math.sin(t * 0.5 + seed * 2), 0, look + 0.25 * math.sin(t * 0.33 + seed))
    for side, sg in (('L', 1), ('R', -1)):
        p['arm' + side].rotation_euler = (0.04 + 0.03 * b, 0, sg * 0.07)


def place(p, x, y, ang, z=None):
    p['root'].location = (x, y, Z0 if z is None else z)
    p['root'].rotation_euler = (0, 0, ang)


def walker_state(b, t):
    """A walker's position and heading at time t from its behaviour (straight path at speed v)."""
    d = Vector(b['dir']).normalized()
    pos = Vector(b['p0']) + d * b['v'] * (t - b.get('t0', 0.0))
    return pos, heading(d)


def floor_z(x, y, shot, t):
    z = Z0 + 0.02
    if abs(x - XS) > 2.25 and abs(x - XS) < 4.0 and any(a <= y <= b for a, b in BLOCKS_Y):
        z = Z0 + SW_H
    if shot == 'fill':
        z = max(z, Z0 + street_deposit_level(t) + 0.05 + 0.16 * float(sstep(abs(x - XS), 1.6, 4.0)))
    return z


def update_people(shot, t):
    beh = BEH.get(shot, {})
    for nm, p in PEOPLE.items():
        if nm.startswith('_'):
            continue
        b = beh.get(nm)
        vis = b is not None
        for ob in [p['root']] + list(p['root'].children_recursive):
            if ob.type != 'EMPTY':
                ob.hide_render = not vis
        if not vis:
            continue
        mode = b['mode']
        if mode in ('walk', 'hurry', 'cart', 'carry', 'basket'):
            pos, ang = walker_state(b, t)
            z = b.get('z', floor_z(pos.x, pos.y, shot, t))
            place(p, pos.x, pos.y, ang, z)
            if mode == 'hurry':
                pose_walk(p, t, b.get('period', 0.82), b.get('phase', 0.0), amp=1.25, lean=0.22, arms=False)
                cover = b.get('cover', 'none')
                if cover == 'head':        # a cloth or cushion held over the head against the falling stones
                    for side, sg in (('L', 1), ('R', -1)):
                        p['arm' + side].rotation_euler = (-2.55, 0, sg * 0.35)
                        p['fore' + side].rotation_euler = (-1.3, 0, 0)
                    p['head'].rotation_euler = (0.35, 0, 0)
                elif cover == 'torch':
                    p['armR'].rotation_euler = (-1.25, 0, -0.1)
                    p['foreR'].rotation_euler = (-0.5, 0, 0)
                    p['armL'].rotation_euler = (-0.4, 0, 0.3)
                    p['foreL'].rotation_euler = (-1.4, 0, 0)
                else:
                    p['armL'].rotation_euler = (-0.6, 0, 0.2)
                    p['foreL'].rotation_euler = (-1.2, 0, 0)
                    p['armR'].rotation_euler = (0.2, 0, -0.1)
            else:
                pose_walk(p, t, b.get('period', 1.1), b.get('phase', 0.0), amp=b.get('amp', 0.9))
            if mode == 'cart':
                for side in ('L', 'R'):
                    p['arm' + side].rotation_euler = (-0.35, 0, (0.25 if side == 'L' else -0.25))
                    p['fore' + side].rotation_euler = (-0.25, 0, 0)
                p['torso'].rotation_euler = (0.18, 0, 0)
                cart = PEOPLE['_cart']
                d = Vector(b['dir']).normalized()
                cpos = pos - d * 2.3
                cart['root'].location = (cpos.x, cpos.y, z)
                cart['root'].rotation_euler = (0, 0, ang)
                dist = b['v'] * (t - b.get('t0', 0.0))
                for w in cart['wheels']:
                    w.rotation_euler = (dist / 0.55, 0, 0)
            if mode == 'carry':                  # an amphora on the shoulder, steadied with one hand
                p['armL'].rotation_euler = (-2.6, 0, 0.55)
                p['foreL'].rotation_euler = (-1.2, 0, 0)
            if mode == 'basket':                 # a basket of spoil balanced on the head
                for side, sg in (('L', 1), ('R', -1)):
                    p['arm' + side].rotation_euler = (-2.9, 0, sg * 0.25)
                    p['fore' + side].rotation_euler = (-0.6, 0, 0)
        elif mode in ('idle', 'merchant', 'look', 'chat'):
            x, y = b['p']
            place(p, x, y, b['ang'], b.get('z', floor_z(x, y, shot, t)))
            pose_idle(p, t, b.get('seed', 0.0), b.get('look0', 0.0))
            if mode == 'merchant':               # lifts a jug from the stall, shows it, sets it down
                u = 0.5 - 0.5 * math.cos(2 * math.pi * (t - 4.0) / 3.0)
                p['armR'].rotation_euler = (-0.3 - 1.0 * u, 0, -0.15)
                p['foreR'].rotation_euler = (-0.6 - 0.5 * u, 0, 0)
                p['torso'].rotation_euler = (0.18 * (1 - u), 0, 0.1)
            if mode == 'chat':
                p['armR'].rotation_euler = (-0.5 - 0.25 * math.sin(t * 2.1 + b.get('seed', 0)), 0, -0.2)
                p['foreR'].rotation_euler = (-1.0, 0, 0)
            if mode == 'look':                   # turn toward the mountain, look up; some point
                a, bb = EV['turn']
                tt = a + b.get('delay', 0.0)
                u = ramp(t, tt, tt + (bb - a))
                ang = b['ang'] + u * ((b['ang_to'] - b['ang'] + math.pi) % (2 * math.pi) - math.pi)
                p['root'].rotation_euler = (0, 0, ang)
                p['head'].rotation_euler = (-0.45 * u + 0.03 * math.sin(t), 0, 0.15 * (1 - u) * math.sin(t * 0.5))
                p['torso'].rotation_euler = (-0.06 * u, 0, 0)
                if b.get('point'):
                    k = ramp(t, tt + 0.6, tt + 1.4)
                    p['armR'].rotation_euler = (0.05 - 2.35 * k, 0, -0.15)
                    p['foreR'].rotation_euler = (-0.15, 0, 0)
                if b.get('hold'):
                    k = ramp(t, tt + 0.4, tt + 1.0)
                    p['armL'].rotation_euler = (-0.6 * k, 0, 0.5 * k)
                    p['foreL'].rotation_euler = (-1.4 * k, 0, 0)
        elif mode in ('dig', 'shovel'):
            x, y = b['p']
            place(p, x, y, b['ang'], b.get('z'))
            rest(p)
            per = b.get('period', 1.6)
            u = (t / per + b.get('phase', 0.0)) % 1.0
            if mode == 'dig':                    # raise the pick, swing it down
                k = math.sin(math.pi * min(u / 0.7, 1.0)) if u < 0.7 else 0.0
                strike = max(0.0, 1 - abs(u - 0.75) / 0.08)
                p['torso'].rotation_euler = (0.35 - 0.3 * k + 0.25 * strike, 0, 0)
                for side, sg in (('L', 1), ('R', -1)):
                    p['arm' + side].rotation_euler = (-0.9 - 1.9 * k, 0, sg * 0.15)
                    p['fore' + side].rotation_euler = (-0.5 + 0.3 * k, 0, 0)
            else:                                # dig in, lever, throw
                k = 0.5 - 0.5 * math.cos(2 * math.pi * u)
                p['torso'].rotation_euler = (0.55 * (1 - k) + 0.1, 0, 0.3 * math.sin(2 * math.pi * u))
                p['armR'].rotation_euler = (-0.6 - 0.8 * k, 0, -0.15)
                p['foreR'].rotation_euler = (-0.6, 0, 0)
                p['armL'].rotation_euler = (-0.9 - 0.6 * k, 0, 0.3)
                p['foreL'].rotation_euler = (-0.9, 0, 0)
            for side in ('L', 'R'):
                p['thigh' + side].rotation_euler = (-0.2, 0, (0.12 if side == 'L' else -0.12))
                p['shin' + side].rotation_euler = (0.25, 0, 0)
    cart = PEOPLE.get('_cart')
    if cart:
        cb = beh.get('_cart')
        vis = cb is not None or any(b.get('mode') == 'cart' for b in beh.values())
        for ob in [cart['root']] + list(cart['root'].children_recursive):
            if ob.type != 'EMPTY':
                ob.hide_render = not vis
        if cb is not None:
            cart['root'].location = cb['p']
            cart['root'].rotation_euler = (cb.get('tilt', 0.0), 0, cb['ang'])
    for st, lo in PEOPLE.get('_torches', []):
        on = shot == 'fill' and not st.parent.hide_render
        st.hide_render = not on
        for c in st.children:
            c.hide_render = not on
        lo.data.energy = (45.0 + 12.0 * math.sin(t * 17.0) * math.sin(t * 7.3)) if on else 0.0


