def build_props(bm, rng, pts, kinds, mi_t, mi_b, mi_w):
    for (x, y, z), k in zip(pts, kinds):
        a = rng.uniform(0, 6.28)
        if k == 'amph':
            amphora(bm, (x, y, z), a, rng.uniform(-0.05, 0.05), rng.uniform(0.85, 1.1), mi=mi_t)
        elif k == 'amph_lean':
            amphora(bm, (x, y, z + 0.08), a, 0.35, 1.0, mi=mi_t)
        elif k == 'dolium':
            lathe(bm, DOLIUM, 16, Matrix.Translation((x, y, z)) @ Matrix.Diagonal((0.8, 0.8, 0.8, 1)), mi_t)
        elif k == 'jugs':
            for j in range(rng.randint(2, 4)):
                lathe(bm, JUG, 10, Matrix.Translation((x + rng.uniform(-0.25, 0.25), y + rng.uniform(-0.25, 0.25), z)), mi_t)
        elif k == 'bowls':
            for j in range(rng.randint(2, 5)):
                lathe(bm, BOWL, 12, Matrix.Translation((x + 0.0, y + 0.0, z + 0.035 * j)), mi_t)
        elif k == 'basket':
            lathe(bm, [(0.16, 0.0), (0.24, 0.05), (0.27, 0.25), (0.26, 0.26)], 12, Matrix.Translation((x, y, z)), mi_b)
            cauliflower_bm(bm, (x, y, z + 0.24), (0.23, 0.23, 0.07), rng.randint(0, 99), detail=1, rough=0.2)
        elif k == 'crate':
            add_box(bm, x - 0.3, y - 0.22, z, x + 0.3, y + 0.22, z + 0.38, matrix=Matrix(), mi=mi_w)


