def flash_level(t):
    """Brief flashes inside the cloud (Pliny describes flashes like lightning), at pseudo-random moments."""
    a, b = EV['flashes']
    if not (a <= t <= b):
        return 0.0
    v = 0.0
    for k in range(9):
        tk = a + (b - a) * ((k * 0.618034 + 0.13) % 1.0)
        d = t - tk
        if 0 <= d < 0.35:
            v = max(v, math.exp(-d / 0.07) * (0.6 + 0.4 * math.sin(k * 3.1) ** 2))
    return v


def surge_front_puffs(t):
    """Soft billboard ash along the advancing front, so its edge reads as a turbulent cloud, not solid blobs."""
    F = surge_front(t)
    if F < 0:
        return None
    n = 260
    k = np.arange(n)
    r1, r2, r3 = hash01(k, 1.0, 3.0), hash01(k, 2.0, 5.0), hash01(k, 3.0, 7.0)
    s = F - r1 ** 1.5 * 900.0
    w = 700.0 + 0.32 * s
    x = VX + (r2 * 2 - 1) * w + 300.0 * np.sin(s / 1300.0)
    y = VY - 600.0 - s
    z = terrain_h(x, y) + 40.0 + r3 * 260.0
    size = 120.0 + 260.0 * r3 + 0.02 * s
    pos = np.stack([x, y, z], -1)
    alpha = 0.55 * np.clip(s / 600.0, 0, 1)
    return pos, size, np.full(n, 0.5), r2, alpha, np.zeros(n)


