_FONTS = {}


def font(path):
    if path not in _FONTS:
        _FONTS[path] = bpy.data.fonts.load(path, check_existing=True)
    return _FONTS[path]


def save_png(path, arr):
    """arr: (H, W, 4) float in 0..1, top row first."""
    h, w = arr.shape[:2]
    im = bpy.data.images.new(os.path.basename(path), w, h, alpha=True)
    im.pixels.foreach_set(np.ascontiguousarray(arr[::-1]).astype(np.float32).ravel())
    im.filepath_raw = path
    im.file_format = 'PNG'
    im.save()
    bpy.data.images.remove(im)


def make_overlays():
    d = os.path.join(BUILD, 'overlays')
    os.makedirs(d, exist_ok=True)
    vpath = os.path.join(d, 'vignette.png')
    if not os.path.exists(vpath):
        h, w = 960, 540
        y, x = np.mgrid[0:h, 0:w]
        r = np.sqrt(((x - w / 2) / (w / 2)) ** 2 * 0.9 + ((y - h / 2) / (h / 2)) ** 2)
        a = np.clip((r - 0.55) / 0.75, 0, 1) ** 1.6 * 0.75
        arr = np.zeros((h, w, 4))
        arr[..., 3] = a
        save_png(vpath, arr)
    grains = []
    rng = np.random.default_rng(5)
    for k in range(24):
        gp = os.path.join(d, f'grain_{k:02d}.png')
        if not os.path.exists(gp):
            g = rng.normal(0.5, 0.12, (960, 540))
            arr = np.stack([g, g, g, np.ones_like(g)], -1).clip(0, 1)
            save_png(gp, arr)
        grains.append(os.path.basename(gp))
    return vpath, d, grains


def key_alpha(strip, pts):
    for f, a in pts:
        strip.blend_alpha = a
        strip.keyframe_insert('blend_alpha', frame=f)


def add_text(se, name, text, t0, t1, style, channel, fade=5, rise=0.012, y=None):
    fnt, size, col, y0, outline = TITLE_STYLE[style]
    y = y0 if y is None else y
    f0, f1 = frame(t0), frame(t1)
    st = se.sequences.new_effect(name=name, type='TEXT', channel=channel, frame_start=f0, frame_end=f1)
    st.text = text
    st.font = font(fnt)
    st.font_size = size
    st.color = col
    st.align_x = 'CENTER'
    st.align_y = 'CENTER'
    st.wrap_width = 0.92
    st.use_shadow = True
    st.shadow_color = (0, 0, 0, 0.85)
    st.shadow_blur = 0.35
    st.shadow_offset = 0.035
    if outline > 0:
        st.use_outline = True
        st.outline_color = (0, 0, 0, 1)
        st.outline_width = outline
    if style in ('tag', 'final2', 'quote'):
        # a dark plate keeps small or light text readable over busy props (newspapers, papers)
        st.use_box = True
        st.box_color = (0.03, 0.02, 0.015, {'tag': 0.62, 'quote': 0.72}.get(style, 0.78))
        st.box_margin = 0.012
    st.blend_type = 'ALPHA_OVER'
    fade = min(fade, max(1, (f1 - f0) // 3))
    key_alpha(st, [(f0, 0.0), (f0 + fade, 1.0), (f1 - fade, 1.0), (f1, 0.0)])
    st.location = (0.5, y - rise)
    if rise > 0:
        st.keyframe_insert('location', frame=f0)
        st.location = (0.5, y)
        st.keyframe_insert('location', frame=f0 + fade * 2)
    return st


def stage_edit():
    frames_dir = ARGS.out
    files = sorted(f for f in os.listdir(frames_dir) if f.startswith('f_') and f.endswith('.png')) if os.path.isdir(frames_dir) else []
    if not files:
        raise SystemExit('no rendered frames in ' + frames_dir)
    fset = set(files)
    missing = [f for f in range(1, RENDER_END + 1) if f'f_{f:04d}.png' not in fset]
    if missing:
        print(f'WARNING: {len(missing)} frames missing (first {missing[:5]}); they will show as black')
    bpy.ops.wm.read_factory_settings(use_empty=True)
    sc = bpy.context.scene
    sc.name = 'Edit'
    sc.render.resolution_x, sc.render.resolution_y = RES
    sc.render.resolution_percentage = 100
    sc.render.fps = FPS
    sc.frame_start, sc.frame_end = 1, LAST_FRAME
    sc.view_settings.view_transform = 'Standard'     # frames are already tone-mapped (AgX) in the render
    sc.view_settings.look = 'None'
    se = sc.sequence_editor_create()
    first = 1
    while f'f_{first:04d}.png' not in fset:
        first += 1
    img = se.sequences.new_image('Frames', os.path.join(frames_dir, f'f_{first:04d}.png'), channel=1, frame_start=first, fit_method='FIT')
    for f in range(first + 1, RENDER_END + 1):
        img.elements.append(f'f_{f:04d}.png')
    img.transform.filter = 'CUBIC_MITCHELL'
    # opening fade-in, dips to black between scenes, closing fade-out to black
    pts = [(1, 0.0), (frame(EV['fade_in'][1]), 1.0)]           # a slow reveal out of darkness
    for sc_ in TIMING['scenes'][1:]:
        c = frame(sc_['start'])
        if c > RENDER_END:
            continue
        pts += [(c - 6, 1.0), (c - 1, 0.04), (c, 0.04), (c + 5, 1.0)]
    fb = EV['fade_to_black']
    pts += [(frame(fb[0]), 1.0), (frame(fb[1]), 0.0)]
    for f, v in sorted(pts):
        img.color_multiply = v
        img.keyframe_insert('color_multiply', frame=f)
    vpath, gdir, grains = make_overlays()
    vg = se.sequences.new_image('Vignette', vpath, channel=2, frame_start=1, fit_method='STRETCH')
    vg.frame_final_end = RENDER_END + 1
    vg.blend_type = 'ALPHA_OVER'
    gr = se.sequences.new_image('Grain', os.path.join(gdir, grains[0]), channel=3, frame_start=1, fit_method='STRETCH')
    for f in range(2, LAST_FRAME + 1):
        gr.elements.append(grains[(f - 1) % len(grains)])
    gr.blend_type = 'OVERLAY'
    gr.blend_alpha = 0.22
    # soft flashes as the column bursts up and as the current reaches the town
    for nm, tm, col, peak, ch in (('Flash', EV['erupt'][0], (1.0, 0.92, 0.82), 0.10, 4), ('Flash2', EV['surge_hit'][0], (0.9, 0.85, 0.8), 0.06, 5)):
        f0 = frame(tm)
        fl = se.sequences.new_effect(nm, type='COLOR', channel=ch, frame_start=f0 - 2, frame_end=f0 + 12)
        fl.color = col
        fl.blend_type = 'ADD'
        key_alpha(fl, [(f0 - 2, 0.0), (f0, peak), (f0 + 1, peak * 0.8), (f0 + 11, 0.0)])
    ch = 6
    for k, tl in enumerate(TIMING['titles']):
        # '|' marks a line break: each line is its own centred strip, stacked downward
        for j, line in enumerate(tl['text'].split('|')):
            st = add_text(se, f'Title{k}_{j}', line, tl['start'], tl['end'], tl['style'], ch + (k % 4) * 2 + j,
                          fade=10 if tl['style'].startswith('final') else 5, rise=0.0 if tl['style'] == 'tag' else 0.012,
                          y=tl.get('y'))
            if j:
                dy = j * TITLE_STYLE[tl['style']][1] * 1.2 / RES[1]
                fc = sc.animation_data.action.fcurves if sc.animation_data and sc.animation_data.action else []
                for fcu in fc:
                    if fcu.data_path == f'sequence_editor.sequences_all["{st.name}"].location' and fcu.array_index == 1:
                        for kp in fcu.keyframe_points:
                            kp.co[1] -= dy
                            kp.handle_left[1] -= dy
                            kp.handle_right[1] -= dy
                st.location = (0.5, st.location[1] - dy)
    # scene 9: the year counter, AD 79 -> AD 1748, ticking faster as the centuries pass
    a, b = EV['years']
    yrs = [79, 100, 150, 200, 300, 400, 500, 600, 700, 800, 900, 1000, 1100, 1200, 1300, 1400, 1500, 1550, 1600, 1650, 1700, 1730, 1748]
    fnt, size, col, yy, outline = TITLE_STYLE['big']
    for k, yv in enumerate(yrs):
        t0 = a + (b - a) * (k / len(yrs)) ** 0.8
        t1 = a + (b - a) * ((k + 1) / len(yrs)) ** 0.8 if k < len(yrs) - 1 else b
        st = se.sequences.new_effect(name=f'Year{k}', type='TEXT', channel=30 + k % 2, frame_start=frame(t0), frame_end=max(frame(t1), frame(t0) + 1))
        st.text = f'AD {yv}'
        st.font = font(fnt)
        st.font_size = size
        st.color = col
        st.align_x, st.align_y = 'CENTER', 'CENTER'
        st.use_shadow, st.shadow_color, st.shadow_blur, st.shadow_offset = True, (0, 0, 0, 0.85), 0.35, 0.035
        st.use_outline, st.outline_color, st.outline_width = True, (0, 0, 0, 1), outline
        st.blend_type = 'ALPHA_OVER'
        st.location = (0.5, yy)
    if not ARGS.no_voice:
        vt = os.path.join(BUILD, 'vo_timing.json')
        with open(vt) as fh:
            vlines = json.load(fh)['lines']
        k = 0
        for ln in vlines:
            for c in ln['chunks']:
                st = add_text(se, f'Cap{k}', c['text'].upper(), c['start'], c['end'] + 0.02, 'label', 16 + k % 2, fade=2, rise=0.0)
                st.font_size = 84
                st.location = (0.5, 0.335)
                k += 1
    apath = os.path.join(ROOT, 'audio', 'mix_no_voice.wav' if ARGS.no_voice else 'mix_with_voice.wav')
    se.sequences.new_sound('Audio', apath, channel=20, frame_start=1)
    r = sc.render
    r.use_sequencer = True
    r.use_compositing = False
    r.image_settings.file_format = 'FFMPEG'
    ff = r.ffmpeg
    ff.format = 'MPEG4'
    ff.codec = 'H264'
    ff.constant_rate_factor = 'NONE'
    ff.video_bitrate = ARGS.bitrate
    ff.maxrate = int(ARGS.bitrate * 1.125)
    ff.minrate = 0
    ff.buffersize = 18000
    ff.gopsize = 30
    ff.ffmpeg_preset = 'GOOD'
    ff.audio_codec = 'AAC'
    ff.audio_bitrate = 192
    ff.audio_mixrate = 48000
    ff.audio_channels = 'STEREO'
    name = ARGS.output or ('final_video_no_voice.mp4' if ARGS.no_voice else 'final_video.mp4')
    out = os.path.join(ROOT, name) if name == 'final_video.mp4' else os.path.join(ROOT, 'renders', name)
    tmp = os.path.join(BUILD, 'edit_' + name)
    if ARGS.frames:
        a, b = (int(x) for x in ARGS.frames.split('-'))
        sc.frame_start, sc.frame_end = a, b
    r.filepath = tmp
    r.use_file_extension = False
    bpy.ops.render.render(animation=True)
    try:
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp, '-c', 'copy', '-movflags', '+faststart', out], check=True)
        os.remove(tmp)
    except (OSError, subprocess.CalledProcessError):
        os.replace(tmp, out)
    print('wrote', out)


