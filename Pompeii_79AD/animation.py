def ell(X, Y, s=1.0):
    return np.sqrt((np.asarray(X) / (WALL_A * s)) ** 2 + (np.asarray(Y) / (WALL_B * s)) ** 2)


def vesuvius_h(X, Y):
    r = np.hypot(X - VX, Y - VY)
    a = np.arctan2(Y - VY, X - VX)
    cone = 1500.0 * np.clip(1.0 - r / 6200.0, 0.0, 1.0) ** 1.7
    # radial gullies and lava ridges on the flanks
    g = np.abs(np.sin(a * 27.0 + 2.2 * np.sin(a * 5.0) + r / 900.0)) ** 0.6
    g2 = np.abs(np.sin(a * 61.0 + 3.0 * np.sin(a * 9.0 + 1.0) + r / 400.0)) ** 0.8
    band = sstep(r, 350, 1500) * (1 - sstep(r, 4200, 6200))
    mod = 0.35 + 0.65 * (0.5 + 0.5 * np.sin(a * 3.0 + 1.7) * np.sin(a * 7.0 + 0.3 + r / 1700.0))
    cone = cone - (30.0 * g + 12.0 * g2) * mod * band * np.clip(1.0 - r / 6200.0, 0, 1) ** 0.5
    cone = cone + (22.0 * np.sin(X / 410.0 + 0.6) * np.sin(Y / 350.0) + 9.0 * np.sin(X / 130.0 + Y / 170.0)) * sstep(r, 500, 2000) * (1 - sstep(r, 4500, 6200))
    crater = 260.0 * np.clip(1 - (r / 430.0) ** 2, 0, 1)
    return cone - crater


def terrain_h(X, Y):
    X = np.asarray(X, float)
    Y = np.asarray(Y, float)
    plain = 9.0 + 14.0 * sstep(Y, -4000, 4500) + 4.0 * np.sin(X / 900 + 1.3) * np.cos(Y / 1300) \
        + 2.5 * np.sin(X / 310) * np.sin(Y / 270 + 0.7) + 0.8 * np.sin(X / 61 + Y / 83)
    coast = -2300.0 - 500.0 * np.sin(Y / 2600.0) - 0.15 * np.maximum(Y - 1500.0, 0)
    sea = sstep(coast - X, -250, 500)
    plain = plain * (1 - sea) - 14.0 * sea
    w = 1 - sstep(ell(X, Y), 1.0, 1.22)
    plain = plain * (1 - w) + Z0 * w
    return plain + vesuvius_h(X, Y)


def ground_z(x, y):
    return float(terrain_h(np.array([x]), np.array([y]))[0])


def graded(c, half, n, k=3.0):
    u = np.linspace(-1, 1, n)
    return c + half * np.sinh(u * k) / math.sinh(k)


def build_terrain():
    xs = graded(0.0, 24000.0, 640)
    ys = np.unique(np.concatenate([graded(0.0, 24000.0, 560), graded(VY, 6500.0, 220, k=1.5)]))

    def vegf(X, Y):
        r = np.hypot(X - VX, Y - VY)
        v = 0.5 + 0.5 * np.sin(X / 530 + 0.4) * np.sin(Y / 410 + 1.1)
        return np.clip(np.maximum(v * 0.7, sstep(r, 1600, 2600) * (1 - sstep(r, 5200, 7000))), 0, 1)
    ob = grid_mesh('Terrain', xs, ys, terrain_h, MAT['terrain'], 'Land', drop=lambda x, y: ell(x, y) < 0.985, attrs={'veg': vegf})
    ob.data.shade_smooth()
    # the town's ground: streets and squares paved in basalt
    n = 160
    a = np.linspace(0, 2 * np.pi, n, endpoint=False)
    bm = bmesh.new()
    c = bm.verts.new((0, 0, Z0))
    ring = [bm.verts.new((WALL_A * 0.995 * math.cos(t), WALL_B * 0.995 * math.sin(t), Z0)) for t in a]
    for i in range(n):
        bm.faces.new((c, ring[i], ring[(i + 1) % n]))
    obj_from_bm('TownGround', bm, MAT['paving_far'], collection='Land')
    # the sea
