VX, VY = 0.0, 8300.0
WALL_A, WALL_B = 600.0, 350.0
XS = -230.0                         # the hero street (a north-south street that ends at the north gate)
STREET_W = 4.4                      # roadway width; raised pavements 1.8 m on each side
FOR_X0, FOR_X1, FOR_Y0, FOR_Y1 = -352.0, -308.0, -140.0, 0.0     # forum plaza
