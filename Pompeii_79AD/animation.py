def quad_obj(name, n, mat):
    faces = np.arange(4 * n).reshape(n, 4)
    ob = mesh_obj(name, np.zeros((4 * n, 3)), faces, mat, collection='FX', smooth=False)
    me = ob.data
    uv = me.uv_layers.new(name='UVMap')
    uv.data.foreach_set('uv', np.tile(np.array([0, 0, 1, 0, 1, 1, 0, 1], np.float32), n))
    me.color_attributes.new('sm', 'FLOAT_COLOR', 'CORNER')
