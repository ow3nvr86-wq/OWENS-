def fold_cone(bm, r0, z0, r1, z1, seg=18, folds=9, depth=0.06, mi=0, yscale=0.72, open_bottom=True):
    """A flared skirt or cloak: a cone with soft vertical folds that deepen toward the hem."""
    rings = []
    nz = 5
    for j in range(nz + 1):
        u = j / nz
        r = r0 + (r1 - r0) * u
        z = z0 + (z1 - z0) * u
        ring = []
        for k in range(seg):
            a = 2 * math.pi * k / seg
            rr = r * (1 + depth * u * math.sin(a * folds + 0.7))
            ring.append(bm.verts.new((rr * math.cos(a), rr * math.sin(a) * yscale, z)))
        rings.append(ring)
    for a_, b_ in zip(rings[:-1], rings[1:]):
        for k in range(seg):
            f = bm.faces.new((a_[k], a_[(k + 1) % seg], b_[(k + 1) % seg], b_[k]))
            f.material_index = mi
    f = bm.faces.new(rings[0][::-1])
    f.material_index = mi


