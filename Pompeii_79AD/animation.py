def plaster_material(name, color, dado=True):
    """Lime plaster over rubble masonry: painted upper wall, a dark red dado, grime at the foot; with 'decay' the
    plaster falls away in patches to show the grey opus incertum stonework underneath."""
    m, nt, out = new_mat(name)
    geo = nd(nt, 'ShaderNodeNewGeometry')
    wp = geo.outputs['Position']
    z = sep(nt, wp).outputs['Z']
    hz = mth(nt, 'SUBTRACT', z, Z0)
    n = noise(nt, 1.6, 5.0, 0.62, vec=wp)
    nf = noise(nt, 14.0, 3.0, 0.5, vec=wp)
    col = mixc(nt, mth(nt, 'MULTIPLY', nf, 0.22), rgba(color), rgba([c * 0.78 for c in color]))
    if dado:
        dz = mth(nt, 'LESS_THAN', hz, mth(nt, 'MULTIPLY_ADD', n, 0.12, 1.32))
        col = mixc(nt, mth(nt, 'MULTIPLY', dz, value(nt, 'dado', 1.0)), col, (0.30, 0.075, 0.055, 1))
    # grime and rain streaks
    grime = mth(nt, 'MULTIPLY', mth(nt, 'SUBTRACT', 1.0, mth(nt, 'DIVIDE', hz, 1.8), clamp=True), 0.45)
    streak = noise(nt, 1.0, 2.0, 0.5, vec=comb(nt, mth(nt, 'MULTIPLY', sep(nt, wp).outputs['X'], 3.0),
                                                 mth(nt, 'MULTIPLY', sep(nt, wp).outputs['Y'], 3.0), mth(nt, 'MULTIPLY', z, 0.25)))
    grime = mth(nt, 'ADD', grime, mth(nt, 'MULTIPLY', mth(nt, 'SUBTRACT', streak, 0.5, clamp=True), 0.5))
    col = mixc(nt, mth(nt, 'MINIMUM', grime, 0.6), col, (0.18, 0.15, 0.12, 1))
    # decay: plaster lost in patches, rubble masonry behind
    rub = nd(nt, 'ShaderNodeTexVoronoi', Vector=wp, Scale=4.0, p_feature='DISTANCE_TO_EDGE')
    stonec = mixc(nt, mth(nt, 'LESS_THAN', rub.outputs['Distance'], 0.06), (0.42, 0.40, 0.37, 1), (0.22, 0.21, 0.2, 1))
    lost = mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', n, mth(nt, 'SUBTRACT', 1.0, mth(nt, 'MULTIPLY', value(nt, 'decay', 0.0), 0.55))), 1.0)
    col = mixc(nt, lost, col, stonec)
    col, r = ash_and_decay(nt, col, 0.88)
    finish(m, nt, out, col, r, spec=0.25, keys=('ashc', 'dado', 'decay'))
    MAT[name] = m
    return m


