"""THE DAY POMPEII DISAPPEARED - 79 AD.
A fully code-generated, cinematic 3D YouTube Short (1080x1920, 30 fps, 60 s) about the eruption of Mount Vesuvius
in 79 AD and the burial, and rediscovery, of the Roman town of Pompeii.

Everything is generated by this Blender (bpy) script: the Campanian landscape, the sea and Mount Vesuvius; a
schematic walled Pompeii of some 150 city blocks with tiled roofs, courtyards and an amphitheatre; a detailed
Roman street (raised pavements, stepping stones, cart ruts, shops and a tavern counter, amphorae, jars and
awnings); the forum with its colonnades and the temple on its podium; animated Roman townspeople in tunics,
stolas, pallas and cloaks; a handcart; the eruption column, the umbrella cloud, falling pumice and ash, flashes in
the cloud and the pyroclastic density currents; the deposits that bury the town; a time-lapse of the centuries;
the excavation with its trench through the layers; and the ruined forum today. Also all lighting, cameras and
depth of field, the compositor grade, the synthesised music and sound design, the edit (titles, captions,
transitions, film grain) and the MP4 encode.

Accuracy: see sources.txt. The town plan, the eruption's appearance and its pace are artistic reconstructions,
labelled as such on screen. No individual death is depicted.

Run with Blender 4.2 LTS (headless):
  blender -b --factory-startup -P animation.py -- [options]

Stages (default: render):
  --stage render   build the 3D scene and render frames to renders/frames/
  --stage audio    synthesise music + sound design, mix with the narration (audio/*.wav, sound_design.txt)
  --stage edit     assemble frames, titles, captions, grain and audio in the Video Sequencer and
                   encode final_video.mp4
  --stage all      render + audio + edit

Options:
  --quality preview|final         preview = 270x480, 4 samples; final = 540x960, 6 samples (upscaled 2x in the edit)
  --frames A-B                    render only this frame range (resumable: existing frames are kept)
  --stills F1,F2,...              render single frames (look-dev checks)
  --out DIR                       frame folder (default renders/frames)
  --no-voice                      edit stage: leave the narration and captions out (for CapCut)
  --output NAME                   edit stage: output file name
  --bitrate KBPS                  edit stage: video bitrate
  --save-blend PATH               also save the generated .blend (the scene, cameras, animation and frame handler)

Code map (the brief's suggested architecture, by section):
  setup_project / setup_render_settings  reset_scene(), setup_render(), build_compositor()
  create_materials                       build_materials()
  create_vesuvius / environment          build_terrain(), build_countryside()
  create_pompeii_environment             build_town(), build_walls(), build_amphitheatre()
  create_roman_buildings                 build_street(), build_forum(), build_roof_patch(), build_dig()
  create_characters                      build_roman(), build_people()
  create_volcanic_effects                build_puffs(), build_particles(), build_emitters()
  create_camera / animate_scene_01..11   build_cameras() (one keyframed rig per shot) and on_frame(), which
                                         animates each shot's people, effects, deposits and light
  setup_lighting                         build_world(), the LOOKS presets and apply_shot()
  setup_audio                            stage_audio()
  save_project / render_animation        stage_render() (--save-blend), render_all.sh, stage_edit()

Timing comes from scene_timing.json (and build/vo_timing.json once tools/voiceover.py has run).
"""
