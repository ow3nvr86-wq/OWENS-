def cloud_puff_material(name, lit, shadow, glow_key=None):
    """The eruption cloud and the ash currents: opaque, billowing, lit from above, soft and broken at the edges;
    a slowly drifting noise ('boil_t') keeps the surface churning. Optional internal glow ('flash')."""
    m, nt, out = new_mat(name)
    geo = nd(nt, 'ShaderNodeNewGeometry')
    oc = obj_coord(nt)
    tb = value(nt, 'boil_t', 0.0)
    v = nd(nt, 'ShaderNodeVectorMath', p_operation='ADD', Vector=oc)
    nt.links.new(comb(nt, mth(nt, 'MULTIPLY', tb, 0.05), mth(nt, 'MULTIPLY', tb, -0.03), mth(nt, 'MULTIPLY', tb, 0.08)), v.inputs[1])
    n = nd(nt, 'ShaderNodeTexNoise', Scale=1.6, Detail=6.0, Roughness=0.62, Distortion=0.4, Vector=v.outputs[0])
    nz = sep(nt, geo.outputs['Normal']).outputs['Z']
    shade = mth(nt, 'MULTIPLY_ADD', nz, 0.35, mth(nt, 'MULTIPLY_ADD', n.outputs['Fac'], 0.8, 0.0))
    col = mixc(nt, mth(nt, 'MULTIPLY_ADD', shade, 1.0, -0.1, clamp=True), rgba(shadow), rgba(lit))
    lw = nd(nt, 'ShaderNodeLayerWeight', Blend=0.35)
    edge = mth(nt, 'SUBTRACT', 1.0, mth(nt, 'POWER', lw.outputs['Facing'], 2.2))
    alpha = mth(nt, 'ADD', mth(nt, 'MULTIPLY_ADD', edge, 1.7, -0.35), mth(nt, 'MULTIPLY', mth(nt, 'SUBTRACT', n.outputs['Fac'], 0.5), 1.4), clamp=True)
    alpha = mth(nt, 'MULTIPLY', alpha, value(nt, name + '_op', 1.0), clamp=True)
    p = principled(nt, None, **{'Base Color': col, 'Roughness': 1.0, 'Specular IOR Level': 0.0})
    tl = nd(nt, 'ShaderNodeBsdfTranslucent', Color=col)
    mx1 = nd(nt, 'ShaderNodeMixShader', Fac=0.25)
    nt.links.new(p.outputs[0], mx1.inputs[1])
    nt.links.new(tl.outputs[0], mx1.inputs[2])
    sh = mx1.outputs[0]
    if glow_key:
        em = nd(nt, 'ShaderNodeEmission', Color=(1.0, 0.55, 0.28, 1),
                Strength=mth(nt, 'MULTIPLY', value(nt, glow_key, 0.0), mth(nt, 'POWER', n.outputs['Fac'], 3.0)))
        ad = nd(nt, 'ShaderNodeAddShader')
        nt.links.new(sh, ad.inputs[0])
        nt.links.new(em.outputs[0], ad.inputs[1])
        sh = ad.outputs[0]
    tr = nd(nt, 'ShaderNodeBsdfTransparent')
    mx = nd(nt, 'ShaderNodeMixShader', Fac=alpha)
    nt.links.new(tr.outputs[0], mx.inputs[1])
    nt.links.new(sh, mx.inputs[2])
    nt.links.new(mx.outputs[0], out.inputs['Surface'])
    for k in ('boil_t', name + '_op') + ((glow_key,) if glow_key else ()):
        register_value(m, k, k)
    m.blend_method = 'HASHED'
    MAT[name] = m


