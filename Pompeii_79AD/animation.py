def smooth(x):
    x = min(max(x, 0.0), 1.0)
    return x * x * (3 - 2 * x)


def ramp(t, a, b):
    return smooth((t - a) / (b - a)) if b > a else float(t >= a)


def u_of(name, t):
    """0..1 progress of time t through a shot."""
    s = SHOT[name]
    return min(max((t - s['t0']) / (s['t1'] - s['t0']), 0.0), 1.0)



def sstep(x, a, b):
    t = np.clip((np.asarray(x, float) - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


