def col_height(t):
    a = EV['erupt'][0]
    return 0.0 if t < a else HMAX * (1 - math.exp(-(t - a) / 3.6))


def umb_radius(t):
    return 14000.0 * min(max((t - 4.5) / 15.0, 0.0), 1.0) ** 0.75


def surge_front(t):
    a = EV['collapse'][0]
    if t < a:
        return -1.0
    return 300.0 + 11500.0 * min((t - a) / 6.0, 1.6) ** 1.15


def r_col(z):
    return 110.0 + 0.07 * z


def update_puffs(t, shot):
    show_plume = SHOTCFG[shot].get('plume', False)
    H = col_height(t)
    P = FXO['col_p']
    coll_k = ramp(t, EV['collapse'][0], EV['collapse'][1] + 2.0) if shot == 'surge' else 0.0
    for i, ob in enumerate(FXO['col']):
        z = P['f'][i] * HMAX
        vis = show_plume and H > z - 40.0
        ob.hide_render = not vis
        if not vis:
            continue
        g = min(max((H - z) / 700.0, 0.3), 1.0)
        rc = r_col(z)
        off = Vector((math.cos(P['th'][i]), math.sin(P['th'][i]), 0.0)) * rc * 0.55 * P['r'][i]
        drift = Vector((0.0, -0.1 * z, 40.0 * math.sin(t * 0.25 + i)))
        pos = VENT + off + Vector((0, 0, z)) + drift
        if coll_k > 0 and z < 4500:
            k = coll_k * (1 - z / 4500.0)
            rd = Vector((math.cos(P['th'][i]), math.sin(P['th'][i]) * 0.6 - 0.6, 0)).normalized()
            pos += rd * 1500.0 * k - Vector((0, 0, 0.45 * z * k))
        s = rc * 0.8 * P['s'][i] * g * (1.0 + 0.4 * coll_k)
        ob.location = pos
        ob.scale = (s, s, s * 0.9)
        ob.rotation_euler.z = i * 0.7 + t * 0.03
    Q = FXO['head_p']
    for i, ob in enumerate(FXO['head']):
        vis = show_plume and H > 300.0
        ob.hide_render = not vis
        if not vis:
            continue
        rc = r_col(H) * 1.3
        off = Vector((math.cos(Q['th'][i]), math.sin(Q['th'][i]), 0.0)) * rc * 0.7 * Q['r'][i]
        z = H - Q['dz'][i] * 0.12 * H
        ob.location = VENT + off + Vector((0.0, -0.1 * z, z))
        s = rc * Q['s'][i] * (0.6 + 0.4 * min(H / 4000.0, 1.0))
        ob.scale = (s, s, s * 0.8)
    R = umb_radius(t)
    U = FXO['umb_p']
    c = Vector((VX, VY - 0.5 * R, 0.0))
    for i, ob in enumerate(FXO['umb']):
        vis = show_plume and R > 300.0
        ob.hide_render = not vis
        if not vis:
            continue
        rho, th = U['rho'][i], U['th'][i]
        p = c + Vector((math.cos(th), 0.78 * math.sin(th), 0.0)) * rho * R
        p.z = HMAX * 0.86 + U['dz'][i] * 900.0 - 900.0 * rho ** 2
