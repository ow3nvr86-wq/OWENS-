COLL = {}


def coll(name):
    if name not in COLL:
        c = bpy.data.collections.new(name)
        bpy.context.scene.collection.children.link(c)
        COLL[name] = c
    return COLL[name]


def mesh_obj(name, verts, faces, mat=None, collection='World', smooth=True, loc=(0, 0, 0)):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], [], [tuple(f) for f in faces])
    me.update()
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    ob.location = loc
    if mat is not None:
        me.materials.append(mat)
    coll(collection).objects.link(ob)
    return ob


def obj_from_bm(name, bm, mats=None, collection='World', smooth=False, loc=(0, 0, 0)):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    ob.location = loc
    if mats is not None:
        for m in (mats if isinstance(mats, (list, tuple)) else [mats]):
            me.materials.append(m)
    coll(collection).objects.link(ob)
    return ob


def add_box(bm, x0, y0, z0, x1, y1, z1, matrix=Matrix(), mi=0):
    """An axis-aligned box (8 verts, 6 outward faces), built directly: bmesh.ops would rescan the whole mesh."""
    if x1 < x0:
        x0, x1 = x1, x0
    if y1 < y0:
        y0, y1 = y1, y0
    if z1 < z0:
        z0, z1 = z1, z0
    xs, ys, zs = (x0, x1), (y0, y1), (z0, z1)
    vs = [bm.verts.new(matrix @ Vector((xs[i], ys[j], zs[k]))) for k in (0, 1) for j in (0, 1) for i in (0, 1)]
    for f in ((0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)):
        bm.faces.new([vs[q] for q in f]).material_index = mi


def add_cyl(bm, r1, r2, depth, seg=12, matrix=Matrix(), mi=0):
    r = bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=seg, radius1=r1, radius2=r2,
                              depth=depth, matrix=matrix)
    _set_mi(bm, r['verts'], mi)


def add_sphere(bm, r, u=12, v=8, matrix=Matrix(), mi=0):
    res = bmesh.ops.create_uvsphere(bm, u_segments=u, v_segments=v, radius=r, matrix=matrix)
    _set_mi(bm, res['verts'], mi)


def _set_mi(bm, verts, mi):
    if not mi:
        return
    for f in {f for v in verts for f in v.link_faces}:
        f.material_index = mi


def add_quad(bm, pts, mi=0):
    vs = [bm.verts.new(p) for p in pts]
    f = bm.faces.new(vs)
    f.material_index = mi
    return f


def empty(name, loc=(0, 0, 0), collection='Rig'):
    e = bpy.data.objects.new(name, None)
