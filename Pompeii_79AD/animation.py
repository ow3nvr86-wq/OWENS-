# Pompeii materials: stone, plaster, wood, terracotta, roof tiles, ash, pumice, smoke, dust, volcanic rock
# Every building material reads three per-shot values: 'ashc' (a dusting of ash on up-facing surfaces while the
# pumice falls), 'decay' (lost plaster and grime in the excavated ruins) and, for walls, a painted red dado.
# ============================================================================
Z0 = 30.0                          # ground level inside the town walls (the town stands on a low lava spur)
ASH = (0.47, 0.455, 0.43)          # colour of fresh ash / pumice dust


def ash_and_decay(nt, col, rough, key_ash=True):
    """Mix ash onto up-facing faces (value 'ashc') and patches of lost plaster (value 'decay')."""
    geo = nd(nt, 'ShaderNodeNewGeometry')
    nz = sep(nt, geo.outputs['Normal']).outputs['Z']
    up = mth(nt, 'POWER', mth(nt, 'MAXIMUM', nz, 0.0), 2.0)
    wp = geo.outputs['Position']
    n = noise(nt, 0.9, 4.0, 0.6, vec=wp)
    if key_ash:
        a = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', up, value(nt, 'ashc', 0.0)), mth(nt, 'MULTIPLY_ADD', n, 0.6, 0.7), clamp=True)
        col = mixc(nt, a, col, rgba(ASH))
        rough = mth(nt, 'MAXIMUM', a, rough)
    return col, rough


def finish(m, nt, out, col, rough, bump=0.0, bump_scale=6.0, spec=0.35, keys=('ashc',)):
    p = principled(nt, out, **{'Base Color': col, 'Roughness': rough, 'Specular IOR Level': spec})
    if bump > 0:
        geo = nd(nt, 'ShaderNodeNewGeometry')
        b = nd(nt, 'ShaderNodeBump', Strength=bump, Distance=0.02,
               Height=noise(nt, bump_scale, 6.0, 0.65, vec=geo.outputs['Position']))
        nt.links.new(b.outputs['Normal'], p.inputs['Normal'])
    for k in keys:
        if k in nt.nodes:
            register_value(m, k, k)
    return p


def stone_material(name, c0, c1, scale=3.0, rough=0.85, bump=0.0, blocks=None):
    """Grey tuff, limestone or basalt: two-tone noise, darker grime low down, optional ashlar joints."""
    m, nt, out = new_mat(name)
    geo = nd(nt, 'ShaderNodeNewGeometry')
    wp = geo.outputs['Position']
    n1 = noise(nt, scale, 5.0, 0.6, vec=wp)
    n2 = noise(nt, scale * 7.0, 3.0, 0.5, vec=wp)
    col = mixc(nt, mth(nt, 'MULTIPLY_ADD', n1, 1.3, -0.15, clamp=True), rgba(c0), rgba(c1))
    col = mixc(nt, mth(nt, 'MULTIPLY', n2, 0.35), col, rgba([c * 0.7 for c in c0]))
    if blocks:
        b = nd(nt, 'ShaderNodeTexBrick', Vector=wp, Scale=1.0, p_offset=0.5, Color1=(1, 1, 1, 1), Color2=(0.9, 0.9, 0.9, 1),
               Mortar=(0.45, 0.45, 0.45, 1), **{'Mortar Size': 0.012, 'Brick Width': blocks[0], 'Row Height': blocks[1]})
        mul = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='MULTIPLY', Factor=1.0)
        nt.links.new(col, mul.inputs[6])
        nt.links.new(b.outputs['Color'], mul.inputs[7])
        col = mul.outputs[2]
    col, r = ash_and_decay(nt, col, rough)
    finish(m, nt, out, col, r, bump=bump, bump_scale=scale * 9)
    MAT[name] = m
    return m


