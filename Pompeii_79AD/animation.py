def column(bm, x, y, z, h, prof, scale=1.0, mi=0, seg=16, broken=None):
    """A column from a (radius, fraction-of-height) profile; broken=height at which it ends (a stump)."""
    top = h if broken is None else min(broken, h)
    pts = [(r * scale, f * h) for r, f in prof if f * h <= top + 1e-6]
    if broken is not None and broken < h:
        rr = pts[-1][0]
        pts.append((rr * 0.98, top))
    M = Matrix.Translation((x, y, z))
    lathe(bm, pts, seg, M, mi)
    if broken is None or broken >= h:
        f = bm.faces.new([bm.verts.new(M @ Vector((pts[-1][0] * math.cos(2 * math.pi * k / seg), pts[-1][0] * math.sin(2 * math.pi * k / seg), top)))
                          for k in range(seg)])
        f.material_index = mi


