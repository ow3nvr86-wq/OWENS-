def gn_scatter(name, pts, variant, rot, scale, inst_coll, collection, extra=None):
    me = bpy.data.meshes.new(name)
    me.vertices.add(len(pts))
    me.vertices.foreach_set('co', np.asarray(pts, np.float32).ravel())
    for an, arr, typ in (('variant', variant, 'INT'), ('rot', rot, 'FLOAT_VECTOR'), ('scl', scale, 'FLOAT_VECTOR')):
        a = me.attributes.new(an, typ, 'POINT')
        a.data.foreach_set('value' if typ == 'INT' else 'vector', np.asarray(arr).ravel().astype(
            np.int32 if typ == 'INT' else np.float32))
    for an, arr in (extra or {}).items():
        a = me.attributes.new(an, 'FLOAT', 'POINT')
        a.data.foreach_set('value', np.asarray(arr, np.float32))
    ob = bpy.data.objects.new(name, me)
    coll(collection).objects.link(ob)
    ng = bpy.data.node_groups.new(name + '_GN', 'GeometryNodeTree')
    ng.interface.new_socket('Geometry', in_out='INPUT', socket_type='NodeSocketGeometry')
    ng.interface.new_socket('Geometry', in_out='OUTPUT', socket_type='NodeSocketGeometry')
    N = ng.nodes
    gi, go = N.new('NodeGroupInput'), N.new('NodeGroupOutput')
    ci = N.new('GeometryNodeCollectionInfo')
    ci.inputs['Collection'].default_value = inst_coll
    ci.inputs['Separate Children'].default_value = True
    ci.inputs['Reset Children'].default_value = True
    iop = N.new('GeometryNodeInstanceOnPoints')
    iop.inputs['Pick Instance'].default_value = True

    def named(nm, dt):
        x = N.new('GeometryNodeInputNamedAttribute')
        x.data_type = dt
        x.inputs['Name'].default_value = nm
        return x.outputs['Attribute']
    ng.links.new(gi.outputs[0], iop.inputs['Points'])
    ng.links.new(ci.outputs[0], iop.inputs['Instance'])
    ng.links.new(named('variant', 'INT'), iop.inputs['Instance Index'])
    ng.links.new(named('rot', 'FLOAT_VECTOR'), iop.inputs['Rotation'])
    ng.links.new(named('scl', 'FLOAT_VECTOR'), iop.inputs['Scale'])
    ng.links.new(iop.outputs[0], go.inputs[0])
    mod = ob.modifiers.new('Scatter', 'NODES')
    mod.node_group = ng
    return ob


