def build_section():
    xs = np.arange(-420.0, 520.0 + 0.1, 2.0)
    ds = np.concatenate([np.arange(0, 4.0, 0.25), np.arange(4.0, 12.0, 1.0), np.arange(12.0, 230.0, 2.0)])
    X, D = np.meshgrid(xs, ds, indexing='xy')
    Z = height(X, np.full_like(X, YC)) - D
    verts = np.stack([X, np.full_like(X, YC), Z], -1).reshape(-1, 3)
    ny, nx = X.shape
    ii = np.arange(nx * ny).reshape(ny, nx)
    q = np.stack([ii[:-1, :-1], ii[1:, :-1], ii[1:, 1:], ii[:-1, 1:]], -1).reshape(-1, 4)
    c = verts[q].mean(1)
    dc = np.stack([D[:-1, :-1], D[1:, :-1], D[1:, 1:], D[:-1, 1:]], -1).reshape(-1, 4).mean(1)
    hole = (c[:, 0] > SH_X0) & (c[:, 0] < SH_X1) & (dc < SH_BASE)
    q = q[~hole]
    me = bpy.data.meshes.new('Section')
    me.vertices.add(len(verts))
    me.vertices.foreach_set('co', verts.astype(np.float32).ravel())
    me.loops.add(q.size)
    me.loops.foreach_set('vertex_index', q.astype(np.int32).ravel())
    me.polygons.add(len(q))
    me.polygons.foreach_set('loop_start', (np.arange(len(q)) * 4).astype(np.int32))
    me.update()
    a = me.attributes.new('depth', 'FLOAT', 'POINT')
    a.data.foreach_set('value', D.astype(np.float32).ravel())
    ob = bpy.data.objects.new('Section', me)
    me.materials.append(MAT['section'])
    coll('Section').objects.link(ob)
    ob['burn'] = 1000.0
    ob['patchy'] = 0.0
    SEC['face'] = ob
    build_section_house()


