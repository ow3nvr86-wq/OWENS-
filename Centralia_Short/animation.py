"""CENTRALIA - THE TOWN THAT BURNED FROM WITHIN.
A fully code-generated, cinematic 3D YouTube Short (1080x1920, 30 fps, 60 s).

Everything is generated by this Blender (bpy) script: the Appalachian terrain, the street grid of
Centralia (Pennsylvania) with ~500 procedural frame houses, shops, the Ukrainian church on the hill,
a colliery breaker and culm banks, period cars and pedestrians, the strip-mine pit used as the town
dump, the room-and-pillar coal mine under the town, the cut-away geological section with the
spreading fire front, the cut-open house with gas seeping into the basement, the 1981 sinkhole, the
cracked highway, all fire / smoke / ember particle effects, materials, lighting, haze, cameras, the
compositor grade, the synthesised music and sound effects, the edit (titles, captions, transitions,
film grain) and the final MP4 encode.

Run with Blender 4.2 LTS (headless):
  blender -b --factory-startup -P animation.py -- [options]

Stages (default: render):
  --stage render   build the 3D scene and render frames to renders/frames/
  --stage audio    synthesise music + SFX and write audio/mix_*.wav and sound_effects.md (numpy only)
  --stage edit     assemble frames, titles, captions, grain and audio in the Video Sequencer and
                   encode renders/centralia_final.mp4
  --stage all      render + audio + edit

Options:
  --quality preview|final         preview = 270x480, 4 samples; final = 540x960, 8 samples (upscaled 2x in the edit)
  --frames A-B                    render only this frame range (resumable: existing frames are kept)
  --stills F1,F2,...              render single frames (look-dev checks)
  --out DIR                       frame folder (default renders/frames)
  --no-voice                      edit stage: leave the narration and captions out (for CapCut)
  --output NAME                   edit stage: output file name in renders/
  --save-blend PATH               also save the generated .blend

Timing comes from scene_timing.json (and build/vo_timing.json once tools/voiceover.py has run).
"""
