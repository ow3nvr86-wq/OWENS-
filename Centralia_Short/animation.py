def tree_bm(seed, h=11.0, crown=3.6, blobs=6):
    rng = np.random.default_rng(seed)
    bm = bmesh.new()
    add_cyl(bm, 0.28, 0.14, h * 0.62, seg=7, matrix=Matrix.Translation((0, 0, h * 0.31 - 0.3)), mi=1)
    for k in range(blobs):
        a = rng.uniform(0, 2 * np.pi)
        r = rng.uniform(0.2, 0.75) * crown
        cz = h * rng.uniform(0.55, 0.9)
        s = crown * rng.uniform(0.55, 0.85)
        res = bmesh.ops.create_icosphere(bm, subdivisions=2, radius=s,
                                         matrix=Matrix.Translation((r * math.cos(a), r * math.sin(a), cz)))
        for v in res['verts']:
            nrm = v.co - Vector((r * math.cos(a), r * math.sin(a), cz))
            v.co += nrm.normalized() * float(rng.normal(0, 0.12)) * s
    return bm


