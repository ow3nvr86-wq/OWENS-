def xsec_front(t):
    """x position of the fire front in the section during scene 3 (moves west under the streets)."""
    a, b = EV['xsec_front']
    return 340.0 - 300.0 * ramp(t, a - 0.6, b + 0.4)


def xsec_time_at(x):
    a, b = EV['xsec_front']
    ts = np.linspace(a - 1, b + 1, 400)
    xs = np.array([xsec_front(t) for t in ts])
    i = int(np.argmin(np.abs(xs - x)))
    return float(ts[i])


