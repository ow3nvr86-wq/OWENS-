def strip(name, p0, p1, width, lift, mat, collection, seg=2.0, nw=2, hole=None):
    p0, p1 = np.array(p0, float), np.array(p1, float)
    L = np.linalg.norm(p1 - p0)
    d = (p1 - p0) / L
    nrm = np.array([-d[1], d[0]])
    n = max(1, int(L / seg))
    us = np.linspace(0, 1, n + 1)
    ws = np.linspace(-0.5, 0.5, nw + 1)
    U, W = np.meshgrid(us, ws, indexing='xy')
    P = p0[None, None, :] + (U[..., None] * L) * d[None, None, :] + (W[..., None] * width) * nrm[None, None, :]
    Z = height(P[..., 0], P[..., 1]) + lift
    verts = np.concatenate([P, Z[..., None]], -1).reshape(-1, 3)
    ii = np.arange(verts.shape[0]).reshape(U.shape)
    q = np.stack([ii[:-1, :-1], ii[:-1, 1:], ii[1:, 1:], ii[1:, :-1]], -1).reshape(-1, 4)
    if hole is not None:
        c = verts[q].mean(1)
        x0, x1, y0, y1 = hole
        q = q[~((c[:, 0] > x0) & (c[:, 0] < x1) & (c[:, 1] > y0) & (c[:, 1] < y1))]
    return verts, q


def merge_parts(name, parts, mat, collection):
    vs, fs, off = [], [], 0
    for v, q in parts:
        vs.append(v)
        fs.append(q + off)
        off += len(v)
    verts = np.concatenate(vs)
    faces = np.concatenate(fs)
    return mesh_obj(name, verts, faces, mat, collection=collection, smooth=True)


