def simple_mat(name, color, rough=0.7, noise_amt=0.15, noise_scale=8.0, metal=0.0, coat=0.0,
               emission=None, estr=0.0):
    m, nt, out = new_mat(name)
    n = noise(nt, noise_scale, 3.0, 0.55, vec=obj_coord(nt))
    base = mixc(nt, mth(nt, 'MULTIPLY', n, noise_amt), rgba(color), rgba([c * 0.55 for c in color]))
    p = principled(nt, out, **{'Base Color': base, 'Roughness': rough, 'Metallic': metal, 'Coat Weight': coat})
    if emission is not None:
        p.inputs['Emission Color'].default_value = rgba(emission)
        p.inputs['Emission Strength'].default_value = estr
    MAT[name] = m
    return m


def emission_mat(name, color, strength):
    m, nt, out = new_mat(name)
    e = nd(nt, 'ShaderNodeEmission', Color=rgba(color), Strength=strength)
    nt.links.new(e.outputs[0], out.inputs['Surface'])
    MAT[name] = m
    return m


def ground_material():
    """Terrain: grass / dirt / rock, black culm banks, scorched ground; 'season' set per shot."""
    m, nt, out = new_mat('ground')
    oc = obj_coord(nt)
    so = sep(nt, oc)
    big = noise(nt, 0.012, 3.0, 0.6, vec=oc)
    mid = noise(nt, 0.09, 3.0, 0.6, vec=oc)
    fine = noise(nt, 1.3, 2.0, 0.6, vec=oc)
    season = value(nt, 'season', 0.0)            # 0 = May 1962 (green), 1 = winter / today (dead brown)
    summer = mixc(nt, big, (0.075, 0.095, 0.03, 1), (0.10, 0.11, 0.045, 1))
    dead = mixc(nt, big, (0.13, 0.105, 0.065, 1), (0.10, 0.085, 0.06, 1))
    grass = mixc(nt, season, summer, dead)
    grass = mixc(nt, mth(nt, 'MULTIPLY', fine, 0.35), grass, (0.05, 0.045, 0.03, 1))
    dirt = (0.12, 0.095, 0.07, 1)
    col = mixc(nt, mth(nt, 'MULTIPLY_ADD', mid, 2.4, -1.25, clamp=True), grass, dirt)
    # steep slopes -> rock
    geo = nd(nt, 'ShaderNodeNewGeometry')
    nz = sep(nt, geo.outputs['Normal']).outputs['Z']
    steep = mth(nt, 'MULTIPLY_ADD', nz, -5.0, 4.4, clamp=True)
    col = mixc(nt, steep, col, (0.09, 0.085, 0.08, 1))
    # culm banks and the pit floor: black coal waste
    blk = None
    for cx, cy, r in ((520.0, 380.0, 75.0), (560.0, 260.0, 60.0), (470.0, 450.0, 50.0), (PIT[0], PIT[1], 30.0)):
        d = nd(nt, 'ShaderNodeVectorMath', p_operation='DISTANCE', Vector=oc)
        d.inputs[1].default_value = (cx, cy, 0.0)
        # distance in xy only: flatten z first
        flat = nd(nt, 'ShaderNodeVectorMath', p_operation='MULTIPLY', Vector=oc)
        flat.inputs[1].default_value = (1.0, 1.0, 0.0)
        nt.links.new(flat.outputs[0], d.inputs[0])
        k = mth(nt, 'MULTIPLY_ADD', d.outputs['Value'], -1.0 / (0.25 * r), 1.0 / 0.25, clamp=True)
        blk = k if blk is None else mth(nt, 'MAXIMUM', blk, k)
    col = mixc(nt, mth(nt, 'MULTIPLY', blk, mth(nt, 'MULTIPLY_ADD', fine, 0.5, 0.6)), col, (0.018, 0.017, 0.017, 1))
    rough = mth(nt, 'MULTIPLY_ADD', blk, -0.35, 0.92)
    p = principled(nt, out, **{'Base Color': col, 'Roughness': rough, 'Specular IOR Level': 0.3})
    b = nd(nt, 'ShaderNodeBump', Strength=0.25, Distance=0.1, Height=mth(nt, 'ADD', fine, mid))
    nt.links.new(b.outputs[0], p.inputs['Normal'])
    MAT['ground'] = m
    register_value(m, 'season', 'season')


def asphalt_material():
    """Asphalt with a per-shot 'decay': cracks, tar patches and weeds (abandoned era)."""
    m, nt, out = new_mat('asphalt')
    oc = obj_coord(nt)
    n1 = noise(nt, 0.6, 3.0, 0.6, vec=oc)
    n2 = noise(nt, 0.05, 2.0, 0.5, vec=oc)
    decay = value(nt, 'decay', 0.0)
    col = mixc(nt, n1, (0.035, 0.034, 0.033, 1), (0.06, 0.058, 0.055, 1))
    col = mixc(nt, mth(nt, 'MULTIPLY', n2, 0.6), col, (0.08, 0.075, 0.07, 1))
    # crack network (voronoi cell edges) warped by noise
    warp = nd(nt, 'ShaderNodeVectorMath', p_operation='ADD', Vector=oc)
    nt.links.new(noise(nt, 0.4, 2.0, 0.5, vec=oc, out='Color'), warp.inputs[1])
    vor = nd(nt, 'ShaderNodeTexVoronoi', Vector=warp.outputs[0], Scale=0.55, p_feature='DISTANCE_TO_EDGE')
    crack = mth(nt, 'LESS_THAN', vor.outputs['Distance'], 0.035)
    crack = mth(nt, 'MULTIPLY', crack, mth(nt, 'MULTIPLY_ADD', n2, 3.0, -1.0, clamp=True))
    crack = mth(nt, 'MULTIPLY', crack, decay)
    weeds = mth(nt, 'MULTIPLY', mth(nt, 'LESS_THAN', vor.outputs['Distance'], 0.09), mth(nt, 'MULTIPLY_ADD', n1, 3.0, -1.6, clamp=True))
    weeds = mth(nt, 'MULTIPLY', weeds, decay)
    col = mixc(nt, weeds, col, (0.07, 0.075, 0.03, 1))
    col = mixc(nt, crack, col, (0.006, 0.005, 0.005, 1))
