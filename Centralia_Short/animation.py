def coal_burn_material(name, origin, front_w=14.0, scale=0.35):
    """Anthracite: black and glassy, with a glowing crack network where the fire has reached.
    The burnt radius is read from the object's custom property 'burn' (keyframed)."""
    m, nt, out = new_mat(name)
    oc = obj_coord(nt)
    burn = attr(nt, 'burn', 'OBJECT')
    flat = nd(nt, 'ShaderNodeVectorMath', p_operation='MULTIPLY', Vector=oc)
    flat.inputs[1].default_value = (1.0, 1.0, 0.0)
    dist = nd(nt, 'ShaderNodeVectorMath', p_operation='DISTANCE', Vector=flat.outputs[0])
    dist.inputs[1].default_value = (origin[0], origin[1], 0.0)
    d = dist.outputs['Value']
    behind = mth(nt, 'SUBTRACT', burn, d)
    burnt = mth(nt, 'MULTIPLY', behind, 1.0 / 25.0, clamp=True)
    front = mth(nt, 'EXPONENT', mth(nt, 'MULTIPLY', mth(nt, 'POWER', mth(nt, 'DIVIDE', behind, front_w), 2.0), -1.0))
    warp = nd(nt, 'ShaderNodeVectorMath', p_operation='ADD', Vector=oc)
    nt.links.new(noise(nt, 0.7, 2.0, 0.5, vec=oc, out='Color'), warp.inputs[1])
    vor = nd(nt, 'ShaderNodeTexVoronoi', Vector=warp.outputs[0], Scale=scale * 2.2, p_feature='DISTANCE_TO_EDGE')
    cracks = mth(nt, 'SUBTRACT', 1.0, mth(nt, 'MULTIPLY', vor.outputs['Distance'], 22.0), clamp=True)
    breakup = mth(nt, 'MULTIPLY_ADD', noise(nt, 0.9, 2.0, 0.5, vec=oc), 2.5, -0.9, clamp=True)
    cracks = mth(nt, 'MULTIPLY', cracks, breakup)
    flick = noise(nt, 0.25, 2.0, 0.5, vec=oc)
    heat = mth(nt, 'ADD', mth(nt, 'MULTIPLY', burnt, 0.5), mth(nt, 'MULTIPLY', front, 1.0))
    patt = mth(nt, 'ADD', cracks, mth(nt, 'MULTIPLY_ADD', flick, 0.35, -0.12, clamp=True))
    heat = mth(nt, 'MULTIPLY', heat, patt, clamp=True)
    em = glow_texture(nt, oc, heat)
    n = noise(nt, 2.0, 3.0, 0.6, vec=oc)
    base = mixc(nt, n, (0.012, 0.012, 0.013, 1), (0.03, 0.028, 0.026, 1))
    base = mixc(nt, burnt, base, (0.06, 0.035, 0.025, 1))
    p = principled(nt, out, **{'Base Color': base, 'Roughness': mth(nt, 'MULTIPLY_ADD', n, 0.3, 0.25), 'Specular IOR Level': 0.6,
                               'Emission Color': em, 'Emission Strength': mth(nt, 'MULTIPLY', heat, 5.0)})
    b = nd(nt, 'ShaderNodeBump', Strength=0.5, Distance=0.08, Height=noise(nt, 2.0, 1.0, 0.5, vec=oc))   # cheap bump (no voronoi)
    nt.links.new(b.outputs[0], p.inputs['Normal'])
    MAT[name] = m
    return m


def particle_materials():
    # smoke: soft billboard puffs; colour attribute 'sm' = (seed, age, glow, opacity)
    m, nt, out = new_mat('smoke')
    uv = nd(nt, 'ShaderNodeUVMap').outputs[0]
    sm = nd(nt, 'ShaderNodeVertexColor', p_layer_name='sm')
    sc = nd(nt, 'ShaderNodeSeparateColor', Color=sm.outputs['Color'])
    seed, age, glow = sc.outputs[0], sc.outputs[1], sc.outputs[2]
    opac = sm.outputs['Alpha']
    su = sep(nt, uv)
    du = mth(nt, 'SUBTRACT', su.outputs['X'], 0.5)
    dv = mth(nt, 'SUBTRACT', su.outputs['Y'], 0.5)
    r2 = mth(nt, 'MULTIPLY', mth(nt, 'ADD', mth(nt, 'MULTIPLY', du, du), mth(nt, 'MULTIPLY', dv, dv)), 4.0)
    fall = mth(nt, 'POWER', mth(nt, 'SUBTRACT', 1.0, r2, clamp=True), 1.6)
    v = comb(nt, mth(nt, 'MULTIPLY_ADD', su.outputs['X'], 1.7, mth(nt, 'MULTIPLY', seed, 37.0)),
             mth(nt, 'MULTIPLY_ADD', su.outputs['Y'], 1.7, mth(nt, 'MULTIPLY', seed, 11.0)),
             mth(nt, 'MULTIPLY', age, 2.2))
    n = noise(nt, 2.2, 5.0, 0.6, vec=v)
    dens = mth(nt, 'MULTIPLY', fall, mth(nt, 'MULTIPLY_ADD', n, 2.2, -0.75, clamp=True))
    dens = mth(nt, 'MULTIPLY', dens, opac, clamp=True)
    tintc = value(nt, 'smoke_tint', 0.0)        # 0 grey-brown smoke, 1 pale steam
    col = mixc(nt, tintc, (0.10, 0.09, 0.08, 1), (0.42, 0.42, 0.40, 1))
    col = mixc(nt, mth(nt, 'MULTIPLY', n, 0.4), col, (0.05, 0.045, 0.04, 1))
    # unlit smoke (emission + transparency): every smoke layer would otherwise sample all the lights,
    # which made smoky shots 3x slower; the shot's ambient level 'smoke_lum' stands in for the lighting,
    # brighter toward the top of each puff, plus the orange underglow from the fire
    lum = value(nt, 'smoke_lum', 0.3)
    shadeuv = mth(nt, 'MULTIPLY_ADD', su.outputs['Y'], 0.6, 0.7)
    lit = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='MULTIPLY', Factor=1.0)
    nt.links.new(col, lit.inputs[6])
    nt.links.new(comb(nt, mth(nt, 'MULTIPLY', lum, shadeuv), mth(nt, 'MULTIPLY', lum, shadeuv), mth(nt, 'MULTIPLY', lum, shadeuv)), lit.inputs[7])
    glowc = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='MULTIPLY', Factor=1.0)
    glowc.inputs[6].default_value = (1.0, 0.35, 0.08, 1)
    g3 = mth(nt, 'MULTIPLY', glow, 2.5)
    nt.links.new(comb(nt, g3, g3, g3), glowc.inputs[7])
    addc = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='ADD', Factor=1.0)
    nt.links.new(lit.outputs[2], addc.inputs[6])
    nt.links.new(glowc.outputs[2], addc.inputs[7])
    em = nd(nt, 'ShaderNodeEmission', Color=addc.outputs[2], Strength=1.0)
    tr = nd(nt, 'ShaderNodeBsdfTransparent')
    mx = nd(nt, 'ShaderNodeMixShader', Fac=dens)
    nt.links.new(tr.outputs[0], mx.inputs[1])
    nt.links.new(em.outputs[0], mx.inputs[2])
    nt.links.new(mx.outputs[0], out.inputs['Surface'])
    MAT['smoke'] = m
    register_value(m, 'smoke_tint', 'smoke_tint')
    register_value(m, 'smoke_lum', 'smoke_lum')
    # gas: a pale grey variant used for the carbon monoxide shot
    m2 = m.copy()
    m2.name = 'gas'
    m2.node_tree.nodes['smoke_tint'].outputs[0].default_value = 1.0
    MAT['gas'] = m2
    register_value(m2, 'smoke_lum', 'smoke_lum')

    # flames: emissive tongues, colour attribute 'sm' = (seed, age, heat, opacity)
    m, nt, out = new_mat('flame')
    uv = nd(nt, 'ShaderNodeUVMap').outputs[0]
    sm = nd(nt, 'ShaderNodeVertexColor', p_layer_name='sm')
    sc = nd(nt, 'ShaderNodeSeparateColor', Color=sm.outputs['Color'])
    seed, age, heat = sc.outputs[0], sc.outputs[1], sc.outputs[2]
    su = sep(nt, uv)
    x, y = su.outputs['X'], su.outputs['Y']
    width = mth(nt, 'MULTIPLY', mth(nt, 'POWER', mth(nt, 'SUBTRACT', 1.0, y, clamp=True), 0.8), 0.48)
    dx = mth(nt, 'ABSOLUTE', mth(nt, 'SUBTRACT', x, 0.5))
    v = comb(nt, mth(nt, 'MULTIPLY_ADD', x, 3.0, mth(nt, 'MULTIPLY', seed, 41.0)),
             mth(nt, 'SUBTRACT', mth(nt, 'MULTIPLY', y, 2.2), mth(nt, 'MULTIPLY', age, 6.0)),
             mth(nt, 'MULTIPLY', seed, 7.0))
    n = noise(nt, 1.8, 4.0, 0.6, vec=v)
    shape = mth(nt, 'SUBTRACT', 1.0, mth(nt, 'DIVIDE', dx, mth(nt, 'ADD', width, 0.001)), clamp=True)
    body = mth(nt, 'MULTIPLY', shape, mth(nt, 'MULTIPLY_ADD', n, 2.0, mth(nt, 'MULTIPLY_ADD', y, -1.1, -0.15), clamp=True))
    body = mth(nt, 'MULTIPLY', body, mth(nt, 'MULTIPLY', y, 12.0, clamp=True))
    body = mth(nt, 'MULTIPLY', body, sm.outputs['Alpha'], clamp=True)
    t = mth(nt, 'MULTIPLY', body, mth(nt, 'MULTIPLY_ADD', heat, 0.6, 0.5), clamp=True)
    col = ramp_node(nt, t, [(0.0, (0.3, 0.02, 0.0)), (0.35, (1.0, 0.18, 0.01)), (0.7, (1.0, 0.5, 0.08)), (1.0, (1.0, 0.85, 0.5))])
    em = nd(nt, 'ShaderNodeEmission', Color=col, Strength=mth(nt, 'MULTIPLY', t, 14.0))
    tr = nd(nt, 'ShaderNodeBsdfTransparent')
    mx = nd(nt, 'ShaderNodeMixShader', Fac=mth(nt, 'MULTIPLY', body, 1.6, clamp=True))
    nt.links.new(tr.outputs[0], mx.inputs[1])
    nt.links.new(em.outputs[0], mx.inputs[2])
    nt.links.new(mx.outputs[0], out.inputs['Surface'])
    MAT['flame'] = m
    emission_mat('ember', (1.0, 0.45, 0.08), 40.0)
    simple_mat('slurry', (0.33, 0.32, 0.30), rough=0.6, noise_amt=0.3, noise_scale=3.0)


def section_material():
    """The cut face of the ground (scene 3 / 5): soil, sandstone and shale beds, two coal seams with
    room-and-pillar workings, and the fire: burning where x > the face object's 'burn' property."""
    m, nt, out = new_mat('section')
    oc = obj_coord(nt)
    so = sep(nt, oc)
    X = so.outputs['X']
    depth = attr(nt, 'depth', 'GEOMETRY')
    burn = attr(nt, 'burn', 'OBJECT')
    patchy = attr(nt, 'patchy', 'OBJECT')
    n_big = noise(nt, 0.02, 3.0, 0.6, vec=oc)
    n_mid = noise(nt, 0.15, 4.0, 0.6, vec=oc)
    n_fine = noise(nt, 1.5, 2.0, 0.6, vec=oc)
    # bedding: depth + gentle dip + wobble
    bed = mth(nt, 'ADD', mth(nt, 'ADD', depth, mth(nt, 'MULTIPLY', X, 0.06)), mth(nt, 'MULTIPLY', n_big, 6.0))
    stripes = mth(nt, 'FRACT', mth(nt, 'MULTIPLY', bed, 1 / 7.5))
    stripes2 = mth(nt, 'FRACT', mth(nt, 'MULTIPLY', bed, 1 / 2.3))
    rock = mixc(nt, mth(nt, 'GREATER_THAN', stripes, 0.55), (0.20, 0.17, 0.13, 1), (0.11, 0.105, 0.10, 1))
    rock = mixc(nt, mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', stripes2, 0.7), 0.35), rock, (0.26, 0.22, 0.17, 1))
    rock = mixc(nt, mth(nt, 'MULTIPLY', n_mid, 0.6), rock, (0.07, 0.065, 0.06, 1))
    soil = mixc(nt, n_mid, (0.16, 0.11, 0.07, 1), (0.22, 0.16, 0.10, 1))
    top = mth(nt, 'LESS_THAN', mth(nt, 'ADD', depth, mth(nt, 'MULTIPLY', n_mid, 2.0)), 4.0)
    col = mixc(nt, top, rock, soil)
    col = mixc(nt, mth(nt, 'LESS_THAN', depth, 0.45), col, (0.06, 0.045, 0.03, 1))
    # coal seams (Seven-Foot above, Buck Mountain below; depths illustrative, the real fire is up to ~90 m deep)
    def seam(d0, thick):
        c = mth(nt, 'ADD', mth(nt, 'MULTIPLY', X, -0.07), d0)
        return mth(nt, 'LESS_THAN', mth(nt, 'ABSOLUTE', mth(nt, 'SUBTRACT', bed, mth(nt, 'ADD', c, mth(nt, 'MULTIPLY', X, 0.06)))), thick / 2)
    s1 = seam(38.0, 3.0)
    s2 = seam(66.0, 5.0)
    seams = mth(nt, 'MAXIMUM', s1, s2)
    # room-and-pillar: rooms (open voids) between coal pillars
    room = mth(nt, 'LESS_THAN', mth(nt, 'FRACT', mth(nt, 'MULTIPLY', mth(nt, 'ADD', X, mth(nt, 'MULTIPLY', n_mid, 3.0)), 1 / 15.0)), 0.42)
    room = mth(nt, 'MULTIPLY', room, seams)
    coal = mixc(nt, n_fine, (0.012, 0.012, 0.013, 1), (0.03, 0.03, 0.03, 1))
    col = mixc(nt, seams, col, coal)
    col = mixc(nt, room, col, (0.004, 0.003, 0.003, 1))
    # fire: burnt where x > burn (fire came from the east); 'patchy' breaks it into hot spots
    behind = mth(nt, 'SUBTRACT', X, burn)
    burnt = mth(nt, 'MULTIPLY', behind, 1.0 / 30.0, clamp=True)
    front = mth(nt, 'EXPONENT', mth(nt, 'MULTIPLY', mth(nt, 'POWER', mth(nt, 'DIVIDE', behind, 9.0), 2.0), -1.0))
    spots = mth(nt, 'MULTIPLY_ADD', noise(nt, 0.03, 2.0, 0.5, vec=oc), 3.0, -1.1, clamp=True)
    spots = mth(nt, 'ADD', mth(nt, 'MULTIPLY', spots, patchy), mth(nt, 'SUBTRACT', 1.0, patchy))
    flick = mth(nt, 'MULTIPLY_ADD', noise(nt, 0.6, 3.0, 0.6, vec=oc), 1.6, -0.25, clamp=True)
    heat_seam = mth(nt, 'MULTIPLY', mth(nt, 'ADD', mth(nt, 'MULTIPLY', burnt, 0.7), mth(nt, 'MULTIPLY', front, 1.2)), seams)
    heat_seam = mth(nt, 'MULTIPLY', heat_seam, mth(nt, 'ADD', mth(nt, 'MULTIPLY', room, 0.6), flick))
    heat_seam = mth(nt, 'MULTIPLY', heat_seam, spots)
    # heated, fractured rock above the burning seams: glowing cracks fading toward the surface
    mp = nd(nt, 'ShaderNodeMapping', Vector=oc, Scale=(1.0, 1.0, 0.35))
    vor = nd(nt, 'ShaderNodeTexVoronoi', Vector=mp.outputs[0], Scale=0.22, p_feature='DISTANCE_TO_EDGE')
    frac = mth(nt, 'SUBTRACT', 1.0, mth(nt, 'MULTIPLY', vor.outputs['Distance'], 30.0), clamp=True)
    frac = mth(nt, 'MULTIPLY', frac, mth(nt, 'MULTIPLY_ADD', noise(nt, 0.08, 2.0, 0.5, vec=oc), 3.0, -1.2, clamp=True))
    above = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY_ADD', depth, 1 / 40.0, -0.05, clamp=True), burnt)
    above = mth(nt, 'MULTIPLY', above, mth(nt, 'LESS_THAN', depth, 70.0))
    heat_frac = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', frac, above), mth(nt, 'MULTIPLY', spots, 0.55))
    heat = mth(nt, 'ADD', heat_seam, heat_frac, clamp=False)
    scorch = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', burnt, mth(nt, 'MULTIPLY_ADD', depth, 1 / 60.0, 0.0, clamp=True)), 0.6)
    col = mixc(nt, mth(nt, 'MULTIPLY', scorch, spots), col, (0.17, 0.07, 0.035, 1))
    em = glow_texture(nt, oc, mth(nt, 'MINIMUM', heat, 1.0))
    p = principled(nt, out, **{'Base Color': col, 'Roughness': 0.9,
                               'Emission Color': em, 'Emission Strength': mth(nt, 'MULTIPLY', heat, 6.0)})
    b = nd(nt, 'ShaderNodeBump', Strength=0.35, Distance=0.3, Height=mth(nt, 'ADD', n_fine, n_mid))
    nt.links.new(b.outputs[0], p.inputs['Normal'])
    MAT['section'] = m


