def mine_flame_sources(center, radius, n, seed, burn_r):
    """Points around pillar bases inside the burnt zone of the mine, near a centre point."""
    rng = np.random.default_rng(seed)
    pts = []
    tries = 0
    while len(pts) < n and tries < 20000:
        tries += 1
        x = center[0] + rng.uniform(-radius, radius)
        y = center[1] + rng.uniform(-radius, radius)
        px = (x + 180 - 7.5) / 15.0
        py = (y + 180 - 7.5) / 15.0
        cx, cy = round(px) * 15.0 - 180 + 7.5, round(py) * 15.0 - 180 + 7.5
        dx, dy = x - cx, y - cy
        if max(abs(dx), abs(dy)) < 4.6 or max(abs(dx), abs(dy)) > 5.6:
            continue
        if math.hypot(x - MINE_ORIGIN[0], y - MINE_ORIGIN[1]) > burn_r - 4:
            continue
        pts.append((x, y, 0.1))
    return np.array(pts) + np.array(M0)


