def prism(bm, quad, thick, mi):
    """Slab from a planar quad (list of 4 points), extruded by 'thick' against its normal."""
    a, b, c, d = [Vector(p) for p in quad]
    n = (b - a).cross(d - a).normalized()
    top = [bm.verts.new(p) for p in (a, b, c, d)]
    bot = [bm.verts.new(p - n * thick) for p in (a, b, c, d)]
    faces = [top, bot[::-1]] + [[top[i], bot[i], bot[(i + 1) % 4], top[(i + 1) % 4]][::-1] for i in range(4)]
    for f in faces:
        bm.faces.new(f).material_index = mi


def tri(bm, pts, mi):
    f = bm.faces.new([bm.verts.new(p) for p in pts])
    f.material_index = mi


def window(bm, c, axis, w, h, sign=-1, glass=3):
    """Window on a wall: c = centre on the wall surface; axis 'x' (wall normal along y) or 'y'."""
    cx, cy, cz = c
    o = 0.03 * sign
    if axis == 'x':
        add_box(bm, cx - w / 2 - 0.09, cy + o - 0.02, cz - h / 2 - 0.1, cx + w / 2 + 0.09, cy + o + 0.02, cz + h / 2 + 0.09, mi=2)
        add_box(bm, cx - w / 2, cy + 2 * o - 0.015, cz - h / 2, cx + w / 2, cy + 2 * o + 0.015, cz + h / 2, mi=glass)
        add_box(bm, cx - w / 2 - 0.12, cy + o * 2.5 - 0.06, cz - h / 2 - 0.16, cx + w / 2 + 0.12, cy + o * 2.5 + 0.06, cz - h / 2 - 0.1, mi=2)
    else:
        add_box(bm, cx + o - 0.02, cy - w / 2 - 0.09, cz - h / 2 - 0.1, cx + o + 0.02, cy + w / 2 + 0.09, cz + h / 2 + 0.09, mi=2)
        add_box(bm, cx + 2 * o - 0.015, cy - w / 2, cz - h / 2, cx + 2 * o + 0.015, cy + w / 2, cz + h / 2, mi=glass)


def gable(bm, W, D, H, pitch, along, oh=0.45, mi_roof=1, mi_wall=0, y0=0.0):
    t = math.tan(math.radians(pitch))
    if along == 'Y':
        hr = H + W / 2 * t
        e = W / 2 + oh
        ze = hr - e * t
        prism(bm, [(-e, y0 - oh, ze), (0, y0 - oh, hr), (0, y0 + D + oh, hr), (-e, y0 + D + oh, ze)][::-1], 0.14, mi_roof)
        prism(bm, [(e, y0 - oh, ze), (0, y0 - oh, hr), (0, y0 + D + oh, hr), (e, y0 + D + oh, ze)], 0.14, mi_roof)
        tri(bm, [(-W / 2, y0, H), (W / 2, y0, H), (0, y0, hr - 0.05)], mi_wall)
        tri(bm, [(W / 2, y0 + D, H), (-W / 2, y0 + D, H), (0, y0 + D, hr - 0.05)], mi_wall)
    else:
        hr = H + D / 2 * t
        e = D / 2 + oh
        ze = hr - e * t
        yc = y0 + D / 2
        prism(bm, [(-W / 2 - oh, yc - e, ze), (W / 2 + oh, yc - e, ze), (W / 2 + oh, yc, hr), (-W / 2 - oh, yc, hr)][::-1], 0.14, mi_roof)
        prism(bm, [(-W / 2 - oh, yc + e, ze), (W / 2 + oh, yc + e, ze), (W / 2 + oh, yc, hr), (-W / 2 - oh, yc, hr)], 0.14, mi_roof)
        tri(bm, [(-W / 2, y0 + D, H), (-W / 2, y0, H), (-W / 2, yc, hr - 0.05)], mi_wall)
        tri(bm, [(W / 2, y0, H), (W / 2, y0 + D, H), (W / 2, yc, hr - 0.05)], mi_wall)
    return hr


