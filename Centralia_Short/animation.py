    # survivors: a handful of houses still stand today (five residents in 2020), plus the municipal building
    surv = np.zeros(n, bool)
    for target in ((15.0, 60.0), (-84.0, 150.0), (96.0, -190.0), (-176.0, -40.0), (186.0, 110.0), (-6.0, -210.0)):
        d = np.hypot(pts[:, 0] - target[0], pts[:, 1] - target[1])
        surv[int(np.argmin(d))] = True
    # demolition order for the time-lapse (scene 4): roughly spreading out from the fire area (south-east)
    d0 = np.hypot(pts[:, 0] - 250.0, pts[:, 1] + 300.0)
    order = (d0 - d0.min()) / (d0.max() - d0.min()) * 0.75 + rng.uniform(0, 0.25, n)
