def _raw_height(x, y):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    base = 0.028 * y + 0.008 * x
    north = 70.0 * sstep(y, 330.0, 760.0) + 18.0 * np.exp(-((x - CHURCH[0]) ** 2 + (y - CHURCH[1]) ** 2) / 75.0 ** 2)
    south = 85.0 * sstep(-y, 470.0, 900.0)
    sides = 55.0 * sstep(np.abs(x - 40.0), 420.0, 1000.0)
    hills = 22.0 * fbm(x / 520.0 + 3.3, y / 520.0 + 1.7, 4, seed=3) + 4.0 * fbm(x / 90.0, y / 90.0, 3, seed=9)
    town = sstep(-np.maximum.reduce([np.abs(x - 10.0) - 250.0, np.abs(y) - 300.0]), -10.0, 80.0)
    z = base + north + south + sides + (1.0 - 0.85 * town) * hills
    # the dump: an old strip-mine pit, ~11 m deep with steep walls
    px, py = (x - PIT[0]) / 34.0, (y - PIT[1]) / 22.0
    pr = np.sqrt(px * px + py * py)
    z = z - 11.0 * sstep(-pr, -1.0, -0.62)
    # culm banks (black waste heaps) beside the breaker
    for cx, cy, h, r in ((520.0, 380.0, 26.0, 70.0), (560.0, 260.0, 18.0, 55.0), (470.0, 450.0, 14.0, 45.0)):
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2)
        z = z + h * np.clip(1 - d / r, 0, 1) ** 1.3
    return z


_H0 = float(_raw_height(0.0, 0.0))


def height(x, y):
    return _raw_height(x, y) - _H0


