def house_lots():
    rng = random.Random(62)
    pts, rot, var, tint, lit = [], [], [], [], []
    for sx in STREETS_X:
        w = MAIN_W if sx == 0 else SIDE_W
        bounds = [TOWN_Y0] + STREETS_Y + [TOWN_Y1]
        for side in (-1, 1):
            for a, b in zip(bounds[:-1], bounds[1:]):
                y = a + SIDE_W / 2 + 4.5 if a in STREETS_Y else a + 2.0
                yend = b - SIDE_W / 2 - 4.5 if b in STREETS_Y else b - 2.0
                while True:
                    commercial = sx == 0 and -120 < y < 130 and rng.random() < 0.75
                    v = 3 if commercial else rng.choice([0, 0, 0, 1, 1, 2])
                    width = {0: 6.8, 1: 11.0, 2: 6.4, 3: 9.0}[v]
                    gap = 0.4 if v == 3 else rng.uniform(1.6, 3.2)
                    if y + width > yend:
                        break
                    setback = w / 2 + 2.2 + (0.4 if v == 3 else 2.4 + (2.4 if v != 2 else 3.6))
                    x = sx + side * setback
                    yc = y + width / 2
                    pts.append((x, yc, gz(x, yc)))
                    rot.append((0.0, 0.0, -math.pi / 2 if side > 0 else math.pi / 2))
                    var.append(v)
                    tint.append(rng.random())
                    lit.append(1.0 if rng.random() < 0.45 else 0.0)
                    y += width + gap
    return np.array(pts), np.array(rot), np.array(var), np.array(tint), np.array(lit)


