# Scene 1: the crack in the asphalt (a deforming patch of road) and the glow beneath it
# ============================================================================
CRACK = {}


def crack_paths():
    x0, x1, y0, y1 = CRACK_BOX
    rng = random.Random(14)
    main, y = [], HOOK[1] - 0.8
    for k in range(13):
        x = x0 + (x1 - x0) * k / 12
        main.append((x, y + rng.uniform(-0.25, 0.25) + 0.9 * (k / 12)))
    br1 = [main[5]] + [(main[5][0] + 0.4 * k + rng.uniform(-0.1, 0.1), main[5][1] - 0.35 * k) for k in range(1, 5)]
    br2 = [main[9]] + [(main[9][0] - 0.3 * k + rng.uniform(-0.1, 0.1), main[9][1] + 0.32 * k) for k in range(1, 5)]
    return [(np.array(main), 1.0), (np.array(br1), 0.45), (np.array(br2), 0.38)]


def seg_dist(P, A, B):
    AB = B - A
    t = np.clip(((P - A) @ AB) / (AB @ AB), 0, 1)
    return np.linalg.norm(P - (A + t[:, None] * AB), axis=1), t


def build_crack():
    """A flat patch of road with a slot cut out, plus a ribbon mesh along each crack path whose
    cross-section (lips, steep walls, deep V) widens as the crack opens."""
    x0, x1, y0, y1 = CRACK_BOX
    xs = np.arange(x0, x1 + 1e-6, 0.05)
    ys = np.arange(y0, y1 + 1e-6, 0.05)
    X, Y = np.meshgrid(xs, ys, indexing='xy')
    P = np.stack([X.ravel(), Y.ravel()], -1)
    base = height(P[:, 0], P[:, 1]) + 0.07
    ny, nx = X.shape
    ii = np.arange(nx * ny).reshape(ny, nx)
    q = np.stack([ii[:-1, :-1], ii[:-1, 1:], ii[1:, 1:], ii[1:, :-1]], -1).reshape(-1, 4)
    c = P[q].mean(1)
    cut = np.zeros(len(q), bool)
    ribbons = []
    for pts, wf in crack_paths():
        # resample the path every 2 cm
        seglen = np.linalg.norm(np.diff(pts, axis=0), axis=1)
        sacc = np.concatenate([[0], np.cumsum(seglen)])
        ss = np.arange(0, sacc[-1], 0.02)
        px = np.interp(ss, sacc, pts[:, 0])
        py = np.interp(ss, sacc, pts[:, 1])
        tang = np.stack([np.gradient(px), np.gradient(py)], -1)
        tang /= np.linalg.norm(tang, axis=1, keepdims=True)
        nrm = np.stack([-tang[:, 1], tang[:, 0]], -1)
        jag = 0.5 + 0.5 * fbm(px * 5.0, py * 5.0, 3, seed=81 + int(wf * 10))
        taper = np.clip(np.minimum(ss, sacc[-1] - ss) / 0.4, 0.15, 1.0) if wf < 1 else np.ones_like(ss)
        ribbons.append(dict(p=np.stack([px, py], -1), n=nrm, jag=jag, wf=wf * taper))
        for a_, b_ in zip(pts[:-1], pts[1:]):
            d, _ = seg_dist(c, a_, b_)
            cut |= d < 0.36 * wf + 0.06
    q = q[~cut]
    verts = np.concatenate([P, base[:, None]], -1)
    patch = mesh_obj('CrackPatch', verts, q, crack_material(), collection='Hook', smooth=False)
    patch.data.attributes.new('dz', 'FLOAT', 'POINT')
    patch['glow'] = 0.0
    CRACK['patch'] = patch
    CRACK['ribbons'] = ribbons
    # ribbon topology: 11 points across, strips along
    OFF = np.array([-1.0, -0.85, -0.7, -0.55, -0.3, 0.0, 0.3, 0.55, 0.7, 0.85, 1.0])
    CRACK['OFF'] = OFF
    faces, start = [], 0
    for r in ribbons:
        n = len(r['p'])
        idx = start + np.arange(n * len(OFF)).reshape(n, len(OFF))
        for i in range(n - 1):
            for k in range(len(OFF) - 1):
                faces.append((idx[i, k], idx[i, k + 1], idx[i + 1, k + 1], idx[i + 1, k]))
        start += n * len(OFF)
    rib = mesh_obj('CrackRibbon', np.zeros((start, 3)), faces, MAT['crack_patch'], collection='Hook', smooth=True)
    rib.data.attributes.new('dz', 'FLOAT', 'POINT')
    CRACK['obj'] = rib
    CRACK['base'] = base
    # glow plate under the crack and a flickering light
    zmin = float(base.min())
    mesh_obj('CrackGlow', [(x0, y0, zmin - 1.3), (x1, y0, zmin - 1.3), (x1, y1, zmin - 1.3), (x0, y1, zmin - 1.3)],
             [(0, 1, 2, 3)], MAT['deep_glow'], collection='Hook')
    ld = bpy.data.lights.new('CrackLight', 'POINT')
    ld.color = (1.0, 0.35, 0.06)
    ld.shadow_soft_size = 0.4
    lo = bpy.data.objects.new('CrackLight', ld)
    lo.location = (HOOK[0], HOOK[1] - 0.35, float(base.mean()) - 0.3)
    coll('Hook').objects.link(lo)
    CRACK['light'] = lo
    update_crack(0.0)


def crack_material():
    """Asphalt on top, broken gravel and glowing earth inside the crack (by depth below the surface)."""
    m, nt, out = new_mat('crack_patch')
    oc = obj_coord(nt)
    dz = attr(nt, 'dz', 'GEOMETRY')
    n1 = noise(nt, 0.6, 3.0, 0.6, vec=oc)
    n2 = noise(nt, 8.0, 2.0, 0.6, vec=oc)
    asphalt = mixc(nt, n1, (0.035, 0.034, 0.033, 1), (0.06, 0.058, 0.055, 1))
    inside = mth(nt, 'GREATER_THAN', dz, 0.025)
    gravel = mixc(nt, n2, (0.05, 0.04, 0.03, 1), (0.1, 0.08, 0.06, 1))
    col = mixc(nt, inside, asphalt, gravel)
    heat = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY_ADD', dz, 1 / 0.3, -0.08, clamp=True), mth(nt, 'MULTIPLY_ADD', n2, 0.6, 0.7))
    heat = mth(nt, 'MULTIPLY', heat, attr(nt, 'glow', 'OBJECT'))
    em = glow_texture(nt, oc, mth(nt, 'MINIMUM', heat, 1.0))
    p = principled(nt, out, **{'Base Color': col, 'Roughness': 0.85, 'Emission Color': em,
                               'Emission Strength': mth(nt, 'MULTIPLY', heat, 16.0)})
    b = nd(nt, 'ShaderNodeBump', Strength=0.4, Distance=0.02, Height=n2)
    nt.links.new(b.outputs[0], p.inputs['Normal'])
    MAT['crack_patch'] = m
    return m


def crack_state(t):
    a, b = EV['crack_open']
    k = ramp(t, a, b)
    w = 0.004 + 0.26 * k ** 1.3                 # half-width of the main crack (m)
    return k, w


def update_crack(t):
    k, w = crack_state(t)
    C = CRACK
    OFF = C['OFF']
    allv, alldz = [], []
    for r in C['ribbons']:
        hw = (w * r['wf'] * (0.7 + 0.6 * r['jag']))[:, None]                 # half-width per sample
        D = (0.9 + 0.5 * r['jag'])[:, None] * min(1.0, k * 3 + 0.05)          # depth of the V
        # lateral offsets: outer band (flat road, overlapping the cut in the patch) -> lip -> wall -> V
        band = 0.42                                                             # m, covers the slot in the patch
        lat = np.where(np.abs(OFF)[None, :] >= 0.85,
                       np.sign(OFF)[None, :] * (hw + (np.abs(OFF)[None, :] - 0.7) / 0.3 * band),
                       OFF[None, :] / 0.7 * hw)
        prof = np.interp(np.abs(OFF), [0.0, 0.3, 0.55, 0.7, 0.85, 1.0], [1.0, 0.85, 0.45, 0.0, 0.0, 0.0])
        heave = np.interp(np.abs(OFF), [0.0, 0.7, 0.85, 1.0], [0.0, 1.0, 0.4, 0.0]) * 0.035 * k
        xy = r['p'][:, None, :] + r['n'][:, None, :] * lat[..., None]
        zb = height(xy[..., 0], xy[..., 1]) + 0.071
        dz = prof[None, :] * D
        z = zb - dz + heave[None, :]
        allv.append(np.concatenate([xy, z[..., None]], -1).reshape(-1, 3))
        alldz.append(dz.reshape(-1))
    me = C['obj'].data
    me.vertices.foreach_set('co', np.concatenate(allv).astype(np.float32).ravel())
    me.attributes['dz'].data.foreach_set('value', np.concatenate(alldz).astype(np.float32))
    me.update()
    flick = 0.8 + 0.2 * math.sin(t * 23.0) * math.sin(t * 7.1 + 1)
    C['obj']['glow'] = (0.15 + 0.85 * k) * flick
    C['obj'].update_tag()
    C['light'].data.energy = 3000.0 * k ** 1.5 * flick


