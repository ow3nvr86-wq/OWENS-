def glint(t, cs):
    """The U-2 as a point of reflected sunlight once the camera has fallen far behind."""
    a, b = EV['glint']
    p = u2_fly_pos(t) + Vector((6.0, 0.0, 0.5))
    d = (p - Vector(cs['loc'])).length
    k = ramp(t, a, a + 1.5) * (1 - ramp(t, b, b + 0.4)) * min(max((d - 90.0) / 260.0, 0.0), 1.0)
    if k <= 0:
        return None
    tw = 0.7 + 0.3 * math.sin(t * 23.0) * math.sin(t * 7.3)
    return np.array([tuple(p)]), np.array([0.0045 * d]), np.zeros(1), np.zeros(1), np.array([k * tw]), np.ones(1)


