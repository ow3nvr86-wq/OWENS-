def hash01(a, b, salt=0.0):
    v = np.sin(a * 12.9898 + b * 78.233 + salt * 37.719) * 43758.5453
    return v - np.floor(v)


def emitter(kind, src, rate, life, vel, spread, size, opacity=1.0, glow=0.0, area=0.5, t0=-10.0, t1=1e9,
            rise=0.0, turb=0.4, wind=(0, 0, 0), salt=0.0, fade=None, flat=False, vjit=0.0):
    return dict(vjit=vjit, kind=kind, src=np.atleast_2d(np.array(src, float)), rate=rate, life=life, vel=np.array(vel, float),
                spread=spread, size=size, opacity=opacity, glow=glow, area=area, t0=t0, t1=t1, rise=rise, turb=turb,
                wind=np.array(wind, float), salt=salt, fade=fade, flat=flat)


def eval_emitter(e, t):
    """Returns (pos (N,3), size (N,), agen (N,), seed (N,), alpha (N,), glow (N,))."""
    K = len(e['src'])
    slots = int(math.ceil(e['life'] * e['rate'])) + 1
    k = np.repeat(np.arange(K), slots)
    j = np.tile(np.arange(slots), K)
    phase = hash01(k, 0.5, e['salt'])
    i_last = np.floor((t - e['t0']) * e['rate'] - phase)
    i = i_last - j
    tb = e['t0'] + (i + phase) / e['rate']
    age = t - tb
    ok = (age >= 0) & (age <= e['life']) & (tb <= e['t1']) & (i >= 0)
    k, i, age = k[ok], i[ok], age[ok]
    r1, r2, r3, r4 = (hash01(k + 0.1 * q, i, e['salt'] + q) for q in range(4))
    a = r1 * 2 * np.pi
    rr = np.sqrt(r2) * e['area']
    start = e['src'][k] + np.stack([rr * np.cos(a), rr * np.sin(a), np.zeros_like(a)], -1)
    dirn = np.stack([np.cos(a + 1.3), np.sin(a + 1.3), (r3 - 0.5) * (0.0 if e['flat'] else 0.6)], -1)
    u = age / e['life']
    vs = 1.0 - e['vjit'] * hash01(k + 0.5, i, e['salt'] + 7)          # per-particle launch speed (ragged jets)
    pos = start + (e['vel'][None, :] * vs[:, None] + e['wind'][None, :] * u[:, None]) * age[:, None] + dirn * (e['spread'] * age)[:, None]
    pos[:, 2] += 0.5 * e['rise'] * age ** 2
    tw = e['turb'] * np.stack([np.sin(age * 1.3 + r4 * 6.3), np.cos(age * 1.1 + r1 * 6.3), np.zeros_like(age)], -1) * u[:, None]
    pos += tw
    s0, s1 = e['size']
    size = (s0 + (s1 - s0) * u ** 0.6) * (0.7 + 0.6 * r3)
    alpha = e['opacity'] * np.clip(u / 0.12, 0, 1) * np.clip((1 - u) / 0.45, 0, 1)
    if e['fade'] is not None:
        alpha = alpha * ramp(t, *e['fade'])
    glow = np.full_like(u, e['glow'])
    return pos, size, u, r4, alpha, glow



def eval_dots(name, t):
    D = DOTS.get(name)
    if D is None:
        return None
    p = D['p'].copy()
    p[:, 0] += 0.25 * np.sin(t * 0.4 + D['ph'])
    p[:, 1] += 0.25 * np.cos(t * 0.33 + D['ph'] * 1.3)
    p[:, 2] += 0.15 * np.sin(t * 0.5 + D['ph'] * 0.7)
    tw = 0.75 + 0.25 * np.sin(t * 2.0 + D['ph'] * 5.0)
    return p, D['s'], np.zeros(len(p)), D['ph'] / 6.28, D['c'] * tw, np.zeros(len(p))


def cam_basis(cs):
    fwd = Vector(cs['fwd']).normalized()
    right = fwd.cross(Vector((0, 0, 1)))
    if right.length < 1e-4:
        right = Vector((1, 0, 0))
    right.normalize()
    up = right.cross(fwd).normalized()
    return np.array(right), np.array(up)


def update_particles(t, shot, cs, extra=None):
    right, up = cam_basis(cs)
    groups = {k: [] for k in MAXQ}
    for e in EMIT.get(shot['name'], []):
        if e['t0'] > t:
            continue
        groups[e['kind']].append(eval_emitter(e, t))
    dd = eval_dots(shot['name'], t)
    if dd is not None:
        groups['dot'].append(dd)
    for kind, g in (extra or {}).items():
        if g is not None:
            groups[kind].append(g)
    camp = np.array(cs['loc'])
    fwd = np.array(cs['fwd'])
    for kind in MAXQ:
        ob = PART[kind]
        n = MAXQ[kind]
        V = np.zeros((n, 4, 3))
        C = np.zeros((n, 4, 4))
        if groups[kind]:
            pos, size, u, seed, alpha, glow = (np.concatenate(x) for x in zip(*groups[kind]))
            rel = pos - camp
            d = np.linalg.norm(rel, axis=1)
            front = rel @ fwd > -2.0
            pos, size, u, seed, alpha, glow, d = (a[front] for a in (pos, size, u, seed, alpha, glow, d))
            if kind == 'dot':
                size = size + CUR.get('dot_grow', 0.0028) * d    # keep distant specks visible at this resolution
            if len(pos) > n:
                idx = np.argsort(d)[:n]
                pos, size, u, seed, alpha, glow, d = (a[idx] for a in (pos, size, u, seed, alpha, glow, d))
            m = len(pos)
            alpha = alpha * np.clip((d - size * 0.8) / (size * 1.5 + 0.3), 0, 1)
            rr = right[None, :] * size[:, None]
            uu = up[None, :] * size[:, None]
            V[:m, 0] = pos - rr - uu
            V[:m, 1] = pos + rr - uu
            V[:m, 2] = pos + rr + uu
            V[:m, 3] = pos - rr + uu
            C[:m] = np.stack([seed, u, glow, alpha], -1)[:, None, :]
        me = ob.data
        me.vertices.foreach_set('co', V.astype(np.float32).ravel())
        me.color_attributes['sm'].data.foreach_set('color', C.astype(np.float32).ravel())
        me.update()


