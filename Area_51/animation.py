def build_fence(name, pts, collection, h=3.0, step=3.0):
    """Chain-link fence along a polyline: posts, mesh, three strands of barbed wire on outriggers."""
    posts, wire = bmesh.new(), bmesh.new()
    verts, faces, uvs = [], [], []
    for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
        a, b = Vector((x0, y0, 0)), Vector((x1, y1, 0))
        L = (b - a).length
        n = max(1, int(L / step))
        za, zb = ground_z(x0, y0), ground_z(x1, y1)
        for k in range(n + 1):
            p = a.lerp(b, k / n)
            z = za + (zb - za) * k / n
            add_cyl(posts, 0.04, 0.04, h + 0.5, seg=6, matrix=Matrix.Translation((p.x, p.y, z + (h + 0.5) / 2)))
        base = len(verts)
