def camera_shot(name, lens, path, target, fstop=5.6, shake=0.0, focus=None, ease=True):
    """path/target: list of (u, (x, y, z)) keys with u in 0..1 of the shot."""
    s = SHOT[name]
    rig = empty('Rig_' + name)
    tgt = empty('Target_' + name)
    cd = bpy.data.cameras.new('Cam_' + name)
    cd.lens = lens
    cd.sensor_width = 24
    cd.sensor_fit = 'VERTICAL'
    cd.clip_start, cd.clip_end = 0.05, 40000
    cd.dof.use_dof = fstop < 50
    cd.dof.aperture_fstop = fstop
    cd.dof.aperture_blades = 6
    cam = bpy.data.objects.new('Cam_' + name, cd)
    coll('Rig').objects.link(cam)
    cam.parent = rig
    con = rig.constraints.new('TRACK_TO')
    con.target = tgt
    con.track_axis = 'TRACK_NEGATIVE_Z'
    con.up_axis = 'UP_Y'
    fe = empty('Focus_' + name)
    cd.dof.focus_object = tgt if focus is None else fe
    span = s['f1'] + 1 - s['f0']
    for u, p in path:
        rig.location = p
        rig.keyframe_insert('location', frame=s['f0'] + u * span)
    for u, p in target:
        tgt.location = p
        tgt.keyframe_insert('location', frame=s['f0'] + u * span)
    if focus is not None:
        for u, p in focus:
            fe.location = p
            fe.keyframe_insert('location', frame=s['f0'] + u * span)
    for ob in (rig, tgt, fe):
        if ob.animation_data:
            for fc in ob.animation_data.action.fcurves:
                for kp in fc.keyframe_points:
                    kp.interpolation = 'BEZIER'
                    kp.easing = ease if isinstance(ease, str) else ('EASE_IN_OUT' if ease else 'AUTO')
                    if not ease:
                        kp.handle_left_type = kp.handle_right_type = 'VECTOR'
    m = bpy.context.scene.timeline_markers.new('M_' + name, frame=s['f0'])
    m.camera = cam
    CAMS[name] = cam
    RIGS[name] = (rig, tgt)
    SHAKE[name] = shake
    return cam


def eval_loc(ob, f):
    ad = ob.animation_data
    v = Vector(ob.location)
    if ad and ad.action:
        for fc in ad.action.fcurves:
            if fc.data_path == 'location':
                v[fc.array_index] = fc.evaluate(f)
    return v


def cam_state(name, f):
    rig, tgt = RIGS[name]
    loc = eval_loc(rig, f)
    tl = eval_loc(tgt, f)
    fwd = (tl - loc).normalized()
    return {'loc': tuple(loc), 'fwd': tuple(fwd)}



def shake_offset(f, s):
    amp = SHAKE.get(s['name'], 0.0)
    if amp <= 0:
        return Vector((0, 0, 0))
    t = tsec(f)
    return Vector((math.sin(t * 7.0), math.sin(t * 5.3 + 1), math.sin(t * 4.1 + 2))) * amp



