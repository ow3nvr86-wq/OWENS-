def build_world(sc):
    w = bpy.data.worlds.new('Sky')
    sc.world = w
    w.use_nodes = True
    nt = w.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputWorld')
    tc = nd(nt, 'ShaderNodeTexCoord')
    gen = tc.outputs['Generated']
    z = sep(nt, gen).outputs['Z']
    up = mth(nt, 'POWER', mth(nt, 'MAXIMUM', z, 0.0), 0.3)
    hor = nd(nt, 'ShaderNodeRGB')
    hor.name = 'SkyHorizon'
    zen = nd(nt, 'ShaderNodeRGB')
    zen.name = 'SkyZenith'
    col = mixc(nt, up, hor.outputs[0], zen.outputs[0])
    # a soft glow around the sun / moon direction (dawn, dusk)
    sv = nd(nt, 'ShaderNodeCombineXYZ')
    sv.name = 'SunVec'
    dot = nd(nt, 'ShaderNodeVectorMath', p_operation='DOT_PRODUCT', Vector=gen)
    nt.links.new(sv.outputs[0], dot.inputs[1])
    g = mth(nt, 'POWER', mth(nt, 'MAXIMUM', dot.outputs['Value'], 0.0), 6.0)
    g2 = mth(nt, 'POWER', mth(nt, 'MAXIMUM', dot.outputs['Value'], 0.0), 60.0)
    gcol = nd(nt, 'ShaderNodeRGB')
    gcol.name = 'GlowCol'
    gamt = mth(nt, 'MULTIPLY', mth(nt, 'ADD', g, mth(nt, 'MULTIPLY', g2, 2.0)), value(nt, 'SunGlow', 0.0))
    glow = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='MULTIPLY', Factor=1.0)
    nt.links.new(gcol.outputs[0], glow.inputs[6])
    nt.links.new(comb(nt, gamt, gamt, gamt), glow.inputs[7])
    add = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='ADD', Factor=1.0)
    nt.links.new(col, add.inputs[6])
    nt.links.new(glow.outputs[2], add.inputs[7])
    # stars: tiny voronoi points, varied brightness, only above the horizon
    vs = nd(nt, 'ShaderNodeVectorMath', p_operation='SCALE', Vector=gen)
    vs.inputs['Scale'].default_value = 420.0
    vor = nd(nt, 'ShaderNodeTexVoronoi', Vector=vs.outputs[0], Randomness=1.0)
    star = mth(nt, 'LESS_THAN', vor.outputs['Distance'], 0.11)
    bright = mth(nt, 'POWER', sep(nt, vor.outputs['Color']).outputs['X'], 4.0)
    above = mth(nt, 'GREATER_THAN', z, 0.04)
    s = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', star, bright), mth(nt, 'MULTIPLY', above, value(nt, 'Stars', 0.0)))
    add2 = nd(nt, 'ShaderNodeMix', p_data_type='RGBA', p_blend_type='ADD', Factor=1.0)
    nt.links.new(add.outputs[2], add2.inputs[6])
    nt.links.new(comb(nt, s, s, mth(nt, 'MULTIPLY', s, 1.1)), add2.inputs[7])
    bg = nd(nt, 'ShaderNodeBackground', Color=add2.outputs[2], Strength=1.0)
    nt.links.new(bg.outputs[0], out.inputs['Surface'])
    w.cycles.sampling_method = 'MANUAL'
    w.cycles.sample_map_resolution = 64
    SKY.update(bg=bg, hor=hor, zen=zen, sunvec=sv, glowcol=gcol, glow=nt.nodes['SunGlow'], stars=nt.nodes['Stars'])
    w.mist_settings.start = 20
    w.mist_settings.depth = 1500
    w.mist_settings.falloff = 'QUADRATIC'
    sun = bpy.data.lights.new('Sun', 'SUN')
    sun.angle = math.radians(1.0)
    so = bpy.data.objects.new('Sun', sun)
    so.rotation_mode = 'XYZ'
    coll('Lights').objects.link(so)
    SKY['sun'] = so


