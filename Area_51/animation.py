# ============================================================================
# The desert: a basin of dry valley floor, a white lakebed and ridged mountains (one big graded mesh)
# ============================================================================
LAKE = (2600.0, 3300.0, 1500.0, 2600.0)          # centre x, y and radii of the dry lakebed
BASIN = (1500.0, 2000.0, 1.45)                   # basin centre and N-S stretch
TERRAIN = {}


def basin_r(X, Y):
    return np.hypot(X - BASIN[0], (Y - BASIN[1]) / BASIN[2])


def lake_mask(X, Y):
    e = ((X - LAKE[0]) / LAKE[2]) ** 2 + ((Y - LAKE[1]) / LAKE[3]) ** 2
    return 1.0 - sstep(e, 0.82, 1.0)


def terrain_h(X, Y):
    from mathutils import noise as mn
    X = np.asarray(X, float)
    Y = np.asarray(Y, float)
    r = basin_r(X, Y)
    mask = sstep(r, 4300.0, 7600.0)
    H = np.zeros_like(X)
    idx = np.nonzero(mask.ravel() > 0.0)[0]
    xf, yf = X.ravel()[idx], Y.ravel()[idx]
    rm = np.array([mn.ridged_multi_fractal(Vector((x / 3800.0, y / 3800.0, 0.37)), 0.95, 2.1, 7, 1.0, 2.0, noise_basis='PERLIN_ORIGINAL')
                   for x, y in zip(xf, yf)])
    Hf = H.ravel()
    Hf[idx] = mask.ravel()[idx] * (np.maximum(rm, 0.0) ** 1.7 * 560.0 + 260.0 * mask.ravel()[idx])
    H = Hf.reshape(X.shape)
    und = np.sin(X / 610.0 + 1.3) * np.cos(Y / 830.0) * 5.0 + np.sin((X + Y) / 260.0) * 1.5
    flat = sstep(np.hypot(X - 150.0, Y / 2.6), 900.0, 1600.0)
    H += und * flat
    H += (np.maximum(r - 2500.0, 0.0) / 1000.0) ** 2 * 8.0          # the valley floor rises gently to the hills
    lk = lake_mask(X, Y)
    return H * (1 - lk) + lk * -0.4


def build_terrain():
    u = np.linspace(-1.0, 1.0, 621)
    xs = 32000.0 * np.sinh(4.5 * u) / np.sinh(4.5)
    ob = grid_mesh('Desert', xs + 100.0, xs + 300.0, terrain_h, MAT['desert'], 'Desert', attrs={'lake': lake_mask})
    TERRAIN['ob'] = ob


def ground_z(x, y):
    return float(terrain_h(np.array([x]), np.array([y]))[0])


