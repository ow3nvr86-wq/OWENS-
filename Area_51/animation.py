# ============================================================================
# Aircraft (built from published dimensions; nose along +x, fuselage centreline at z = 0)
#   Lockheed U-2A (1955): length 15.1 m, span 24.4 m; long, straight glider wings; natural-metal finish.
#   Lockheed A-12 OXCART (1962): length 31.3 m, span 16.97 m; chined fuselage, delta wing, two engine
#   nacelles at mid-span with conical inlet spikes, two vertical fins canted inward; titanium, painted black.
# ============================================================================
def loft(bm, rings, cap0=True, cap1=True, mi=0):
    """rings: list of equal-length lists of 3D points; consecutive rings are bridged with quads."""
    vr = [[bm.verts.new(p) for p in r] for r in rings]
    n = len(rings[0])
    faces = []
    for a, b in zip(vr[:-1], vr[1:]):
        for i in range(n):
            j = (i + 1) % n
            faces.append(bm.faces.new((a[i], a[j], b[j], b[i])))
    if cap0:
        faces.append(bm.faces.new(vr[0][::-1]))
    if cap1:
        faces.append(bm.faces.new(vr[-1]))
    for f in faces:
        f.material_index = mi
    return faces


def airfoil(chord_x0, chord_x1, t, n=14):
    """Symmetric section (NACA-like thickness), as (x, z) pairs from the trailing edge over the top and back."""
    c = (1 - np.cos(np.linspace(0, math.pi, n))) / 2
    yt = 5 * t * (0.2969 * np.sqrt(c) - 0.126 * c - 0.3516 * c ** 2 + 0.2843 * c ** 3 - 0.1036 * c ** 4)
    L = chord_x1 - chord_x0
    up = [(chord_x1 - L * ci, yi * L) for ci, yi in zip(c, yt)]            # LE at chord_x1 (front), TE at chord_x0
    lo = [(chord_x1 - L * ci, -yi * L) for ci, yi in zip(c[::-1], yt[::-1])]
    pts = up[::-1] + lo[::-1][1:-1]
    return pts


def wing_rings(stations, le, te, thick, z0, dihedral=0.0, side=1):
    rings = []
    for y in stations:
        a, b = te(y), le(y)
        rel = thick(y) / max(b - a, 0.05)
        pts = airfoil(a, b, rel)
        zc = z0 + y * math.tan(dihedral)
        rings.append([(x, side * y, zc + z) for x, z in pts])
    return rings


def ellipsoid(bm, c, r, mi=0, u=20, v=10):
    add_sphere(bm, 1.0, u, v, matrix=Matrix.Translation(c) @ Matrix.Diagonal((r[0], r[1], r[2], 1)), mi=mi)


def u2_bm(gear=True):
    """Returns (bm, materials): 0 metal, 1 canopy glass, 2 tyres."""
    bm = bmesh.new()
    xs = np.linspace(0.0, 15.1, 40)
    rad = np.interp(xs, [0, 0.6, 3.0, 7.0, 9.5, 12.0, 13.6, 14.6, 15.1], [0.22, 0.32, 0.55, 0.72, 0.75, 0.62, 0.45, 0.22, 0.02])
    rings = []
    for x, r in zip(xs, rad):
        rings.append([(x, 0.92 * r * math.cos(a), r * math.sin(a) + 0.08 * r * (1 if math.sin(a) > 0 else 0))
                      for a in np.linspace(0, 2 * math.pi, 22, endpoint=False)])
    loft(bm, rings)
    ellipsoid(bm, (12.25, 0, 0.52), (0.95, 0.36, 0.34), mi=1)
    for s in (-1, 1):
        ellipsoid(bm, (10.3, s * 0.66, 0.05), (1.1, 0.26, 0.34))
        # wings: span 24.4 m, root chord about 3.2 m, tip about 1.3 m, small sweep of the leading edge
        st = np.linspace(0.3, 12.2, 16)
        rings = wing_rings(st, lambda y: 9.6 - 1.3 * (y / 12.2), lambda y: 6.4 + 0.6 * (y / 12.2), lambda y: 0.36 - 0.26 * (y / 12.2), 0.05,
                           math.radians(0.5), side=s)
        loft(bm, rings if s > 0 else [r[::-1] for r in rings])
        add_box(bm, 7.4, s * 12.05 - 0.05, -0.25, 8.4, s * 12.05 + 0.05, 0.02)                    # wingtip skid
        # horizontal tail
        st = np.linspace(0.2, 3.6, 6)
        rings = wing_rings(st, lambda y: 2.0 - 0.6 * (y / 3.6), lambda y: 0.5 + 0.1 * (y / 3.6), lambda y: 0.12 - 0.06 * (y / 3.6), 0.12, side=s)
        loft(bm, rings if s > 0 else [r[::-1] for r in rings])
    # vertical fin (sections in x-y, stacked up z)
    rings = []
    for z in np.linspace(0.3, 2.9, 7):
        u = (z - 0.3) / 2.6
        a, b = 0.0 + 0.1 * u, 2.7 - 1.7 * u
        pts = airfoil(a, b, (0.14 - 0.08 * u) / (b - a))
        rings.append([(x, yv, z) for x, yv in pts])
    loft(bm, rings)
    if gear:
        for x, rr in ((9.0, 0.38), (8.2, 0.38), (1.6, 0.18)):
            add_cyl(bm, rr, rr, 0.2, seg=16, matrix=Matrix.Translation((x, 0, -1.3 + rr)) @ Matrix.Rotation(math.pi / 2, 4, 'X'), mi=2)
            add_box(bm, x - 0.05, -0.05, -1.3 + rr, x + 0.05, 0.05, -0.4)
        for s in (-1, 1):                                                                          # 'pogo' outriggers
            add_cyl(bm, 0.035, 0.035, 1.3, seg=6, matrix=Matrix.Translation((7.6, s * 6.3, -0.62)))
            add_cyl(bm, 0.14, 0.14, 0.08, seg=12, matrix=Matrix.Translation((7.6, s * 6.3, -1.16)) @ Matrix.Rotation(math.pi / 2, 4, 'X'), mi=2)
    return bm, [MAT['u2metal'], MAT['canopy'], MAT['tyre']]


def a12_bm(gear=True):
    """Returns (bm, materials): 0 black titanium, 1 canopy, 2 spikes, 3 nozzles, 4 tyres."""
    bm = bmesh.new()
    xs = np.linspace(0.0, 31.3, 64)
    rad = np.interp(xs, [0, 1.5, 6, 14, 20, 24, 27, 29.5, 31.3], [0.45, 0.6, 0.85, 0.88, 0.85, 0.75, 0.55, 0.32, 0.02])
    chW = np.interp(xs, [0, 18.0, 19.0, 22.0, 26.0, 29.2, 31.3], [0, 0, 2.3, 1.75, 1.2, 0.35, 0.02])
    rings = []
    for x, r, W in zip(xs, rad, chW):
        W = max(W, r)
        f = 0.13 if W > r * 1.05 else 0.0
        ring = []
        for th in np.linspace(0, 2 * math.pi, 36, endpoint=False):
            y = W * math.cos(th)
            core = r * math.sqrt(max(0.0, 1 - (y / r) ** 2)) if abs(y) < r else 0.0
            fl = f * (1 - abs(y) / W)
            z = (core + fl) if math.sin(th) >= 0 else -(0.78 * core + 0.6 * fl)
            ring.append((x, y, z))
        rings.append(ring)
    loft(bm, rings)
    ellipsoid(bm, (25.3, 0, 0.6), (1.9, 0.45, 0.42), mi=1)
    for s in (-1, 1):
        st = np.linspace(1.0, 8.48, 18)
        rings = wing_rings(st, lambda y: float(np.interp(y, [1.0, 2.3, 4.7, 8.48], [22.0, 19.0, 15.2, 6.8])),
                           lambda y: 1.0 + 2.4 * (y - 1.0) / 7.48, lambda y: 0.32 - 0.25 * (y - 1.0) / 7.48, -0.05, side=s)
        loft(bm, rings if s > 0 else [r[::-1] for r in rings])
        # nacelle with inlet spike and nozzle
        yc = s * 4.7
