    oh = sum(np.sin(2 * np.pi * f * tt) for f in (220.0, 223.1, 330.0, 333.7, 661.0)) * np.minimum(tt / 0.8, 1) * np.minimum((tt[-1] - tt) / 0.3, 1)
    _place(sfx, oh / 5, t_orb, 0.07)
