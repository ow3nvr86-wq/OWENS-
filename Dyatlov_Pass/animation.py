def hiker_path(i, t):
    p = HIKERS[i]
    d = HIKER_DIR
    perp = Vector((-d.y, d.x, 0))
    s = HIKER_SPEED * t - i * HIKER_GAP
    pos = HIKER_START + d * s + perp * (p['lat'] + 0.4 * math.sin(s * 0.08 + i))
    return pos


def update_hikers(t):
    for i, p in enumerate(HIKERS):
        pos = hiker_path(i, t)
        z = float(height(pos.x, pos.y, platform=False))
        ahead = hiker_path(i, t + 0.6)
        dvec = (ahead - pos)
        dvec.z = 0
        dvec.normalize()
        za = float(height(pos.x + dvec.x * 0.6, pos.y + dvec.y * 0.6, platform=False))
        zb = float(height(pos.x - dvec.x * 0.6, pos.y - dvec.y * 0.6, platform=False))
        pitch = math.atan2(za - zb, 1.2)
        yaw = math.atan2(dvec.y, dvec.x) - math.pi / 2
        root = p['root']
        root.rotation_euler = (0, 0, yaw)
        ph = 2 * math.pi * t / p['period'] + p['phase']
        legs = {}
        for side, sgn in (('L', 1), ('R', -1)):
            s = math.sin(ph if sgn > 0 else ph + math.pi)
            c = math.cos(ph if sgn > 0 else ph + math.pi)
            a1 = 0.30 * s + 0.12
            a2 = -0.18 - 0.32 * max(0.0, -c)
            p['thigh' + side].rotation_euler = (a1, 0, 0)
            p['shin' + side].rotation_euler = (a2, 0, 0)
            p['boot' + side].rotation_euler = (-(a1 + a2) + pitch, 0, 0)
            fy = THIGH * math.sin(a1) + SHIN * math.sin(a1 + a2)
            fz = -THIGH * math.cos(a1) - SHIN * math.cos(a1 + a2)
            legs[side] = (sgn * 0.1, fy, fz)
            p['arm' + side].rotation_euler = (-0.55 * s + 0.25, 0, sgn * 0.08)
            p['fore' + side].rotation_euler = (0.45 + 0.25 * max(0.0, s), 0, 0)
            p['pole' + side].rotation_euler = (-0.75 - 0.35 * s, 0, 0)
        tanp = math.tan(pitch)
        # hip height so that the lower ski rests on the (sloping) ground
        hip = max(-(fz - 0.09 - tanp * fy) for (_, fy, fz) in legs.values())
        lean = -0.3 - 0.5 * pitch
        p['hips'].location = (0, 0, hip)
        p['hips'].rotation_euler = (0, 0, 0.06 * math.sin(ph))
        p['torso'].rotation_euler = (lean, 0.04 * math.sin(ph), 0)
        p['head'].rotation_euler = (-lean * 0.6 + 0.1, 0, 0.05 * math.sin(ph * 0.5 + i))
        root.location = (pos.x, pos.y, z)
        for side in ('L', 'R'):
            fx, fy, fz = legs[side]
            ski = p['ski' + side]
            ski.location = (fx, fy, hip + fz - 0.09)
            ski.rotation_euler = (pitch, 0, 0)


