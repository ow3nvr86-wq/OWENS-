def octa_verts(c, axis, length, width):
    """Elongated octahedra: centres c (N,3), unit streak axis (N,3), half-length, half-width (N,)."""
    a = axis
    ref = np.where(np.abs(a[:, 2:3]) < 0.9, np.array([[0, 0, 1.0]]), np.array([[1.0, 0, 0]]))
    e1 = np.cross(a, ref)
    e1 /= np.linalg.norm(e1, axis=1, keepdims=True) + 1e-9
    e2 = np.cross(a, e1)
    L = length[:, None]
    W = width[:, None]
    v = np.stack([c + a * L, c - a * L, c + e1 * W, c - e1 * W, c + e2 * W, c - e2 * W], 1)
    return v


def update_snow(t, shot, campos):
    cfg = SNOWCFG.get(shot['name'])
    ob = FLK['obj']
    verts = np.zeros((NFLAKE, 6, 3))
    if cfg is not None:
        n = cfg['n']
        wind = np.array(cfg['wind'], float)
        base, ph, fq = FLK['base'][:n], FLK['phase'][:n], FLK['freq'][:n]
        turb = cfg['turb'] * np.sin(fq * t * 2.0 + ph)
        dturb = cfg['turb'] * 2.0 * fq * np.cos(fq * t * 2.0 + ph)
        fall = np.zeros((n, 3))
        fall[:, 2] = -1.1 * FLK['fall'][:n]
        vel = wind[None, :] + fall + dturb
        if cfg.get('salt'):
            # wind-blown snow skimming down the slope of the cut-away set
            span = 12.0
            x = DRIFT_X0 - 4.0 + np.mod(base[:, 0] * span + wind[0] * t * FLK['fall'][:n] + turb[:, 0], span)
            y = FRONT_Y + 0.05 + base[:, 1] * 9.0 + turb[:, 1] * 0.3
            hgt = 0.02 + 0.9 * base[:, 2] ** 2.5 + 0.06 * turb[:, 2]
            z = surface4(x, 1.0) + drift_thickness(x, ramp(t, *EV['wind_load'])) + hgt
            c = np.stack([x, y, z], -1) + np.array(SET0)
            vel = np.stack([np.full(n, wind[0]), np.zeros(n), np.full(n, -wind[0] * GRAD)], -1) * FLK['fall'][:n, None]
        else:
            box = np.array(cfg['box'], float)
            cam = np.array(campos['loc'])
            fwd = np.array(campos['fwd'])
            centre = cam + fwd * cfg['ahead']
            lo = centre - box / 2
            c = lo + np.mod(base * box + (wind[None, :] + fall) * t + turb - lo, box)
        speed = np.linalg.norm(vel, axis=1) + 1e-6
        axis = vel / speed[:, None]
        size = cfg['size'] * FLK['size'][:n]
        L = size + speed / 60.0 * 0.5
        W = size * 0.35
        if not cfg.get('salt'):
            dcam = np.linalg.norm(c - np.array(campos['loc']), axis=1)
            k = np.clip((dcam - 45 * cfg['size']) / (70 * cfg['size']), 0, 1)
            L, W = L * k, W * k
        verts[:n] = octa_verts(c, axis, L, W)
    ob.data.vertices.foreach_set('co', verts.astype(np.float32).ravel())
    ob.data.update()


def update_powder(t):
    ob = FLK['pobj']
    verts = np.zeros((NPOWDER, 6, 3))
    pw = SET.get('powder')
    if pw is not None and len(pw) and SHOT['release']['t0'] <= t <= SHOT['release']['t1'] + 1:
        pw = pw[:NPOWDER]
        tb = pw[:, 0]
        age = t - tb
        alive = (age > 0) & (age < pw[:, 8])
        p0, v0 = pw[:, 1:4], pw[:, 4:7]
        vinf = np.array([1.4, 0.0, -0.35])
        kd = 2.2
        a = np.maximum(age, 0)[:, None]
        pos = p0 + vinf * a + (v0 - vinf) * (1 - np.exp(-kd * a)) / kd
        size = pw[:, 7] * (1 + 0.8 * a[:, 0]) * (1 - np.clip((age - pw[:, 8] * 0.6) / (pw[:, 8] * 0.4), 0, 1)) * alive
        c = pos + np.array(SET0)
        axis = np.tile(np.array([[0, 0, 1.0]]), (len(pw), 1))
        verts[:len(pw)] = octa_verts(c, axis, size, size * 0.8)
    ob.data.vertices.foreach_set('co', verts.astype(np.float32).ravel())
    ob.data.update()


