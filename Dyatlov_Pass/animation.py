PLATFORM = dict(x0=-1.15, x1=1.35, y0=-2.9, y1=2.9)


def _raw_height(x, y):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    dome = 300.0 * np.exp(-((x + 700.0) ** 2 + 0.55 * (y - 150.0) ** 2) / 760.0 ** 2)
    ridge = 110.0 * np.exp(-((x + 720.0 + 120 * np.sin(y / 900.0)) / 420.0) ** 2) * (0.65 + 0.35 * np.cos(y / 1700.0))
    valley = -230.0 * np.exp(-((x - 1550.0 - 200 * np.sin(y / 1300.0)) / 750.0) ** 2)
    tilt = -0.07 * np.clip(x, -3000, 3000)
    d = np.sqrt((x - 900.0) ** 2 + (y * 0.8) ** 2)
    ranges = 520.0 * ridged(x / 3200.0 + 3.1, y / 3200.0 + 7.3, 5, seed=11) * np.clip((d - 2200.0) / 2600.0, 0, 1) ** 1.3
    far = 700.0 * np.clip((d - 9000.0) / 9000.0, 0, 1) * (0.5 + 0.5 * fbm(x / 7000.0, y / 7000.0, 3, seed=5))
    roll = 38.0 * fbm(x / 520.0, y / 520.0, 4, seed=3)
    near = np.exp(-(x * x + y * y) / 40.0 ** 2)
    small = (1.0 - 0.85 * near) * (3.0 * fbm(x / 55.0, y / 55.0, 3, seed=9) + 0.35 * fbm(x / 7.0, y / 7.0, 2, seed=21))
    return dome + ridge + valley + tilt + ranges + far + roll + small


_H0 = float(_raw_height(0.0, 0.0))


def height(x, y, platform=True):
    """Terrain height (m) relative to the tent platform; vectorised."""
    z = _raw_height(x, y) - _H0
    if platform:
        x = np.asarray(x, float)
        y = np.asarray(y, float)
        P = PLATFORM
        # the hikers dug a flat platform into the slope: a level floor with a steep uphill wall
        floor = float(_raw_height(P['x1'], 0.0) - _H0) + 0.05
        inside_y = np.clip(1 - (np.abs(y) - (P['y1'] - 0.3)) / 0.6, 0, 1)
        wall = floor + np.maximum(0, (P['x0'] - x)) * 2.4
        cut = np.minimum(z, np.maximum(floor, wall))
        tx = np.clip(1 - (x - P['x1']) / 0.8, 0, 1)
        w = inside_y * tx * (x > P['x0'] - 2.0)
        z = z + (cut - z) * w
    return z


def terrain_normal(x, y, e=0.5):
    hx = (height(x + e, y) - height(x - e, y)) / (2 * e)
    hy = (height(x, y + e) - height(x, y - e)) / (2 * e)
    n = np.stack([-hx, -hy, np.ones_like(hx)], -1)
    return n / np.linalg.norm(n, axis=-1, keepdims=True)


