def build_footprints():
    """Nine lines of sock / bare-foot prints leading from the tent down the slope (illustrative)."""
    rng = np.random.default_rng(12)
    verts, faces = [], []
    ring = 12
    ang = np.linspace(0, 2 * np.pi, ring, endpoint=False)

    def shape(a, sx, sy):
        # foot outline: wider at the toes (+u)
        w = 1.0 + 0.25 * np.cos(a)
        return np.cos(a) * sx, np.sin(a) * sy * w
    TRACKS = []
    for k in range(9):
        y0 = -1.9 + 0.48 * k + rng.uniform(-0.1, 0.1)
        x0 = 1.6 + rng.uniform(0, 0.8)
        TRACKS.append((x0, y0, rng.uniform(-0.04, 0.04), rng.uniform(0, 6)))
    for (x0, y0, drift, ph) in TRACKS:
        n_steps = 240
        for s in range(n_steps):
            u = x0 + s * 0.62 + rng.uniform(-0.05, 0.05)
            side = 1 if s % 2 else -1
            y = y0 + drift * s * 0.62 + 0.25 * math.sin(s * 0.05 + ph) + side * 0.11
            yaw = math.atan2(drift + 0.25 * 0.05 * math.cos(s * 0.05 + ph), 1.0) + rng.uniform(-0.12, 0.12)
            ca, sa = math.cos(yaw), math.sin(yaw)
            fill = rng.uniform(0.35, 1.0) * (1.0 - 0.6 * min(s / n_steps, 1.0))   # older prints drift in
            rim_h = 0.022 * fill
            base = len(verts)
            layers = ((1.32, 1.45, -0.01), (1.0, 1.0, rim_h), (0.72, 0.62, 0.004), (0.0, 0.0, 0.0))
            for li, (sx, sy, dz) in enumerate(layers[:3]):
                lx, ly = shape(ang, 0.135 * sx, 0.052 * sy)
                wx = u + lx * ca - ly * sa
                wy = y + lx * sa + ly * ca
                wz = height(wx, wy) + dz
                verts.extend(np.stack([wx, wy, wz], -1).tolist())
            verts.append([u, y, float(height(u, y)) + 0.003])
            c = len(verts) - 1
            for li in range(2):
                for j in range(ring):
                    a0 = base + li * ring + j
                    a1 = base + li * ring + (j + 1) % ring
                    faces.append((a0, a1, a1 + ring, a0 + ring))
            for j in range(ring):
                faces.append((base + 2 * ring + j, base + 2 * ring + (j + 1) % ring, c))
    ob = mesh_obj('Footprints', verts, faces, MAT['snow_smooth'], collection='Camp')
    CAMP['tracks'] = TRACKS
    return ob


