def update_set4(t, sim=None, fi=None):
    cutf, load, pitch = set_state(t)
    nx, ny = len(X4), len(Y4)
    X, Y = np.meshgrid(X4, Y4, indexing='ij')
    in_cut = (np.abs(Y - TENT4['y']) < 2.9).astype(float)
    Z = s0(X) - cutf * (s0(X) - s_cut(X)) * in_cut
    Z += 0.015 * perlin(X * 1.7, Y * 1.7, 81) * (X < -0.4)
    me = SET['top'].data
    me.vertices.foreach_set('co', np.stack([X, Y, Z], -1).astype(np.float32).ravel())
    me.update()
    surf = surface4(X4, cutf)
    rz = rock_z(X4)
    k = np.linspace(0, 1, FACE_ROWS)
    FZ = rz[:, None] + (surf - rz)[:, None] * k[None, :] ** 0.8
    fv = np.stack([np.repeat(X4, FACE_ROWS), np.full(nx * FACE_ROWS, FRONT_Y), FZ.ravel()], -1)
    me = SET['face'].data
    me.vertices.foreach_set('co', fv.astype(np.float32).ravel())
    me.attributes['depth'].data.foreach_set('value', (surf[:, None] - FZ).ravel().astype(np.float32))
    me.update()
    # drift on top of the cut surface
    dx = SET['dx']
    base = surface4(dx, cutf)
    th = drift_thickness(dx, load)
    for nm in ('DriftSlab', 'DriftRest'):
        ys = SET[nm + '_ys']
        DX, DY = np.meshgrid(dx, ys, indexing='ij')
        edge = np.clip((DY - FRONT_Y) / 0.05, 0, 1) if nm == 'DriftSlab' else np.ones_like(DY)
        wob = 1 + 0.08 * perlin(DX * 1.3, DY * 1.3, 83)
        DZ = base[:, None] + (th[:, None] * wob + 0.004) * np.maximum(edge, 0.999)
        me = SET[nm].data
        me.vertices.foreach_set('co', np.stack([DX, DY, DZ], -1).astype(np.float32).ravel())
        me.update()
    k5 = np.linspace(0, 1, 5)
    for key_, yv in (('dface', FRONT_Y), ('dside', SLAB_Y1)):
        wob = 1 + 0.08 * perlin(dx * 1.3, np.full_like(dx, yv) * 1.3, 83)
        FZ2 = base[:, None] + (th * wob + 0.004)[:, None] * k5[None, :]
        me = SET[key_].data
        me.vertices.foreach_set('co', np.stack([np.repeat(dx, 5), np.full(len(dx) * 5, yv - 0.002), FZ2.ravel()], -1).astype(np.float32).ravel())
        me.attributes['depth'].data.foreach_set('value', ((th * wob)[:, None] * (1 - k5[None, :])).ravel().astype(np.float32))
        me.update()
    # spoil heap grows while digging
    h = SET['heap']
    h.location = SET0 + Vector((3.3, TENT4['y'] + 0.2, float(s0(3.3)) - 0.15))
    h.scale = (1.3 * cutf + 0.001, 2.4 * cutf + 0.001, 0.38 * cutf + 0.001)
    h.rotation_euler = (0, SLOPE, 0)
    # tent: pitched, then crushed by the slab (ridge heights from the simulation)
    ridge = np.full(TENT_NU + 1, TENT_H * pitch)
    lean = 0.0
    if sim is not None and fi is not None:
        m = sim['tent_m'][fi]
        u = np.linspace(0, 1, TENT_NU + 1)
        segs = np.interp(u, np.linspace(0, 1, len(m)), m)
        ridge = TENT_H * segs
        lean = 1 - segs.mean()
    tv = tent_surface(np.maximum(ridge, 0.02), sag=0.06 + 0.25 * lean, wrinkle=0.02 + 0.05 * lean, seed=4)
    # a crushed tent leans downslope (pushed by the slab from the uphill side)
    tv[..., 0] += lean * 0.35 * tv[..., 2] / TENT_H
    tv = np.concatenate([tv.reshape(-1, 3), np.array([[0, -TENT_L / 2, 0.0], [0, TENT_L / 2, 0.0]])])
    me = SET['tent'].data
    me.vertices.foreach_set('co', tv.astype(np.float32).ravel())
    me.update()
    SET['tpoles'].scale = (1, 1, max(pitch * (1 - 0.7 * lean), 0.001))


