def slab_blocks():
    xs = np.arange(DRIFT_X0 + 0.25, DRIFT_X1, 0.5)
    ys = np.arange(FRONT_Y + 0.25, SLAB_Y1, 0.5)
    B = []
    for x in xs:
        h = float(drift_thickness(x, 1.0))
        if h < 0.1:
            continue
        for y in ys:
            B.append((x, y, h))
    return np.array(B)


def run_slab_sim():
    path = os.path.join(BUILD, 'slab_sim.npz')
    t_rel = EV['slab_release']
    t_end = SHOT['release']['t1'] + 0.6
    key = np.array([t_rel, t_end, DRIFT_X0, DRIFT_X1, SLOPE, 3.0])
    if os.path.exists(path):
        d = np.load(path)
        if np.allclose(d['key'], key):
            return {k: d[k] for k in d.files}
    rng = np.random.default_rng(3)
    B = slab_blocks()
    N = len(B)
    h = B[:, 2]
    pos = np.stack([B[:, 0], B[:, 1], s_cut(B[:, 0]) + h / 2], -1)
    vel = np.zeros_like(pos)
    mass = 0.5 * 0.5 * h * 380.0
    # bonds to the 8 neighbours
    d0 = np.linalg.norm(pos[:, None, :2] - pos[None, :, :2], axis=-1)
    bond = (d0 < 0.75) & (d0 > 0)
    L0 = d0.copy()
    strength = rng.uniform(0.025, 0.07, (N, N))
    strength = np.minimum(strength, strength.T)
    k_g, c_g = 2.5e5, 900.0
    k_b, c_b = 1.2e5, 300.0
    k_t = 2.0e4
    mu_slab, mu_floor = 0.14, 0.45
    tent_m = np.ones(4)
    tm_hist = []
    pitch = np.full(N, SLOPE)
    omega = np.zeros(N)
    yaw = np.zeros(N)
    yaw_rate = rng.normal(0, 1.2, N)
    dt = 4e-4
    nsteps = int((t_end - t_rel) / dt)
    out_every = int(round(1 / FPS / dt))
    P, PI, YW, TM = [], [], [], []
    impact_t, first_tent = None, None
    powder = []
    tx0, tx1 = TENT4['x'] - TENT_W / 2, TENT4['x'] + TENT_W / 2
    ty0, ty1 = TENT4['y'] - TENT_L / 2, TENT4['y'] + TENT_L / 2
    for step in range(nsteps + 1):
        t = t_rel + step * dt
        if step % out_every == 0:
            P.append(pos.copy())
            PI.append(pitch.copy())
            YW.append(yaw.copy())
            TM.append(tent_m.copy())
        F = np.zeros_like(pos)
        F[:, 2] -= mass * 9.81
        # ground
        g = s_cut(pos[:, 0])
        gs = s_cut_slope(pos[:, 0])
        inv = 1 / np.sqrt(1 + gs * gs)
        n = np.stack([-gs * inv, np.zeros(N), inv], -1)
        dist = (pos[:, 2] - g) * inv - h / 2
        pen = np.maximum(-dist, 0)
        vn = np.einsum('ij,ij->i', vel, n)
        fn = np.where(pen > 0, k_g * pen - c_g * vn, 0)
        fn = np.maximum(fn, 0)
        vt = vel - vn[:, None] * n
        vts = np.linalg.norm(vt, axis=1) + 1e-9
        mu = np.where(pos[:, 0] < -0.05, mu_slab, mu_floor)
        F += fn[:, None] * n - (mu * fn / np.maximum(vts, 0.05))[:, None] * vt
        grounded = pen > 0
        # tent roof (soft)
        intent = (pos[:, 0] > tx0) & (pos[:, 0] < tx1) & (pos[:, 1] > ty0) & (pos[:, 1] < ty1)
        seg = np.clip(((pos[:, 1] - ty0) / TENT_L * 4).astype(int), 0, 3)
        ax = np.abs(pos[:, 0] - TENT4['x']) / (TENT_W / 2)
        roof = FLOOR_Z + TENT_H * tent_m[seg] * (1 - ax)
        tp = np.where(intent, roof - (pos[:, 2] - h / 2), 0)
        tp = np.maximum(tp, 0)
        ft = k_t * tp - 200 * np.minimum(vel[:, 2], 0) * (tp > 0)
        ft = np.maximum(ft, 0)
        F[:, 2] += ft
        F[:, 0] -= 0.3 * ft * np.sign(TENT4['x'] - pos[:, 0])
        load = np.zeros(4)
        np.add.at(load, seg, ft)
        if first_tent is None and ft.max() > 0:
            first_tent = t
        target = np.clip(1 - load / 1100.0, 0.18, 1.0)
        tent_m = np.minimum(tent_m, tent_m + (target - tent_m) * min(1.0, 8 * dt))
        # bonds and block-block contact
        dvec = pos[None, :, :] - pos[:, None, :]
        dd = np.linalg.norm(dvec, axis=-1) + 1e-9
        u = dvec / dd[..., None]
        strain = (dd - L0) / np.maximum(L0, 1e-6)
        broken = bond & (np.abs(strain) > strength)
        bond &= ~broken
        dv = vel[None, :, :] - vel[:, None, :]
        rel = np.einsum('ijk,ijk->ij', dv, u)
        fb = np.where(bond, k_b * (dd - L0) + c_b * rel, 0)
        overlap = np.maximum(0.46 - dd, 0) * (~bond) * (dd < 0.46)
        np.fill_diagonal(overlap, 0)
        fc = -k_g * 0.6 * overlap
        F += np.einsum('ij,ijk->ik', fb + fc, u)
        vel += F / mass[:, None] * dt
        vel[:, 1] *= (1 - 2.0 * dt)
        pos += vel * dt
        # orientation for rendering
        target_p = np.arctan(-gs)
        speed = np.linalg.norm(vel, axis=1)
        nb = bond.sum(1)
        omega = np.where(grounded, omega * (1 - min(1, 10 * dt)), np.where(omega == 0, vel[:, 0] * 1.4, omega))
        pitch = np.where(grounded, pitch + (target_p - pitch) * min(1, 9 * dt), pitch + omega * dt)
        yaw += yaw_rate * speed * dt * (nb < 3) * 0.6
        if impact_t is None and (pos[:, 2] < FLOOR_Z + 1.2).any() and (pos[:, 0] > 0).any():
            impact_t = t
        # snow dust thrown up by fast blocks hitting things
        if step % 25 == 0:
            hot = np.nonzero((speed > 1.3) & (grounded | (tp > 0)))[0]
            for i in hot[:10]:
                for _ in range(8):
                    powder.append([t, *pos[i] + rng.normal(0, 0.15, 3),
                                   *(vel[i] * rng.uniform(0.2, 0.6) + np.array([rng.normal(0, 0.6), rng.normal(0, 0.6), rng.uniform(0.3, 1.6)])),
                                   rng.uniform(0.003, 0.009), rng.uniform(1.6, 3.0)])
    res = dict(key=key, pos=np.array(P, np.float32), pitch=np.array(PI, np.float32), yaw=np.array(YW, np.float32),
               tent_m=np.array(TM, np.float32), h=h.astype(np.float32),
               impact=np.array([impact_t or t_rel + 0.8, first_tent or t_rel + 0.9]),
               powder=np.array(powder if powder else np.zeros((0, 9)), np.float32), t_rel=np.array([t_rel]))
    os.makedirs(BUILD, exist_ok=True)
    np.savez(path, **res)
    print(f'slab sim: {N} blocks, {nsteps} steps, impact {res["impact"]}, powder {len(powder)}')
    return res


def block_mesh(name, h, seed):
    rng = np.random.default_rng(seed)
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    bmesh.ops.subdivide_edges(bm, edges=bm.edges[:], cuts=2, use_grid_fill=True)
    for v in bm.verts:
        p = v.co
        jitter = 0.035 * perlin(p.x * 5 + seed, p.y * 5 + p.z * 3, 85)
        v.co = Vector((p.x * (0.49 + jitter), p.y * (0.49 + jitter), p.z * (h - 0.01) + jitter * 0.5))
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(MAT['drift_face'])
    for p in me.polygons:
        p.use_smooth = False
    return me


