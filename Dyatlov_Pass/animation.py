    t = np.arange(N) / SR
    music = np.zeros((2, N))
    amb = np.zeros((2, N))
    sfx = np.zeros((2, N))
    cues = []

    def cue(time, what, layer):
        cues.append((time, what, layer))

    # --- wind bed (stereo, gusty), level follows the scenes ---------------------------------
    gust = 0.6 + 0.25 * np.sin(2 * np.pi * t / 7.3) + 0.15 * np.sin(2 * np.pi * t / 3.1 + 1) + \
        0.2 * np.interp(t, np.arange(0, 61, 1.5), np.random.default_rng(4).random(len(np.arange(0, 61, 1.5))))
    lvl = _env(t, [(0, 0.0), (0.3, 0.9), (5.9, 1.0), (6.0, 0.7), (16.8, 0.8), (17.0, 0.04), (22.3, 0.04),
                   (22.5, 0.45), (28.8, 0.5), (29.0, 0.35), (38.3, 0.3), (41.4, 0.75), (41.7, 0.15),
                   (43.8, 0.35), (44.0, 0.55), (50.3, 0.6), (51.5, 0.9), (53.0, 0.2), (57.0, 0.1), (60.0, 0.0)])
    for ch in range(2):
        w = _bandpass(_noise(N, 10 + ch, 'pink'), 90, 1800)
        amb[ch] += w / (np.abs(w).max() + 1e-9) * gust * lvl * 0.55
        howl = _sweep_bp(_noise(N, 20 + ch), lambda tt, ch=ch: 520 + 180 * math.sin(tt * 0.45 + ch) + 120 * math.sin(tt * 1.3), q=18)
        amb[ch] += howl / (np.abs(howl).max() + 1e-9) * gust * lvl * 0.16
    cue(0.0, 'Wind bed with gusts and a whistling howl (stereo), ducks out for the desk scene', 'ambience')

    # --- score: D-minor drones, pulse, music-box motif, hits, risers ----------------------------
    D2, F2, A2, D3 = 73.42, 87.31, 110.0, 146.83
    pad = _pad([D2, A2, D3, F2 * 2], DURATION, seed=1, cutoff=700)
    padenv = _env(t, [(0, 0.0), (1.5, 0.5), (16.5, 0.6), (17.0, 0.35), (28.5, 0.7), (29.0, 0.45),
                      (41.6, 0.8), (41.75, 0.0), (42.2, 0.0), (43.0, 0.55), (51.0, 0.6), (53.0, 0.8), (58.5, 0.6), (60, 0.0)])
    music[0] += pad * padenv * 0.32
    music[1] += np.roll(pad, 240) * padenv * 0.32
    high = _pad([D3 * 4, A2 * 6], DURATION, seed=2, cutoff=4000)
    henv = _env(t, [(0, 0), (22.4, 0), (24.0, 0.25), (29.0, 0.0), (38.4, 0.0), (41.6, 0.35), (41.75, 0.0), (53.4, 0.0), (56, 0.2), (60, 0)])
