TENT_NU, TENT_NV = 44, 26


def tent_surface(ridge, sag=0.06, wrinkle=0.025, seed=0):
    """Vertices (NU+1 x NV+1 x 3) of the ridge-tent roof in local space: x across, y along the ridge.
    ridge: array (NU+1,) of ridge heights along the tent."""
    u = np.linspace(-TENT_L / 2, TENT_L / 2, TENT_NU + 1)
    v = np.linspace(-TENT_W / 2, TENT_W / 2, TENT_NV + 1)
    U, V = np.meshgrid(u, v, indexing='ij')
    a = np.abs(V) / (TENT_W / 2)
    h = ridge[:, None]
    z = h * (1 - a) - sag * h * 4 * a * (1 - a)
    z += wrinkle * perlin(U * 3.1 + seed, V * 4.3, 61) * np.sin(np.pi * a) * (h / TENT_H + 0.3)
    return np.stack([V, U, np.maximum(z, 0.0)], -1)


def tent_faces():
    f = []
    W = TENT_NV + 1
    for i in range(TENT_NU):
        for j in range(TENT_NV):
            f.append((i * W + j, (i + 1) * W + j, (i + 1) * W + j + 1, i * W + j + 1))
    base = (TENT_NU + 1) * W
    # gable ends: fan from a centre point on the floor
    for end, row in ((0, 0), (1, TENT_NU)):
        c = base + end
        for j in range(TENT_NV):
            a, b = row * W + j, row * W + j + 1
            f.append((c, b, a) if end == 0 else (c, a, b))
    return f


def tent_verts(ridge, **kw):
    s = tent_surface(ridge, **kw).reshape(-1, 3)
    ends = np.array([[0, -TENT_L / 2, 0.0], [0, TENT_L / 2, 0.0]])
    return np.concatenate([s, ends])


def discovered_ridge():
    """Ridge line of the tent as found: one end still standing, the other half collapsed."""
    u = np.linspace(0, 1, TENT_NU + 1)
    return TENT_H * (0.95 - 0.62 * smoothstep_np(u, 0.35, 0.9)) * (1 - 0.06 * np.sin(u * 9))


def smoothstep_np(x, a, b):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


CAMP = {}


def build_camp():
    """The tent as the searchers found it: half-collapsed, under snow, cut open, gear around it."""
    tx = 0.1
    z0 = float(height(tx, 0.0))
    CAMP['origin'] = Vector((tx, 0.0, z0))
    ridge = discovered_ridge()
    tv = tent_verts(ridge, sag=0.1, wrinkle=0.04, seed=3)
    tent = mesh_obj('TentFound', tv, tent_faces(), MAT['tent'], collection='Camp', loc=CAMP['origin'])
    # snow load on the roof: thick on the uphill side (x<0) and on the collapsed end
    s = tent_surface(ridge, sag=0.1, wrinkle=0.04, seed=3)
    U, V = s[..., 1], s[..., 0]
    a = V / (TENT_W / 2)
    thick = 0.05 + 0.22 * np.clip(-a, 0, 1) + 0.12 * smoothstep_np(U / TENT_L + 0.5, 0.4, 0.95)
    thick += 0.05 * perlin(U * 2 + 1, V * 2, 71)
    thick *= np.clip(1.0 - 2.4 * np.clip(a + 0.05, 0, 1), 0.04, 1)   # the cut (downslope) side is mostly bare
    sv = s.copy()
    sv[..., 2] += np.maximum(thick, 0.0) - 0.025      # thin snow sinks below the canvas -> bare fabric shows
    # extend the drift beyond the uphill edge down to the platform
    ext = sv[:, :1, :].copy()
    drift = []
    for k, w in enumerate((0.25, 0.55, 0.9)):
        e = ext.copy()
        e[..., 0] -= w
        e[..., 2] = e[..., 2] * (1 - (k + 1) / 3.2)
        drift.append(e)
    grid = np.concatenate(drift[::-1] + [sv], axis=1)
    nu, nv = grid.shape[0], grid.shape[1]
    faces = [(i * nv + j, (i + 1) * nv + j, (i + 1) * nv + j + 1, i * nv + j + 1)
             for i in range(nu - 1) for j in range(nv - 1)]
    mesh_obj('TentSnow', grid.reshape(-1, 3), faces, MAT['snow_smooth'], collection='Camp', loc=CAMP['origin'])
    # long cuts in the downslope wall (x > 0): dark, lens-shaped openings in the canvas
    bm = bmesh.new()
    for (uc, a0, a1, skew) in ((-1.05, 0.12, 0.78, 0.16), (-0.35, 0.10, 0.85, -0.08), (0.45, 0.16, 0.7, 0.1)):
        ring = []
        n = 12
        for side in (1, -1):
            for k in range(n + 1):
                t = k / n if side == 1 else 1 - k / n
                aa = a0 + (a1 - a0) * t
                uu = uc + skew * t
                w = 0.05 * math.sin(math.pi * t) ** 0.7 * side
                iu = int(round((uu + TENT_L / 2) / TENT_L * TENT_NU))
                hz = ridge[min(max(iu, 0), TENT_NU)]
                vx = aa * TENT_W / 2
                z = hz * (1 - aa) - 0.1 * hz * 4 * aa * (1 - aa) + 0.012
                ring.append(bm.verts.new((vx, uu + w, z)))
        bm.faces.new(ring[:-1])
    obj_from_bm('TentCuts', bm, MAT['slit'], collection='Camp', loc=CAMP['origin'])
    build_camp_gear()


def ski_bm(bm, length=1.95, width=0.075, matrix=Matrix()):
    """A wooden ski with an upturned tip, lying along +Y."""
    n = 14
    prev = None
    for i in range(n + 1):
        t = i / n
        y = -length / 2 + length * t
        z = 0.0
        if t > 0.86:
            z = 0.11 * ((t - 0.86) / 0.14) ** 2
        w = width * (0.85 if 0.4 < t < 0.6 else 1.0)
        ring = [bm.verts.new(matrix @ Vector(p)) for p in ((-w / 2, y, z), (w / 2, y, z), (w / 2, y, z + 0.018), (-w / 2, y, z + 0.018))]
        if prev:
            for k in range(4):
                bm.faces.new((prev[k], prev[(k + 1) % 4], ring[(k + 1) % 4], ring[k]))
        prev = ring


