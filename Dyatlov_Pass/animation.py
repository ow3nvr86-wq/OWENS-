def seg_matrix(p0, p1, radius_scale=1.0):
    """Matrix that maps a unit-length cylinder along +Z centred at origin onto segment p0-p1."""
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    q = Vector((0, 0, 1)).rotation_difference(d.normalized())
    return Matrix.Translation((p0 + p1) / 2) @ q.to_matrix().to_4x4()


# --- shader node helpers ---------------------------------------------------
def new_mat(name):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    return m, nt, out


def nd(nt, kind, **inputs):
    n = nt.nodes.new(kind)
    for k, v in inputs.items():
        if k.startswith('p_'):
            setattr(n, k[2:], v)
        else:
            sock = n.inputs[k]
            if isinstance(v, bpy.types.NodeSocket):
                nt.links.new(v, sock)
            else:
                sock.default_value = v
    return n


def mth(nt, op, a, b=None, c=None, clamp=False):
    n = nt.nodes.new('ShaderNodeMath')
    n.operation = op
    n.use_clamp = clamp
    for i, v in enumerate((a, b, c)):
        if v is None:
            continue
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, n.inputs[i])
        else:
            n.inputs[i].default_value = v
    return n.outputs[0]


def mixc(nt, fac, a, b):
    n = nt.nodes.new('ShaderNodeMix')
    n.data_type = 'RGBA'
    for idx, v in ((0, fac), (6, a), (7, b)):
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, n.inputs[idx])
        else:
            n.inputs[idx].default_value = v
    return n.outputs[2]


def rgba(c):
    return (c[0], c[1], c[2], 1.0)


def principled(nt, out, **kw):
    p = nt.nodes.new('ShaderNodeBsdfPrincipled')
    for k, v in kw.items():
        if isinstance(v, bpy.types.NodeSocket):
            nt.links.new(v, p.inputs[k])
        else:
            p.inputs[k].default_value = v
    nt.links.new(p.outputs[0], out.inputs['Surface'])
    return p


def noise(nt, scale, detail=2.0, rough=0.5, vec=None, out='Fac'):
    n = nd(nt, 'ShaderNodeTexNoise', Scale=scale, Detail=detail, Roughness=rough)
    if vec is not None:
        nt.links.new(vec, n.inputs['Vector'])
    return n.outputs[out]


def snow_cover(nt, strength=1.0, noise_scale=6.0):
    """0..1 factor: how much snow sits on a surface (up-facing + noise)."""
    geo = nd(nt, 'ShaderNodeNewGeometry')
    sep = nd(nt, 'ShaderNodeSeparateXYZ', Vector=geo.outputs['Normal'])
    up = mth(nt, 'MULTIPLY_ADD', sep.outputs['Z'], 1.6, -0.55, clamp=True)
    n = noise(nt, noise_scale, 3.0, 0.6)
    f = mth(nt, 'MULTIPLY', up, mth(nt, 'MULTIPLY_ADD', n, 1.8, -0.35, clamp=True), clamp=True)
    return mth(nt, 'MULTIPLY', f, strength, clamp=True)


MAT = {}


def simple_mat(name, color, rough=0.7, snow=0.0, noise_amt=0.15, noise_scale=8.0, emission=None, estr=0.0,
               metal=0.0, coat=0.0):
    m, nt, out = new_mat(name)
    n = noise(nt, noise_scale, 3.0, 0.55)
    base = mixc(nt, mth(nt, 'MULTIPLY', n, noise_amt), rgba(color), rgba([c * 0.55 for c in color]))
    if snow > 0:
        base = mixc(nt, snow_cover(nt, snow), base, (0.82, 0.86, 0.92, 1))
    p = principled(nt, out, **{'Base Color': base, 'Roughness': rough, 'Metallic': metal, 'Coat Weight': coat})
    if emission is not None:
        p.inputs['Emission Color'].default_value = rgba(emission)
        p.inputs['Emission Strength'].default_value = estr
    MAT[name] = m
    return m


def snow_material(name='snow', bump=True, scour=True):
    """Wind-packed snow: cold white with blue-grey scoured patches and wind ripples."""
    m, nt, out = new_mat(name)
    tc = nd(nt, 'ShaderNodeTexCoord')
    obj = tc.outputs['Object']
    # stretch the coordinates along the wind direction (x) for sastrugi-like streaks
    mp = nd(nt, 'ShaderNodeMapping', Vector=obj)
    mp.inputs['Scale'].default_value = (0.35, 1.6, 1.0)
    streak = noise(nt, 1.3, 2.0, 0.6, vec=mp.outputs[0])
    big = noise(nt, 0.035, 1.0, 0.5, vec=obj)
    geo = nd(nt, 'ShaderNodeNewGeometry')
    sep = nd(nt, 'ShaderNodeSeparateXYZ', Vector=geo.outputs['Normal'])
    steep = mth(nt, 'MULTIPLY_ADD', sep.outputs['Z'], -6.0, 4.0, clamp=True)      # 0 flat .. 1 at ~ >55 deg
    rockn = noise(nt, 0.6, 2.0, 0.7, vec=obj)
    rockf = mth(nt, 'MULTIPLY', steep, mth(nt, 'MULTIPLY_ADD', rockn, 2.2, -0.75, clamp=True), clamp=True)
    white = (0.80, 0.84, 0.90, 1)
    blue = (0.58, 0.65, 0.76, 1)
    col = mixc(nt, mth(nt, 'MULTIPLY', streak, 0.45 if scour else 0.2), white, blue)
    col = mixc(nt, mth(nt, 'MULTIPLY', big, 0.35), col, (0.70, 0.75, 0.83, 1))
    col = mixc(nt, rockf, col, (0.05, 0.05, 0.055, 1))
    p = principled(nt, out, **{'Base Color': col, 'Roughness': 0.62, 'Specular IOR Level': 0.35})
    if bump:
        rip = noise(nt, 9.0, 0.0, 0.5, vec=mp.outputs[0])
        b = nd(nt, 'ShaderNodeBump', Strength=0.18, Distance=0.05, Height=mth(nt, 'ADD', rip, mth(nt, 'MULTIPLY', streak, 0.6)))
        nt.links.new(b.outputs[0], p.inputs['Normal'])
    MAT[name] = m
    return m


def fabric_material(name, color, snow=0.7):
    m, nt, out = new_mat(name)
    tc = nd(nt, 'ShaderNodeTexCoord')
    w = nd(nt, 'ShaderNodeTexWave', Vector=tc.outputs['Object'], Scale=60.0, Distortion=1.5)
    n = noise(nt, 4.0, 3.0, 0.6)
    base = mixc(nt, mth(nt, 'MULTIPLY', n, 0.35), rgba(color), rgba([c * 0.5 for c in color]))
    base = mixc(nt, mth(nt, 'MULTIPLY', w.outputs['Fac'], 0.08), base, rgba([c * 0.8 for c in color]))
    if snow > 0:
        base = mixc(nt, snow_cover(nt, snow, 9.0), base, (0.80, 0.84, 0.90, 1))
    principled(nt, out, **{'Base Color': base, 'Roughness': 0.88, 'Specular IOR Level': 0.25,
                           'Sheen Weight': 0.3})
    MAT[name] = m
    return m


def emission_mat(name, color, strength):
    m, nt, out = new_mat(name)
    e = nd(nt, 'ShaderNodeEmission', Color=rgba(color), Strength=strength)
    nt.links.new(e.outputs[0], out.inputs['Surface'])
    MAT[name] = m
    return m


def strength_socket(name):
    """The Emission Strength socket of an emission material (for keyframing)."""
    for n in MAT[name].node_tree.nodes:
        if n.type == 'EMISSION':
            return n.inputs['Strength']
    return None


