def build_compositor(sc):
    sc.use_nodes = True
    nt = sc.node_tree
    nt.nodes.clear()

    def n(kind, **kw):
        x = nt.nodes.new(kind)
        for k, v in kw.items():
            setattr(x, k, v)
        return x
    rl = n('CompositorNodeRLayers')
    # distance fog from the mist pass
    ramp = n('CompositorNodeValToRGB')
    ramp.color_ramp.elements[0].position = 0.0
    ramp.color_ramp.elements[1].position = 1.0
    nt.links.new(rl.outputs['Mist'], ramp.inputs[0])
    amt = n('CompositorNodeMath', operation='MULTIPLY', name='FogAmt')
    amt.inputs[0].default_value = 0.4
    nt.links.new(ramp.outputs[0], amt.inputs[1])
    fog = n('CompositorNodeMixRGB', blend_type='MIX', name='FogColor')
    fog.inputs[2].default_value = (0.2, 0.25, 0.34, 1)
    nt.links.new(amt.outputs[0], fog.inputs[0])
    nt.links.new(rl.outputs['Image'], fog.inputs[1])
    # moonlight shafts: bright pass -> sun beams -> add
    bright = n('CompositorNodeRGBToBW')
    nt.links.new(fog.outputs[0], bright.inputs[0])
    thr = n('CompositorNodeMath', operation='SUBTRACT', use_clamp=True)
    thr.inputs[1].default_value = 0.55
    nt.links.new(bright.outputs[0], thr.inputs[0])
    beams = n('CompositorNodeSunBeams', name='Beams', ray_length=0.22)
    nt.links.new(thr.outputs[0], beams.inputs[0])
    bamt = n('CompositorNodeMath', operation='MULTIPLY', name='BeamAmt')
    nt.links.new(beams.outputs[0], bamt.inputs[1])
    tint = n('CompositorNodeMixRGB', blend_type='MULTIPLY')
    tint.inputs[0].default_value = 1.0
    tint.inputs[2].default_value = (0.75, 0.85, 1.0, 1)
    nt.links.new(bamt.outputs[0], tint.inputs[1])
    add = n('CompositorNodeMixRGB', blend_type='ADD')
    add.inputs[0].default_value = 1.0
    nt.links.new(fog.outputs[0], add.inputs[1])
    nt.links.new(tint.outputs[0], add.inputs[2])
    glare = n('CompositorNodeGlare', glare_type='FOG_GLOW', quality='HIGH', threshold=0.9, size=8, mix=-0.6)
    nt.links.new(add.outputs[0], glare.inputs[0])
    # cold documentary grade
    cb = n('CompositorNodeColorBalance', correction_method='LIFT_GAMMA_GAIN')
    cb.lift = (0.975, 0.995, 1.05)
    cb.gamma = (0.96, 0.99, 1.06)
    cb.gain = (0.86, 0.95, 1.10)
    nt.links.new(glare.outputs[0], cb.inputs[1])
    hsv = n('CompositorNodeHueSat')
    hsv.inputs['Saturation'].default_value = 0.82
    nt.links.new(cb.outputs[0], hsv.inputs['Image'])
    comp = n('CompositorNodeComposite')
    nt.links.new(hsv.outputs[0], comp.inputs[0])     # vignette and grain are added in the edit stage


