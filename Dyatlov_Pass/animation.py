# Terrain: one polar-grid mesh centred on the camp (fine near the tent, coarse far away)
# ============================================================================
def build_terrain():
    K = 448
    rs = [0.0]
    r = 0.3
    while r < 32000:
        rs.append(r)
        r *= 1.021
    rs = np.array(rs)
    ang = np.linspace(0, 2 * np.pi, K, endpoint=False)
    R, A = np.meshgrid(rs[1:], ang, indexing='ij')
    X = R * np.cos(A)
    Y = R * np.sin(A)
    Z = height(X, Y)
    verts = np.concatenate([[[0, 0, float(height(0.0, 0.0))]], np.stack([X, Y, Z], -1).reshape(-1, 3)])
    nr = len(rs) - 1
    faces = []
    for k in range(K):
        faces.append((0, 1 + k, 1 + (k + 1) % K))
    idx = lambda i, k: 1 + i * K + (k % K)  # noqa: E731
    for i in range(nr - 1):
        for k in range(K):
            faces.append((idx(i, k), idx(i + 1, k), idx(i + 1, k + 1), idx(i, k + 1)))
    ob = mesh_obj('Terrain', verts, faces, MAT['snow'], collection='Terrain')
    print('terrain verts', len(verts))
    return ob


