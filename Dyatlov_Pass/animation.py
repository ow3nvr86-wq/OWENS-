def tree_mesh(name, seed, tiers=11, slim=0.26):
    rng = np.random.default_rng(seed)
    verts, faces = [], []

    def add(v):
        verts.append(v)
        return len(verts) - 1
    # trunk
    seg = 6
    base = [add((0.018 * math.cos(a), 0.018 * math.sin(a), -0.05)) for a in np.linspace(0, 2 * np.pi, seg, endpoint=False)]
    top = add((0, 0, 0.98))
    for i in range(seg):
        faces.append((base[i], base[(i + 1) % seg], top))
    trunk_faces = len(faces)
    for t in range(tiers):
        h = 0.10 + 0.86 * t / (tiers - 1) + rng.uniform(-0.015, 0.015)
        rad = slim * (1.0 - h) ** 0.85 + 0.025
        rad *= rng.uniform(0.85, 1.15)
        n = 14
        cz = h + 0.10 * (1 - h) + 0.03
        c = add((0, 0, cz))
        rim = []
        for k in range(n):
            a = 2 * np.pi * k / n + rng.uniform(-0.12, 0.12) + t
            rr = rad * (1.0 if k % 2 == 0 else rng.uniform(0.55, 0.75))
            droop = 0.06 * (rr / max(rad, 1e-3)) + rng.uniform(0, 0.02)
            rim.append(add((rr * math.cos(a), rr * math.sin(a), h - droop * (0.5 + rad))))
        under = add((0, 0, h + 0.015))
        for k in range(n):
            faces.append((c, rim[k], rim[(k + 1) % n]))
            faces.append((under, rim[(k + 1) % n], rim[k]))
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.materials.append(MAT['bark'])
    me.materials.append(MAT['pine'])
    mi = [0] * trunk_faces + [1] * (len(faces) - trunk_faces)
    me.polygons.foreach_set('material_index', mi)
    me.update()
    return me


def build_forest():
    tc = template_collection('TreeTemplates')
    for i in range(5):
        me = tree_mesh(f'tree{i}', 100 + i, tiers=10 + i % 3, slim=0.22 + 0.03 * (i % 3))
        ob = bpy.data.objects.new(f'tree{i}', me)
        tc.objects.link(ob)
    rng = np.random.default_rng(42)
    pts = []
    # near zone (within ~3 km) on a jittered 7 m grid, far zone on a 22 m grid
    for (lo, hi, step, sc0) in ((200, 3600, 7.0, 1.0), (-9000, 9000, 30.0, 1.25)):
        g = np.arange(lo, hi, step)
        gx, gy = np.meshgrid(g, np.arange(-2600 if step < 10 else -9000, 2600 if step < 10 else 9000, step))
        gx = gx.ravel() + rng.uniform(-step / 2, step / 2, gx.size)
        gy = gy.ravel() + rng.uniform(-step / 2, step / 2, gy.size)
        if step > 10:
            keep = ~((gx > 200) & (gx < 3600) & (np.abs(gy) < 2600))
            gx, gy = gx[keep], gy[keep]
        z = height(gx, gy, platform=False)
        n = terrain_normal(gx, gy, e=3.0)[:, 2]
        patch = fbm(gx / 260.0, gy / 260.0, 3, seed=77)
        tl = -175.0 + 55.0 * fbm(gx / 900.0, gy / 900.0, 2, seed=78)        # tree line (rel. camp)
        dens = np.clip((tl - z) / 60.0, 0, 1) * np.clip((n - 0.78) / 0.1, 0, 1) * np.clip(0.75 + patch, 0, 1)
        # a few lone, stunted trees higher up the slope for depth
        sparse = (z < tl + 40) & (rng.random(gx.size) < 0.004)
        keep = (rng.random(gx.size) < dens) | sparse
        gx, gy, z = gx[keep], gy[keep], z[keep]
        d = np.sqrt(gx ** 2 + gy ** 2)
        keep = d > 60
        gx, gy, z = gx[keep], gy[keep], z[keep]
        pts.append(np.stack([gx, gy, z - 0.3], -1))
    pts = np.concatenate(pts)
    N = len(pts)
    variant = rng.integers(0, 5, N)
    far = (pts[:, 0] < 200) | (pts[:, 0] > 3600) | (np.abs(pts[:, 1]) > 2600)
    hgt = rng.uniform(7.0, 17.0, N) * np.where(pts[:, 2] > -180, 0.6, 1.0) * np.where(far, 1.5, 1.15)
    wid = hgt * rng.uniform(0.85, 1.2, N)
    rot = np.stack([rng.normal(0, 0.03, N), rng.normal(0, 0.03, N), rng.uniform(0, 6.28, N)], -1)
    scale = np.stack([wid, wid, hgt], -1)
    ob = gn_scatter('Forest', pts, variant, rot, scale, tc, 'Terrain', extra={'shade': rng.random(N)})
    print('trees', N)
    return ob


def rock_mesh(name, seed):
    rng = np.random.default_rng(seed)
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=3, radius=1.0)
    for v in bm.verts:
        p = v.co
        d = 1.0 + 0.25 * perlin(p.x * 1.7 + seed, p.y * 1.7, 3) + 0.12 * perlin(p.y * 4 + seed, p.z * 4, 4)
        v.co = Vector((p.x * d * rng.uniform(0.9, 1.3), p.y * d, p.z * d * 0.62))
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(MAT['rock'])
    for p in me.polygons:
        p.use_smooth = False
    return me


