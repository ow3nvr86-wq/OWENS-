    env = np.maximum.reduce([np.roll(env, j) for j in range(0, rel_k, rel_k // 12)])
    duck_m = 1 - 0.6 * env
    duck_a = 1 - 0.5 * env
    bed = music + amb + sfx
    # voice level = the bed's peak level x 2.2, so the narration sits ~10-15 dB above music and wind
    vo_gain = 2.2 * np.abs(bed).max() / (np.abs(vo).max() + 1e-9)
    with_voice = 0.38 * music * duck_m + 0.38 * amb * duck_a + 0.5 * sfx + np.stack([vo, vo]) * vo_gain * 0.38
