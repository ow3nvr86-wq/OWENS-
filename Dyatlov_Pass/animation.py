    stamp = np.sin(2 * np.pi * 95 * tt) * np.exp(-tt * 25) + _bandpass(_noise(len(tt), 3), 200, 3000) * np.exp(-tt * 60) * 0.6
    _place(sfx, stamp, 21.25, 0.6)
