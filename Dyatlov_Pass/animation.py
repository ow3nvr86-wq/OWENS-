_PERM = {}


def _perm(seed):
    if seed not in _PERM:
        rng = np.random.default_rng(seed)
        p = rng.permutation(256)
        ang = rng.uniform(0, 2 * np.pi, 256)
        _PERM[seed] = (np.concatenate([p, p]), np.cos(ang), np.sin(ang))
    return _PERM[seed]


def perlin(x, y, seed=0):
    perm, gx, gy = _perm(seed)
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    x0 = np.floor(x)
    y0 = np.floor(y)
    xf, yf = x - x0, y - y0
    xi = x0.astype(np.int64) & 255
    yi = y0.astype(np.int64) & 255

    def g(ix, iy, dx, dy):
        h = perm[perm[ix] + iy]
        return gx[h] * dx + gy[h] * dy

    u = xf * xf * xf * (xf * (xf * 6 - 15) + 10)
    v = yf * yf * yf * (yf * (yf * 6 - 15) + 10)
    n00 = g(xi, yi, xf, yf)
    n10 = g((xi + 1) & 255, yi, xf - 1, yf)
    n01 = g(xi, (yi + 1) & 255, xf, yf - 1)
    n11 = g((xi + 1) & 255, (yi + 1) & 255, xf - 1, yf - 1)
    a = n00 + u * (n10 - n00)
    b = n01 + u * (n11 - n01)
    return (a + v * (b - a)) * 1.4


def fbm(x, y, octaves=5, seed=0, lac=2.03, gain=0.5):
    s = np.zeros_like(np.asarray(x, float))
    amp, f = 1.0, 1.0
    for o in range(octaves):
        s = s + amp * perlin(x * f, y * f, seed + o * 17)
        amp *= gain
        f *= lac
    return s


def ridged(x, y, octaves=5, seed=0):
    s = np.zeros_like(np.asarray(x, float))
    amp, f, w = 1.0, 1.0, 1.0
    for o in range(octaves):
        n = 1.0 - np.abs(perlin(x * f, y * f, seed + o * 31))
        n = n * n * w
        w = np.clip(n * 1.6, 0, 1)
        s = s + amp * n
        amp *= 0.5
        f *= 2.05
    return s


# Camp (the tent) sits at the origin on the east slope of the mountain; the slope falls toward +x
# into a forested valley about 1.5 km away. The summit dome is to the west (-x).
