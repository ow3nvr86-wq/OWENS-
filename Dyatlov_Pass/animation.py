def shake_offset(f, s):
    amp = SHAKE.get(s['name'], 0.0)
    if amp <= 0:
        return Vector((0, 0, 0))
    t = tsec(f)
    imp = SET.get('impact_t', 1e9)
    k = math.exp(-max(t - imp, 0) * 2.5) * (t >= imp)
    return Vector((math.sin(t * 37.0), math.sin(t * 29.0 + 1), math.sin(t * 23.0 + 2))) * amp * k


