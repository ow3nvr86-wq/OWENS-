    cue(0.0, 'D-minor drone pad (D2-A2-D3-F3), swells at 29 s and before the slab release; cut to silence at the crack', 'music')
    # heartbeat pulse: discovery and the wind-loading build-up
    beats = list(np.arange(6.4, 16.8, 0.92)) + list(np.arange(38.5, 41.6, 0.62))
    for b in beats:
        for k, dd in enumerate((0.0, 0.22)):
            tt = np.arange(int(0.35 * SR)) / SR
            th = np.sin(2 * np.pi * 52 * tt) * np.exp(-tt * 14) * (0.8 if k else 1.0)
            _place(music, th, b + dd, 0.55)
