WALL_K = 3.2   # uphill wall: ~73 deg


def s_cut(x):
    x = np.asarray(x, float)
    return np.minimum(s0(x), np.maximum(FLOOR_Z, FLOOR_Z + (-x) * WALL_K))


def s_cut_slope(x, e=0.01):
    return (s_cut(x + e) - s_cut(x - e)) / (2 * e)


def rock_z(x):
    x = np.asarray(x, float)
    return s0(x) - 1.75 - 0.18 * np.sin(0.7 * x + 1.0)


def surface4(x, cutf):
    return s0(x) - cutf * (s0(x) - s_cut(x))


