def build_star_dome():
    """Stars on a huge camera-only dome (cheaper than evaluating them in the world shader for every bounce)."""
    m, nt, out = new_mat('stars')
    tc = nd(nt, 'ShaderNodeTexCoord')
    vor = nd(nt, 'ShaderNodeTexVoronoi', Vector=tc.outputs['Object'], Scale=420.0)
    star = mth(nt, 'LESS_THAN', vor.outputs['Distance'], 0.05)
    tw = noise(nt, 30.0, 1.0, 0.5, vec=tc.outputs['Object'])
    star = mth(nt, 'MULTIPLY', star, mth(nt, 'MULTIPLY_ADD', tw, 2.5, -0.9, clamp=True))
    em = nd(nt, 'ShaderNodeEmission', Color=(0.85, 0.9, 1.0, 1), Strength=mth(nt, 'MULTIPLY', star, 1.6))
    tr = nd(nt, 'ShaderNodeBsdfTransparent')
    add = nd(nt, 'ShaderNodeAddShader')
    nt.links.new(em.outputs[0], add.inputs[0])
    nt.links.new(tr.outputs[0], add.inputs[1])
    nt.links.new(add.outputs[0], out.inputs['Surface'])
    MAT['stars'] = m
