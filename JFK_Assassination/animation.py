def resample(pts, step):
    pts = np.asarray(pts, float)
    d = np.r_[0, np.cumsum(np.linalg.norm(np.diff(pts, axis=0), axis=1))]
    s = np.arange(0, d[-1] + 1e-6, step)
    return np.stack([np.interp(s, d, pts[:, 0]), np.interp(s, d, pts[:, 1])], -1)


def ribbon(name, pts, width, z, mat, collection='City', step=2.0, off=0.0):
    """A flat strip of the given width along a 2D polyline (u across 0..1, v = metres along)."""
    p = resample(pts, step)
    d = np.gradient(p, axis=0)
    d /= np.linalg.norm(d, axis=1, keepdims=True) + 1e-9
    nrm = np.stack([-d[:, 1], d[:, 0]], -1)
    c = p + nrm * off
    L = c + nrm * width / 2
    R = c - nrm * width / 2
    n = len(p)
    verts = np.zeros((2 * n, 3))
    verts[0::2, :2] = R
    verts[1::2, :2] = L
    verts[:, 2] = z
    faces = [(2 * i, 2 * i + 2, 2 * i + 3, 2 * i + 1) for i in range(n - 1)]
    ob = mesh_obj(name, verts, faces, mat, collection, smooth=False)
    s = np.r_[0, np.cumsum(np.linalg.norm(np.diff(c, axis=0), axis=1))]
    uv = np.zeros((2 * n, 2))
    uv[0::2, 0], uv[1::2, 0] = 0.0, 1.0
    uv[0::2, 1] = uv[1::2, 1] = s / 10.0
    uvl = ob.data.uv_layers.new(name='UVMap')
    loops = np.zeros(len(ob.data.loops), np.int32)
    ob.data.loops.foreach_get('vertex_index', loops)
    uvl.data.foreach_set('uv', uv[loops].astype(np.float32).ravel())
    return ob


def kerbs(name, pts, width, collection='City'):
    """Raised kerb lines on both edges of a road."""
    p = resample(pts, 3.0)
    d = np.gradient(p, axis=0)
    d /= np.linalg.norm(d, axis=1, keepdims=True) + 1e-9
    nrm = np.stack([-d[:, 1], d[:, 0]], -1)
    bm = bmesh.new()
    for side in (-1, 1):
        e = p + nrm * side * width / 2
        for i in range(len(e) - 1):
            a, b = e[i], e[i + 1]
            ln = np.linalg.norm(b - a)
            if ln < 1e-3:
                continue
            ang = math.atan2(b[1] - a[1], b[0] - a[0])
            mtx = Matrix.Translation(((a[0] + b[0]) / 2, (a[1] + b[1]) / 2, 0.075)) @ Matrix.Rotation(ang, 4, 'Z')
            add_box(bm, -ln / 2, -0.15, -0.075, ln / 2, 0.15, 0.075, matrix=mtx)
    return obj_from_bm(name, bm, MAT['kerb'], collection=collection)


def elm_dist(X, Y):
    q = resample(ELM_W[:61], 2.0)
    d = np.full(X.shape, 1e9)
    side = np.zeros(X.shape)
    for k in range(len(q) - 1):
        a, b = q[k], q[k + 1]
        dd = np.hypot(X - a[0], Y - a[1])
        closer = dd < d
        d = np.where(closer, dd, d)
        cr = (b[0] - a[0]) * (Y - a[1]) - (b[1] - a[1]) * (X - a[0])
        side = np.where(closer, np.sign(cr), side)
    return d, side


def knoll_h(X, Y):
    """The grassy slope north of Elm St (rising ~4 m to the fence line and the rail yard)."""
    d, side = elm_dist(X, Y)
    north = side > 0
    hgt = 4.2 * sstep(d, 8.0, 40.0) * north * sstep(-X, 25.0, 60.0)
    hgt = np.where((Y > 125) & (X < -25), np.maximum(hgt, 4.2 * sstep(-X, 25.0, 60.0)), hgt)
    return hgt


