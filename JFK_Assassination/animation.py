    # archive: big quiet room, paper, radio static under "acoustic evidence", stamps
    al = _env(t, [(0, 0), (arch[0] - 0.02, 0), (arch[0] + 0.1, 1.0), (arch[1] - 0.05, 1.0), (arch[1] + 0.02, 0), (60, 0)])
    big = _reverb(_norm(_bandpass(_noise(N, 40, 'pink'), 60, 900)), 3.0, seed=41)
    for ch in range(2):
        amb[ch] += _norm(np.roll(big, ch * 1300)) * al * 0.3
    cue(arch[0], 'The archive: a large quiet room, ventilation air, distant footsteps', 'ambience')
    for k in range(3):
        st = _step(60 + k)
        _place(sfx, _norm(st + _reverb(st, 1.6, seed=61) * 0.9), arch[0] + 0.5 + k * 0.7, 0.08, pan=0.4)
    a, b = EV['hsca_slide']
    _place(sfx, _paper(b - a + 0.2, 70), a, 0.45, pan=0.3)
    cue(a, 'A heavy report slides across the table (paper and cloth on wood)', 'sfx')
    a = EV['acoustic'][0]
    _place(sfx, _static(2.2, 44, 1.0), a + 0.1, 0.22, pan=-0.2)
    cue(a, 'Police-radio static under "acoustic evidence" (a nod to the disputed recording)', 'sfx')
    for k in range(6):
        _place(sfx, _paper(0.55, 80 + k), EV['docs'][0] + k * 0.62, 0.25, pan=-0.5 + 0.2 * k)
    cue(EV['docs'][0], 'Released pages slide onto the table one by one', 'sfx')
    for nm in ('stamp_2025', 'stamp_2026'):
        _place(sfx, _stamp(), EV[nm][0], 0.7)
        cue(EV[nm][0], f'Rubber stamp thump: {nm.replace("stamp_", "RELEASED ")}', 'sfx')
    # night: wind, distant traffic, a train horn from the rail yard
    nl = _env(t, [(0, 0), (S['night'][0] - 0.02, 0), (S['night'][0] + 0.3, 1.0), (59.0, 1.0), (60, 0)])
    for ch in range(2):
        w = _norm(_bandpass(_noise(N, 50 + ch, 'pink'), 60, 900)) * (0.6 + 0.3 * np.sin(2 * np.pi * t / 5.3 + ch))
        amb[ch] += w * nl * 0.45
    cue(S['night'][0], 'Night wind across the empty plaza, a far-off traffic hush', 'ambience')
    hn = _horn()
    hn = hn + _reverb(hn, 3.0, seed=52) * 1.6
    _place(amb, _norm(hn), S['night'][0] + 1.3, 0.14, pan=-0.5)
    cue(S['night'][0] + 1.3, 'A distant locomotive horn from the rail yard behind the plaza', 'ambience')

    # --- score -----------------------------------------------------------------------------------
    D2, A2, D3, F3 = 73.42, 110.0, 146.83, 174.61
    pad = _pad([D2, A2, D3, F3], DURATION, seed=1, cutoff=520)
    penv = _env(t, [(0, 0.0), (0.4, 0.55), (S['main_high'][0], 0.45), (S['plaza'][0], 0.55), (shot_t - 0.05, 0.75), (shot_t + 0.02, 0.0),
                    (shot_t + 1.4, 0.0), (shot_t + 3.0, 0.5), (S['desk'][0], 0.45), (S['archive'][0], 0.55), (S['night'][0], 0.6),
                    (57.2, 0.8), (57.3, 0.4), (59.6, 0.3), (60, 0.0)])
    music[0] += pad * penv * 0.35
    music[1] += np.roll(pad, 300) * penv * 0.35
    cue(0.0, 'Dark string-like drone in D minor; drops out completely at "shots rang out" and returns low and grieving', 'music')
    # muffled drums (cloth-covered snares) into the front page
    dr = np.zeros((2, N))
    tm = shot_t + 1.6
    k = 0
    while tm < S['paper2'][1] - 0.2:
        acc = 1.0 if k % 6 == 0 else 0.55
        g = 0.18 * acc * ramp(tm, shot_t + 1.6, shot_t + 3.0)
        _place(dr, _snare(int(tm * 100), muffle=2.2), tm, g, pan=-0.15)
        tm += 1 / 13.0 if (k // 6) % 2 == 0 else 1 / 6.5
        k += 1
    for ch in range(2):
        dr[ch] += _reverb(dr[ch], 2.0, seed=12 + ch) * 0.7
    music += dr
    cue(shot_t + 1.6, 'Muffled drums (cloth-covered snares), quiet and slow, leading into the front page', 'music')
    # a low pulse through the investigations
    beat = 60 / 84
    tm = S['archive'][0]
    k = 0
    while tm < S['files'][1] - 0.1:
        f = [D2 * 2, D2 * 2, F3, D2 * 2, A2 * 2, D2 * 2, F3, 98.0 * 2][k % 8]
        _place(music, _pluck(f, 0.5, 0.3), tm, 0.2 * (0.5 + 0.5 * ramp(tm, S['archive'][0], S['files'][1])), pan=0.15 * math.sin(k))
        tm += beat / 2
        k += 1
    cue(S['archive'][0], 'Low muted pulse (eighth notes, 84 bpm) building through the investigations', 'music')
    motif = [(0.7, 293.66), (1.9, 349.23), (3.1, 329.63), (19.9, 293.66), (21.3, 261.63), (53.1, 293.66), (54.5, 349.23),
             (55.9, 329.63), (57.3, 220.0)]
    mb = np.zeros((2, N))
    for k, (tm, f) in enumerate(motif):
        _place(mb, _pluck(f, 3.5, 0.6), tm, 0.2, pan=0.3 * math.sin(k))
    for ch in range(2):
        mb[ch] += _reverb(mb[ch], 3.6, seed=40 + ch) * 1.4
    music += mb
    cue(0.7, 'Sparse piano-like notes over the hook; reprised in the investigation room and at night', 'music')
    hits = [(S['main_high'][0], 0.45, 46, 'Low hit on the cut to Dallas'), (S['paper2'][0] + 1.5, 0.6, 50, 'Low hit as the front page lands'),
            (S['archive'][0], 0.45, 46, 'Low hit on the cut into the archive'), (57.3, 1.0, 50, 'Final deep impact on WHAT REALLY HAPPENED?')]
    for tm, g, f0, what in hits:
        _place(music, _boom(3.2, f0, f0 / 2, seed=int(tm * 10)), tm, g)
        cue(tm, what, 'music')
    for (a, b_, rg) in ((S['paper2'][0], S['paper2'][0] + 1.5, 0.5), (55.4, 57.28, 0.7)):
        n = int((b_ - a) * SR)
        tt = np.arange(n) / SR
        r = _sweep_bp(_noise(n, int(a * 10)), lambda x, d=(b_ - a): 250 + 3600 * (x / d) ** 2, q=4)
        _place(music, _norm(r) * (tt / tt[-1]) ** 2 * 0.5, a, rg)
        cue(a, f'Noise riser into {b_:.2f} s', 'music')
    # --- sound effects on the front pages --------------------------------------------------------
    _place(sfx, _paper(0.9, 90), 0.35, 0.25)
    cue(0.35, 'Paper rustle as the front page comes out of the dark', 'sfx')
    a, b = EV['paper_spin']
    _place(sfx, _whoosh(b - a, 91), a, 0.4)
    _place(sfx, _paper(0.25, 92), b - 0.05, 0.5)
    cue(a, 'Whoosh as the front page spins toward the lens; a paper slap as it stops', 'sfx')

    # --- mix -----------------------------------------------------------------------------------------
    vo = np.zeros(N)
    vpath = os.path.join(ROOT, 'audio', 'narration.wav')
    if os.path.exists(vpath):
        with wave.open(vpath) as w:
            a_ = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768
        vo[:min(N, len(a_))] = a_[:N]
    env = np.abs(vo)
    k = int(0.03 * SR)
    env = np.convolve(env, np.ones(k) / k, mode='same')
    env = np.clip(env / (env.max() + 1e-9) * 4, 0, 1)
    rel_k = int(0.3 * SR)
    env = np.maximum.reduce([np.roll(env, j) for j in range(0, rel_k, rel_k // 12)])
    duck_m = 1 - 0.6 * env
    duck_a = 1 - 0.5 * env
    bed = music + amb + sfx
    vo_gain = 2.2 * np.abs(bed).max() / (np.abs(vo).max() + 1e-9)
    with_voice = 0.38 * music * duck_m + 0.38 * amb * duck_a + 0.45 * sfx * duck_a + np.stack([vo, vo]) * vo_gain * 0.38
    no_voice = bed
    end_fade = np.clip((DURATION - t) / 0.2, 0, 1)
    os.makedirs(os.path.join(ROOT, 'audio'), exist_ok=True)
    outs = {}
    for name, mix in (('mix_with_voice', with_voice), ('mix_no_voice', no_voice), ('music_sfx_stem', bed)):
        mix = mix * end_fade
        mix = np.tanh(mix / (np.abs(mix).max() + 1e-9) * 1.1) * 0.89
        p = os.path.join(ROOT, 'audio', name + '.wav')
        with wave.open(p, 'wb') as w:
            w.setnchannels(2)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((np.clip(mix.T, -1, 1) * 32767).astype(np.int16).tobytes())
        outs[name] = p
    for name in ('mix_with_voice', 'mix_no_voice'):
        p = outs[name]
        tmp = p.replace('.wav', '_ln.wav')
        try:
            # two-pass, linear loudness normalisation (keeps the dynamics: the silence after the shots stays silent)
            r = subprocess.run(['ffmpeg', '-hide_banner', '-i', p, '-af', 'loudnorm=I=-14:TP=-1.5:LRA=20:print_format=json', '-f', 'null', '-'],
                               check=True, capture_output=True, text=True).stderr
            js = json.loads(r[r.rindex('{'):r.rindex('}') + 1])
            af = (f"loudnorm=I=-14:TP=-1.5:LRA=20:linear=true:measured_I={js['input_i']}:measured_TP={js['input_tp']}:"
                  f"measured_LRA={js['input_lra']}:measured_thresh={js['input_thresh']}:offset={js['target_offset']}")
            subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', p, '-af', af, '-ar', str(SR), tmp], check=True)
            os.replace(tmp, p)
        except (OSError, subprocess.CalledProcessError) as e:
            print('loudnorm skipped:', e)
    write_sound_design(cues)
    print('audio written:', ', '.join(outs))


