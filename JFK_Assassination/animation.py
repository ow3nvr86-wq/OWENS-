    P, R = [], []

    def row(x0, x1, y, face, spacing, jit=0.12, prob=1.0, z=0.15):
        x = x0
        while x < x1:
            if any(abs(x - xs) < 7.5 for xs in XSTREETS) or rng.random() > prob:
                x += spacing
                continue
            P.append((x + rng.uniform(-jit, jit), y + rng.uniform(-jit, jit), z))
            R.append(face + rng.uniform(-0.5, 0.5))
            x += spacing * rng.uniform(0.8, 1.25)
    # Main Street: crowds several deep on both kerbs
    for side in (1, -1):
        face = 0.0 if side > 0 else math.pi
        for k, (yy, sp, pr) in enumerate(((9.55, 0.56, 0.97), (10.2, 0.58, 0.95), (10.85, 0.62, 0.9), (11.55, 0.7, 0.75), (12.3, 0.85, 0.5))):
            row(18.0, 900.0, side * yy, face, sp, prob=pr)
    # Dealey Plaza: thinner crowds along Houston and the Elm St kerbs
    for yy in np.arange(12.0, 76.0, 0.75):
        if rng.random() < 0.8:
            P.append((-9.6 + rng.uniform(-0.15, 0.15), yy, 0.15))
            R.append(-math.pi / 2 + rng.uniform(-0.5, 0.5))
        if rng.random() < 0.35:
            P.append((-10.4 + rng.uniform(-0.2, 0.2), yy, 0.15))
            R.append(-math.pi / 2 + rng.uniform(-0.5, 0.5))
    for yy in np.arange(74.0, 88.0, 0.8):
        P.append((9.6, yy, 0.15))
        R.append(math.pi / 2 + rng.uniform(-0.4, 0.4))
    q = resample(ELM_W[:61], 1.6)
    for k, (x, y) in enumerate(q):
        if x > -12 or x < -170:
            continue
        for off, pr in ((7.6, 0.35), (-7.6, 0.25)):
            if rng.random() < pr:
                d = q[min(k + 1, len(q) - 1)] - q[max(k - 1, 0)]
                nrm = np.array([-d[1], d[0]]) / (np.linalg.norm(d) + 1e-9)
                px, py = x + nrm[0] * off, y + nrm[1] * off
                pz = float(knoll_h(np.array([px]), np.array([py]))[0])
                P.append((px, py, pz))
                R.append(math.atan2(-nrm[1] * np.sign(off), -nrm[0] * np.sign(off)) + math.pi / 2 + rng.uniform(-0.4, 0.4))
    n = len(P)
    variant = rng.choice(np.arange(10), n, p=[0.17, 0.17, 0.15, 0.12, 0.05, 0.05, 0.0, 0.14, 0.0, 0.15])
