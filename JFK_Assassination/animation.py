def update_void(t, shot):
    if shot == 'paper':
        VOIDO['spot'].data.energy = 260.0 * ramp(t, 0.15, 1.9)
        VOIDO['fill'].data.energy = 1.5 * ramp(t, 0.6, 2.5)
    if shot == 'paper2':
        a, b = EV['paper_spin']
        u = min(max((t - a) / (b - a), 0.0), 1.0)
        e = 1 - (1 - u) ** 3
        y = 20.0 + (-0.72 - 20.0) * e
        ang = (1 - e) * 5.5 * math.pi + math.radians(-4) * e
        n = Vector((0, -1, 0))
        r = Matrix.Rotation(ang, 3, n) @ Vector((1, 0, 0))
        u_ = Matrix.Rotation(ang, 3, n) @ Vector((0, 0, 1))
        VOIDO['paper2'].matrix_world = basis_matrix(VP(6.0, y, 1.0), r, u_)
        VOIDO['spot2'].data.energy = 520.0 * (0.2 + 0.8 * ramp(t, a, a + 0.6))


