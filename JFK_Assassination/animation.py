MOTOR = {}          # name -> (object, ds, lateral)
FLAGS = []


def add_child(name, bm, mats, parent, loc, rot=0.0, collection='Motorcade'):
    ob = obj_from_bm(name, bm, mats, collection=collection, smooth=True)
    ob.parent = parent
    ob.location = loc
    ob.rotation_euler = (0, 0, rot)
    return ob


def flag_obj(name, tex, parent, loc):
    nx, ny = 8, 5
    xs, zs = np.linspace(0, 0.34, nx + 1), np.linspace(0, 0.2, ny + 1)
    X, Z = np.meshgrid(xs, zs)
    verts = np.stack([np.zeros_like(X), -X, Z], -1).reshape(-1, 3)
    ii = np.arange((nx + 1) * (ny + 1)).reshape(ny + 1, nx + 1)
    faces = np.stack([ii[:-1, :-1], ii[:-1, 1:], ii[1:, 1:], ii[1:, :-1]], -1).reshape(-1, 4)
    ob = mesh_obj(name, verts, faces, flag_material(tex), 'Motorcade', smooth=True)
    uvl = ob.data.uv_layers.new(name='UVMap')
    uv = np.stack([X / 0.34, Z / 0.2], -1).reshape(-1, 2)
    loops = np.zeros(len(ob.data.loops), np.int32)
    ob.data.loops.foreach_get('vertex_index', loops)
    uvl.data.foreach_set('uv', uv[loops].astype(np.float32).ravel())
    ob.parent = parent
    ob.location = loc
    FLAGS.append((ob, verts.copy(), X.ravel()))
    return ob


