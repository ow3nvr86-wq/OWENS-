ROUTE = {}


def build_route():
    """The motorcade route: west on Main St, right onto Houston St, left onto Elm St, through the underpass."""
    elm = ELM_W[:61].copy()
    d = np.gradient(elm, axis=0)
    d /= np.linalg.norm(d, axis=1, keepdims=True)
    nrm = np.stack([-d[:, 1], d[:, 0]], -1)
    lane = elm + nrm * 1.2                    # just right of the centre line (Elm runs west-south-west here)
    lane = lane[lane[:, 0] < -12.0]
    pts = np.vstack([[(980.0, 2.0), (18.0, 2.0)], bez((18.0, 2.0), (3.0, 2.0), (3.0, 17.0), 16)[1:], [(3.0, 62.0)],
                     bez((3.0, 62.0), (3.0, lane[0][1] + 2.0), lane[0], 16)[1:], lane[1:], [(-260.0, 8.0), (-400.0, 0.0)]])
    p = resample(pts, 0.25)
    s = np.r_[0, np.cumsum(np.linalg.norm(np.diff(p, axis=0), axis=1))]
    ROUTE['p'], ROUTE['s'] = p, s


def route_at(s):
    p, ss = ROUTE['p'], ROUTE['s']
    x = np.interp(s, ss, p[:, 0])
    y = np.interp(s, ss, p[:, 1])
    x2 = np.interp(s + 1.5, ss, p[:, 0])
    y2 = np.interp(s + 1.5, ss, p[:, 1])
    x0 = np.interp(s - 1.5, ss, p[:, 0])
    y0 = np.interp(s - 1.5, ss, p[:, 1])
    return x, y, math.atan2(y2 - y0, x2 - x0)


def route_s_near(pt):
    p = ROUTE['p']
    i = int(np.argmin(np.hypot(p[:, 0] - pt[0], p[:, 1] - pt[1])))
    return float(ROUTE['s'][i])


def limo_s(t, shot):
    """Where the limousine is along the route in each street shot (each shot is its own moment)."""
    if shot == 'main_high':
        return route_s_near((360.0, 2.0)) + 5.0 * (t - SHOT['main_high']['t0'])
    if shot == 'main_low':
        return route_s_near((176.0, 2.0)) + 4.6 * (t - SHOT['main_low']['t0'])
    if shot == 'plaza':
        return route_s_near((-12.0, 79.0)) + 4.2 * (t - SHOT['plaza']['t0'])
    return -1e4


def update_motorcade(t, shot):
    s0 = limo_s(t, shot)
    for nm, (ob, ds, lat) in MOTOR.items():
        if nm.startswith('_'):
            continue
        x, y, h = route_at(s0 + ds)
        ob.location = (x - math.sin(h) * lat, y + math.cos(h) * lat, 0.0)
        ob.rotation_euler = (0, 0, h - math.pi / 2)
    arm = MOTOR['_arm'][0]
    w = math.sin(t * 0.9 + 0.4)
    arm.rotation_euler = (0.15, 0.35 + 0.25 * math.sin(t * 7.0), 0.0) if w > 0.3 else (math.pi * 0.8, 0.0, 0.0)
    for ob, v0, X in FLAGS:
        v = v0.copy()
        k = X / 0.34
        v[:, 0] = 0.035 * k * np.sin(t * 13.0 - X * 26.0)
        v[:, 2] = v0[:, 2] - 0.02 * k * k
        ob.data.vertices.foreach_set('co', v.astype(np.float32).ravel())
        ob.data.update()


def build_person(nm, mats, collection, hat=False, coat=False, tie=False, hair=True, scale=1.0):
    root = empty(nm, collection=collection)
    root.rotation_mode = 'XYZ'
    root.scale = (scale, scale, scale)
    hips = empty(nm + '_hips', collection=collection)
    hips.parent = root
    hips.location = (0, 0, 0.95)
    hips.rotation_mode = 'XYZ'
    bm = bmesh.new()
    add_cyl(bm, 0.17, 0.2, 0.58, seg=14, matrix=Matrix.Translation((0, 0, 0.3)) @ Matrix.Diagonal((1.0, 0.62, 1, 1)))
    add_sphere(bm, 0.2, 14, 8, matrix=Matrix.Translation((0, 0, 0.57)) @ Matrix.Diagonal((1.15, 0.65, 0.4, 1)))
    add_cyl(bm, 0.05, 0.05, 0.12, seg=8, matrix=Matrix.Translation((0, 0, 0.68)), mi=1)
    if coat:
        add_cyl(bm, 0.24, 0.31, 0.75, seg=16, matrix=Matrix.Translation((0, 0, -0.3)) @ Matrix.Diagonal((1.0, 0.72, 1, 1)))
        add_cyl(bm, 0.13, 0.15, 0.1, seg=12, matrix=Matrix.Translation((0, 0, 0.66)))
    if tie:
        add_box(bm, -0.035, -0.135, 0.18, 0.035, -0.115, 0.6, mi=2)
    torso = obj_from_bm(nm + '_torso', bm, [MAT[mats['top']], MAT['skin'], MAT['tie']], collection=collection, smooth=True)
    torso.parent = hips
    torso.rotation_mode = 'XYZ'
    bm = bmesh.new()
    add_sphere(bm, 0.105, 14, 10, matrix=Matrix.Translation((0, 0, 0.14)) @ Matrix.Diagonal((0.92, 1.0, 1.12, 1)))
    if hair:
        add_sphere(bm, 0.11, 14, 10, matrix=Matrix.Translation((0, 0.015, 0.175)) @ Matrix.Diagonal((0.95, 1.0, 0.85, 1)), mi=1)
    if hat:
        add_cyl(bm, 0.2, 0.2, 0.015, seg=18, matrix=Matrix.Translation((0, 0, 0.235)), mi=2)
        add_cyl(bm, 0.115, 0.1, 0.13, seg=14, matrix=Matrix.Translation((0, 0, 0.3)), mi=2)
    head = obj_from_bm(nm + '_head', bm, [MAT['skin'], MAT['hair'], MAT['felt']], collection=collection, smooth=True)
    head.parent = torso
    head.location = (0, 0, 0.72)
    head.rotation_mode = 'XYZ'
    p = dict(root=root, hips=hips, torso=torso, head=head)

    def limb(name, r1, r2, length, mat, parent, loc, end=None):
        b = bmesh.new()
        add_cyl(b, r1, r2, length, seg=10, matrix=Matrix.Translation((0, 0, -length / 2)))
        add_sphere(b, r2 * 1.05, 10, 6, matrix=Matrix.Translation((0, 0, -length)))
        if end == 'hand':
            add_sphere(b, 0.045, 10, 6, matrix=Matrix.Translation((0, 0, -length - 0.07)) @ Matrix.Diagonal((0.7, 1.0, 1.3, 1)), mi=1)
        if end == 'foot':
            add_box(b, -0.05, -0.17, -length - 0.07, 0.05, 0.06, -length + 0.02, mi=1)
        o = obj_from_bm(name, b, [MAT[mat], MAT['skin'] if end == 'hand' else MAT['rubber']], collection=collection, smooth=True)
        o.parent = parent
        o.location = loc
        o.rotation_mode = 'XYZ'
        return o
    for side, sx in (('L', 1), ('R', -1)):
        p['arm' + side] = limb(f'{nm}_arm{side}', 0.065, 0.055, 0.31, mats['top'], torso, (sx * 0.235, 0, 0.56))
        p['fore' + side] = limb(f'{nm}_fore{side}', 0.055, 0.045, 0.28, mats['top'], p['arm' + side], (0, 0, -0.31), end='hand')
        p['thigh' + side] = limb(f'{nm}_thigh{side}', 0.085, 0.068, 0.46, mats['legs'], hips, (sx * 0.1, 0, 0.0))
        p['shin' + side] = limb(f'{nm}_shin{side}', 0.065, 0.05, 0.45, mats['legs'], p['thigh' + side], (0, 0, -0.46), end='foot')
    return p

