def update_tv(t, shot):
    on = EV['tv_on'][0]
    if shot != 'tv' or t < on:
        lum = 0.0
    else:
        u = t - on
        lum = (0.15 if u < 0.25 else 1.0) * (2.4 + 0.5 * math.sin(t * 47.0) + 0.3 * math.sin(t * 13.3))
    for s in SHOTVAL.get('tv_lum', []):
        s.default_value = lum
    for s in SHOTVAL.get('tv_roll', []):
        s.default_value = (t * 0.37) % 1.0
    if 'L_tv' in ROOM:
        ROOM['L_tv'].data.energy = 9.0 * lum


