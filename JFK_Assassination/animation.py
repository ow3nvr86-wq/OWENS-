def bez(p0, p1, p2, n=40):
    t = np.linspace(0, 1, n)[:, None]
    return ((1 - t) ** 2) * np.array(p0, float) + 2 * (1 - t) * t * np.array(p1, float) + t * t * np.array(p2, float)


