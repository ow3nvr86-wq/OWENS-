    ng.links.new(named('scl', 'FLOAT_VECTOR'), iop.inputs['Scale'])
    ng.links.new(iop.outputs[0], go.inputs[0])
    mod = ob.modifiers.new('Scatter', 'NODES')
    mod.node_group = ng
    return ob


