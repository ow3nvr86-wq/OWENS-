def seated_bm(top='suit', hat=None, right_arm=True):
    """A seated passenger, front +y (car forward). Slots: 0 top, 1 skin, 2 hair/hat."""
    bm = bmesh.new()
    add_cyl(bm, 0.18, 0.2, 0.55, seg=10, matrix=Matrix.Translation((0, 0, 0.3)) @ Matrix.Diagonal((1, 0.62, 1, 1)))
    add_sphere(bm, 0.2, 10, 6, matrix=Matrix.Translation((0, 0, 0.56)) @ Matrix.Diagonal((1.1, 0.62, 0.38, 1)))
    add_cyl(bm, 0.05, 0.05, 0.1, seg=6, matrix=Matrix.Translation((0, 0, 0.66)), mi=1)
    add_sphere(bm, 0.105, 10, 8, matrix=Matrix.Translation((0, 0, 0.8)) @ Matrix.Diagonal((0.92, 1.0, 1.12, 1)), mi=1)
    add_sphere(bm, 0.11, 10, 8, matrix=Matrix.Translation((0, -0.015, 0.835)) @ Matrix.Diagonal((0.96, 1.0, 0.85, 1)), mi=2)
    if hat == 'pillbox':
        add_cyl(bm, 0.085, 0.085, 0.07, seg=12, matrix=Matrix.Translation((0, -0.01, 0.93)), mi=0)
    elif hat == 'stetson':
        add_cyl(bm, 0.2, 0.2, 0.015, seg=14, matrix=Matrix.Translation((0, 0, 0.9)), mi=2)
        add_cyl(bm, 0.11, 0.1, 0.12, seg=10, matrix=Matrix.Translation((0, 0, 0.96)), mi=2)
    for sx in (-1, 1):
        sh = Vector((sx * 0.22, 0, 0.52))
        hand = Vector((sx * 0.2, 0.3, 0.18))
        if sx < 0 or right_arm:
            add_cyl(bm, 0.05, 0.04, (hand - sh).length, seg=6, matrix=seg_matrix(sh, hand))
        add_cyl(bm, 0.07, 0.06, 0.45, seg=6, matrix=seg_matrix(Vector((sx * 0.1, 0, 0.02)), Vector((sx * 0.1, 0.45, 0.02))))
    return bm


