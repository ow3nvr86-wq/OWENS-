def area_light(name, loc, rot, sx, sy, energy, color, collection):
    ld = bpy.data.lights.new(name, 'AREA')
    ld.shape = 'RECTANGLE'
    ld.size, ld.size_y = sx, sy
    ld.energy = energy
    ld.color = color
    lo = bpy.data.objects.new(name, ld)
    lo.location = loc
    lo.rotation_euler = rot
    coll(collection).objects.link(lo)
    return lo


def spot_light(name, loc, target, energy, angle, color, collection, blend=0.5, radius=0.05):
    ld = bpy.data.lights.new(name, 'SPOT')
    ld.energy = energy
    ld.spot_size = math.radians(angle)
    ld.spot_blend = blend
    ld.color = color
    ld.shadow_soft_size = radius
    lo = bpy.data.objects.new(name, ld)
    lo.location = loc
    d = (Vector(target) - Vector(loc)).normalized()
    lo.rotation_euler = d.to_track_quat('-Z', 'Y').to_euler()
    coll(collection).objects.link(lo)
    return lo

