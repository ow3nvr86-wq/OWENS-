def build_downtown():
    """Blocks east of Houston St: street frontages of 1910s-1950s commercial buildings and a few towers."""
    rng = random.Random(7)
    xb = [7.0] + [x + 6.0 for x in XSTREETS]
    xe = [x - 6.0 for x in XSTREETS] + [960.0]
    bands = [(13.0, 40.0, 'main'), (42.0, 73.0, 'elm'), (-40.0, -13.0, 'main'), (-73.0, -42.0, 'comm'), (88.0, 140.0, 'n'), (-140.0, -88.0, 's')]
    k = 0
    for bi, (a, b) in enumerate(zip(xb, xe)):
        for y0, y1, kind in bands:
            if bi == 0 and abs(y0) < 120:
                continue                                    # the corner block at Houston is built by hand
            x = a
            while x < b - 6:
                w = min(rng.uniform(14, 36), b - x)
                tall = rng.random()
                if kind == 'main':
                    h = rng.uniform(12, 34) if tall < 0.75 else rng.uniform(45, 95)
                elif tall < 0.12:
                    h = rng.uniform(70, 125)
                else:
                    h = rng.uniform(14, 48)
                mat = 'tower' if h > 60 else 'facade'
                bldg(f'B{k:03d}', x, y0, x + w - 0.4, y1, h, mat=mat)
                if kind == 'main' and rng.random() < 0.7:
                    shopsign(k, x + w / 2, y0 if y0 > 0 else y1, w, rng)
                x += w
                k += 1


