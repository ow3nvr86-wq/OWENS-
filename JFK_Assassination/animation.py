def update_archive(t, shot):
    # the House committee's report slides in beside the Warren report
    a, b = EV['hsca_slide']
    u = smooth((t - a) / (b - a)) if shot != 'archive' else 0.0
    m = ARCH['hsca_rest']
    off = Vector((0.9 * (1 - u), 0.15 * (1 - u), 0))
    ARCH['hsca'].matrix_world = Matrix.Translation(off) @ m @ Matrix.Rotation(0.5 * (1 - u), 4, 'Z')
    ARCH['hsca'].hide_render = shot == 'archive' or t < a
    # released pages slide into frame one by one and stack; release stamps land on top
    d0 = EV['docs'][0]
    for k in range(6):
        ob = ARCH[f'doc{k}']
        if shot != 'files':
            ob.hide_render = True
            continue
        ta = d0 + k * 0.62
        u = smooth((t - ta) / 0.55)
        p1, r1 = doc_rest(k)
        ang = (k * 2.4) % 6.28
        p0 = p1 + Vector((math.cos(ang) * 0.6, math.sin(ang) * 0.6, 0.02))
        p = p0.lerp(p1, u)
        rot = r1 + (1 - u) * (0.9 if k % 2 else -0.9)
        ob.matrix_world = Matrix.Translation(p) @ Matrix.Rotation(rot, 4, 'Z')
        ob.hide_render = t < ta
    for nm, k in (('stamp_2025', 3), ('stamp_2026', 5)):
        ob = ARCH[nm]
        ts = EV[nm][0]
        if shot != 'files' or t < ts:
            ob.hide_render = True
            continue
        ob.hide_render = False
        u = min((t - ts) / 0.18, 1.0)
        sc = 1.0 + 1.6 * (1 - u) ** 2
        p, r = doc_rest(k)
        ob.matrix_world = Matrix.Translation(p + Vector((0.01, 0.05 if nm == 'stamp_2025' else -0.06, 0.004 + 0.06 * (1 - u)))) @ \
            Matrix.Rotation(r + (0.12 if nm == 'stamp_2025' else -0.1), 4, 'Z') @ Matrix.Diagonal((sc, sc, sc, 1))


def torus(bm, R, r, nu=36, nv=10):
    verts = []
    for i in range(nu):
        a = i / nu * 2 * math.pi
        row = []
        for j in range(nv):
            b = j / nv * 2 * math.pi
            row.append(bm.verts.new(((R + r * math.cos(b)) * math.cos(a), (R + r * math.cos(b)) * math.sin(a), r * math.sin(b))))
        verts.append(row)
    for i in range(nu):
        for j in range(nv):
            bm.faces.new((verts[i][j], verts[(i + 1) % nu][j], verts[(i + 1) % nu][(j + 1) % nv], verts[i][(j + 1) % nv]))


