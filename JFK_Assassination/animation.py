    sc = rng.uniform(0.92, 1.06, n) * np.where(rng.random(n) < 0.06, 0.7, 1.0)
    rot = np.stack([np.zeros(n), np.zeros(n), np.array(R)], -1)
    crowd_scatter('Crowd', P, variant, rot, np.repeat(sc[:, None], 3, 1), rng.random(n), rng.uniform(0, 6.28, n), T, 'Crowd')
    print('crowd:', n)


