def crowd_scatter(name, pts, variant, rot, scale, tint, phase, inst_coll, collection):
    """GN instancing with motion: wavers alternate between two arm poses; everyone shifts slightly."""
    n = len(pts)
    me = bpy.data.meshes.new(name)
    me.vertices.add(n)
    me.vertices.foreach_set('co', np.asarray(pts, np.float32).ravel())
    wav = np.isin(variant, WAVERS).astype(np.float32)
    for an, arr, typ in (('variant', variant, 'INT'), ('rot', rot, 'FLOAT_VECTOR'), ('scl', scale, 'FLOAT_VECTOR'),
                         ('tint', tint, 'FLOAT'), ('phase', phase, 'FLOAT'), ('waver', wav, 'FLOAT')):
        a = me.attributes.new(an, typ, 'POINT')
        a.data.foreach_set('value' if typ in ('INT', 'FLOAT') else 'vector',
                           np.asarray(arr).ravel().astype(np.int32 if typ == 'INT' else np.float32))
    ob = bpy.data.objects.new(name, me)
    coll(collection).objects.link(ob)
    ng = bpy.data.node_groups.new(name + '_GN', 'GeometryNodeTree')
    ng.interface.new_socket('Geometry', in_out='INPUT', socket_type='NodeSocketGeometry')
    ng.interface.new_socket('Geometry', in_out='OUTPUT', socket_type='NodeSocketGeometry')
    N, Lk = ng.nodes, ng.links
    gi, go = N.new('NodeGroupInput'), N.new('NodeGroupOutput')
    ci = N.new('GeometryNodeCollectionInfo')
    ci.inputs['Collection'].default_value = inst_coll
    ci.inputs['Separate Children'].default_value = True
    ci.inputs['Reset Children'].default_value = True
    iop = N.new('GeometryNodeInstanceOnPoints')
    iop.inputs['Pick Instance'].default_value = True

    def named(nm, dt):
        x = N.new('GeometryNodeInputNamedAttribute')
        x.data_type = dt
        x.inputs['Name'].default_value = nm
        return x.outputs['Attribute']

    def m(op, a, b):
        x = N.new('ShaderNodeMath')
        x.operation = op
        for i, v in enumerate((a, b)):
            if v is None:
                continue
            if isinstance(v, bpy.types.NodeSocket):
                Lk.new(v, x.inputs[i])
            else:
                x.inputs[i].default_value = v
        return x.outputs[0]
    st = N.new('GeometryNodeInputSceneTime').outputs['Seconds']
    ph = named('phase', 'FLOAT')
    tog = m('GREATER_THAN', m('SINE', m('ADD', m('MULTIPLY', st, 9.0), ph), None), 0.0)
    idx = m('ADD', named('variant', 'INT'), m('MULTIPLY', tog, named('waver', 'FLOAT')))
    Lk.new(gi.outputs[0], iop.inputs['Points'])
    Lk.new(ci.outputs[0], iop.inputs['Instance'])
    Lk.new(idx, iop.inputs['Instance Index'])
    Lk.new(named('rot', 'FLOAT_VECTOR'), iop.inputs['Rotation'])
    Lk.new(named('scl', 'FLOAT_VECTOR'), iop.inputs['Scale'])
    tr = N.new('GeometryNodeTranslateInstances')
    cx = N.new('ShaderNodeCombineXYZ')
    Lk.new(m('MULTIPLY', m('SINE', m('ADD', m('MULTIPLY', st, 1.3), m('MULTIPLY', ph, 2.0)), None), 0.04), cx.inputs[0])
    Lk.new(m('MULTIPLY', m('SINE', m('ADD', m('MULTIPLY', st, 4.0), ph), None), 0.012), cx.inputs[2])
    Lk.new(iop.outputs[0], tr.inputs['Instances'])
    Lk.new(cx.outputs[0], tr.inputs['Translation'])
    Lk.new(tr.outputs[0], go.inputs[0])
    mod = ob.modifiers.new('Crowd', 'NODES')
    mod.node_group = ng
    return ob


