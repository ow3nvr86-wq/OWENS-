def tree_bm(seed):
    rng = random.Random(seed)
    bm = bmesh.new()
    h = rng.uniform(3.0, 4.2)
    add_cyl(bm, 0.28, 0.2, h, seg=8, matrix=Matrix.Translation((0, 0, h / 2)))
    for k in range(3):
        a = k * 2.1 + rng.uniform(-0.3, 0.3)
        p0 = Vector((0, 0, h * 0.8))
        p1 = p0 + Vector((math.cos(a) * 2.6, math.sin(a) * 2.6, 1.4))
        add_cyl(bm, 0.14, 0.09, (p1 - p0).length, seg=6, matrix=seg_matrix(p0, p1))
    res = []
    for k in range(9):
        a = rng.uniform(0, 2 * math.pi)
        r = rng.uniform(0.5, 3.6)
        c = Vector((math.cos(a) * r, math.sin(a) * r, h + rng.uniform(0.6, 2.4)))
        rad = rng.uniform(1.6, 2.6)
        before = set(bm.verts)
        bmesh.ops.create_icosphere(bm, subdivisions=2, radius=rad, matrix=Matrix.Translation(c) @ Matrix.Diagonal((1.2, 1.2, 0.72, 1)))
        new = [v for v in bm.verts if v not in before]
        for v in new:
            v.co += (v.co - c).normalized() * rng.uniform(-0.25, 0.25)
        res += new
    _set_mi(bm, res, 1)
    return bm


