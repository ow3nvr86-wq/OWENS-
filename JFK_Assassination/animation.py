def facade_mat(name, palette, floor_h=3.8, bay=3.0, win=(0.22, 0.78, 0.26, 0.80), ground=4.6, shop=True, lit=0.22, pair=False):
    """Procedural facade for axis-aligned boxes: storeys of windows (dark glass, some with pale blinds),
    a shop-front band at street level, colour picked per building from a period palette.
    Night: a random share of windows glow (value 'win_lum')."""
    m, nt, out = new_mat(name)
    oi = nd(nt, 'ShaderNodeObjectInfo')
    oc = nd(nt, 'ShaderNodeTexCoord').outputs['Object']
    geo = nd(nt, 'ShaderNodeNewGeometry')
    s = sep(nt, oc)
    h = mth(nt, 'ADD', s.outputs['X'], s.outputs['Y'])
    z = s.outputs['Z']
    col = ramp_node(nt, oi.outputs['Random'], palette)
    grime = noise(nt, 0.35, 3.0, 0.6, vec=oc)
    streak = noise(nt, 0.08, 2.0, 0.5, vec=comb(nt, mth(nt, 'MULTIPLY', h, 4.0), 0.0, mth(nt, 'MULTIPLY', z, 0.25)))
    wall = mixc(nt, mth(nt, 'MULTIPLY', mth(nt, 'ADD', mth(nt, 'MULTIPLY', grime, 0.5), mth(nt, 'MULTIPLY', streak, 0.4)), 0.5),
                col, (0.10, 0.09, 0.08, 1))
    fu = mth(nt, 'FRACT', mth(nt, 'DIVIDE', h, bay))
    fz = mth(nt, 'FRACT', mth(nt, 'DIVIDE', mth(nt, 'SUBTRACT', z, ground), floor_h))
    inu = mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', fu, win[0]), mth(nt, 'LESS_THAN', fu, win[1]))
    if pair:
        inu = mth(nt, 'MULTIPLY', inu, mth(nt, 'GREATER_THAN', mth(nt, 'ABSOLUTE', mth(nt, 'SUBTRACT', fu, 0.5)), 0.05))
    inz = mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', fz, win[2]), mth(nt, 'LESS_THAN', fz, win[3]))
    vert = mth(nt, 'LESS_THAN', mth(nt, 'ABSOLUTE', sep(nt, geo.outputs['Normal']).outputs['Z']), 0.5)
    upper = mth(nt, 'GREATER_THAN', z, ground + 0.4)
    wmask = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', inu, inz), mth(nt, 'MULTIPLY', vert, upper))
    cell = comb(nt, mth(nt, 'FLOOR', mth(nt, 'DIVIDE', h, bay)), mth(nt, 'FLOOR', mth(nt, 'DIVIDE', z, floor_h)), mth(nt, 'MULTIPLY', oi.outputs['Random'], 53.0))
    wn = nd(nt, 'ShaderNodeTexWhiteNoise', p_noise_dimensions='3D', Vector=cell)
    blind = mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', wn.outputs['Value'], 0.62), mth(nt, 'GREATER_THAN', fz, 0.5))
    glass = mixc(nt, blind, (0.035, 0.045, 0.06, 1), (0.42, 0.40, 0.34, 1))
    c1 = mixc(nt, wmask, wall, glass)
    rough = mth(nt, 'SUBTRACT', 0.88, mth(nt, 'MULTIPLY', wmask, mth(nt, 'SUBTRACT', 0.76, mth(nt, 'MULTIPLY', blind, 0.6))))
    if shop:
        band = mth(nt, 'MULTIPLY', mth(nt, 'MULTIPLY', mth(nt, 'GREATER_THAN', z, 0.45), mth(nt, 'LESS_THAN', z, 3.3)), vert)
        mull = mth(nt, 'LESS_THAN', mth(nt, 'FRACT', mth(nt, 'DIVIDE', h, 2.2)), 0.06)
        shopc = mixc(nt, mull, (0.03, 0.035, 0.04, 1), (0.12, 0.11, 0.10, 1))
        c1 = mixc(nt, band, c1, shopc)
        rough = mth(nt, 'SUBTRACT', rough, mth(nt, 'MULTIPLY', band, mth(nt, 'SUBTRACT', 1.0, mull)))
        rough = mth(nt, 'MAXIMUM', rough, 0.08)
    p = principled(nt, out, **{'Base Color': c1, 'Roughness': rough, 'Specular IOR Level': 0.45})
    litm = mth(nt, 'MULTIPLY', wmask, mth(nt, 'LESS_THAN', wn.outputs['Value'], lit))
    tint = ramp_node(nt, wn.outputs['Value'], [(0.0, (1.0, 0.62, 0.30)), (1.0, (1.0, 0.82, 0.55))])
    nt.links.new(tint, p.inputs['Emission Color'])
    nt.links.new(mth(nt, 'MULTIPLY', litm, value(nt, 'win_lum', 0.0)), p.inputs['Emission Strength'])
    MAT[name] = m
    register_value(m, 'win_lum', 'win_lum')
    return m


