"""THE JFK ASSASSINATION - DALLAS, NOVEMBER 22, 1963.
A fully code-generated, cinematic 3D YouTube Short (1080x1920, 30 fps, 60 s): President John F. Kennedy's
visit to Dallas, the motorcade, Dealey Plaza, the arrest of Lee Harvey Oswald, his death two days later,
the Warren Commission (1964), the House Select Committee on Assassinations (1979) and the records still
being released (2025, 2026).

Everything is generated by this Blender (bpy) script: a recreated Dallas of 1963 (Main Street with period
buildings, shop signs and crowds along the kerbs; Dealey Plaza with the Texas School Book Depository, the
Elm Street curve, the pergolas, the fence on the slope and the triple underpass; drifting clouds), the
motorcade (police motorcycles, the open dark-blue presidential limousine with its flags, follow-up cars,
a press bus), the 1963 front pages on a dark table, a police investigation room (desk, lamp, typewriter,
blinds and haze, a timeline board, a console TV), a records archive with light shafts, Dealey Plaza at
night in fog, all lighting, cameras and depth of field, the compositor grade, the synthesised music and
sound design, the edit (titles, captions, transitions, film grain) and the MP4 encode. The paper props are
drawn by tools/textures.py.

Respect and accuracy: the shooting, injuries and any weapon are never shown; the motorcade is seen at a
distance and its occupants are faceless mannequins; Oswald is represented by a silhouette card with verified
facts, not a likeness. Investigations reached different conclusions and both are stated as such. See
sources.txt.

Run with Blender 4.2 LTS (headless):
  blender -b --factory-startup -P animation.py -- [options]

Stages (default: render):
  --stage render   build the 3D scene and render frames to renders/frames/
  --stage audio    synthesise music + sound design, mix with the narration (audio/*.wav, sound_design.txt)
  --stage edit     assemble frames, titles, captions, grain and audio in the Video Sequencer and
                   encode final_video.mp4
  --stage all      render + audio + edit

Options:
  --quality preview|final         preview = 270x480, 4 samples; final = 540x960, 6 samples (upscaled 2x in the edit)
  --frames A-B                    render only this frame range (resumable: existing frames are kept)
  --stills F1,F2,...              render single frames (look-dev checks)
  --out DIR                       frame folder (default renders/frames)
  --no-voice                      edit stage: leave the narration and captions out (for CapCut)
  --output NAME                   edit stage: output file name
  --bitrate KBPS                  edit stage: video bitrate
  --save-blend PATH               also save the generated .blend

Timing comes from scene_timing.json (and build/vo_timing.json once tools/voiceover.py has run).
"""
